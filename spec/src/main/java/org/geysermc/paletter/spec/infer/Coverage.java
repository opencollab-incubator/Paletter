package org.geysermc.paletter.spec.infer;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import org.geysermc.paletter.spec.Fixtures;
import org.geysermc.paletter.spec.model.Model;
import org.geysermc.paletter.spec.model.Model.Component;
import org.geysermc.paletter.spec.model.Model.FormatNote;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;

/** {@code codegen/model/coverage.md}: what the docs describe, what BDS accepts and sends, what was inferred. */
final class Coverage {
    private final Model model;
    private final Fixtures fixtures;
    private final JsonObject transforms;
    private final Map<String, JsonObject> results = new LinkedHashMap<>();

    Coverage(Model model, Fixtures fixtures, JsonObject transforms) {
        this.model = model;
        this.fixtures = fixtures;
        this.transforms = transforms;
    }

    void add(Component component, JsonObject result) {
        results.put(component.id(), result);
    }

    private Map<String, Integer> componentCounts() {
        Map<String, Integer> counts = new LinkedHashMap<>();
        for (Component c : model.components()) {
            counts.merge("documented", 1, Integer::sum);
            JsonObject r = results.get(c.id());
            String status = r == null ? "not tested" : r.get("status").getAsString();
            counts.merge(status, 1, Integer::sum);
            if (r != null && (status.equals("sent") || status.equals("server-only"))) {
                counts.merge("accepted by BDS", 1, Integer::sum);
            }
        }
        return counts;
    }

    /** Field statuses, docs fields and errata fields apart. */
    private Map<String, Map<String, Integer>> fieldCounts() {
        Map<String, Map<String, Integer>> counts = new LinkedHashMap<>();
        counts.put("docs", new TreeMap<>());
        counts.put("errata", new TreeMap<>());
        for (Component c : model.components()) {
            JsonObject r = results.get(c.id());
            for (Model.Field f : c.fields()) {
                String origin = f.doc().startsWith("(erratum)") ? "errata" : "docs";
                Map<String, Integer> map = counts.get(origin);
                map.merge("documented", 1, Integer::sum);
                String status = "not-generated";
                if (r != null && r.has("fields") && r.getAsJsonObject("fields").has(f.path())) {
                    status = r.getAsJsonObject("fields").getAsJsonObject(f.path()).get("status").getAsString();
                } else if (r != null) {
                    status = r.get("status").getAsString().equals("rejected") ? "rejected" : "not-generated";
                }
                map.merge(status, 1, Integer::sum);
                if (List.of("inferred", "partial", "unresolved", "hand-rule", "dropped", "no-evidence").contains(status)) {
                    map.merge("accepted by BDS", 1, Integer::sum);
                }
                if (List.of("inferred", "partial", "unresolved", "hand-rule").contains(status)) {
                    map.merge("sent on wire", 1, Integer::sum);
                }
            }
        }
        return counts;
    }

    String summary() {
        return "components " + componentCounts() + "\nfields " + fieldCounts();
    }

    String markdown(List<MappingInference.Capture> captures) {
        StringBuilder md = new StringBuilder();
        md.append("# Component model coverage\n\n");
        md.append("Generated by `./gradlew :spec:inferMappings` from `components.json` (docs commit `").append(model.commit())
            .append("`), `fixtures.json`, `transforms.json` and the captures:\n\n");
        for (MappingInference.Capture capture : captures) {
            long accepted = capture.variants().stream().filter(v -> capture.wire().containsKey(v.identifier())).count();
            md.append("- `").append(capture.name()).append("`: BDS ").append(capture.bdsVersion()).append(", protocol ").append(capture.protocol())
                .append(", ").append(capture.variants().size()).append(" variants (").append(accepted).append(" accepted, ")
                .append(capture.variants().size() - accepted).append(" rejected)\n");
        }
        md.append("\n## Components\n\n| | count |\n|---|---|\n");
        componentCounts().forEach((k, v) -> md.append("| ").append(k).append(" | ").append(v).append(" |\n"));
        md.append("\n`sent`: the component changes the wire; `server-only`: accepted, nothing on the wire; `rejected`: BDS rejects every "
            + "variant; `untestable`: its companions were rejected.\n\n## Fields\n\n");
        Map<String, Map<String, Integer>> fields = fieldCounts();
        TreeSet<String> statuses = new TreeSet<>();
        fields.values().forEach(m -> statuses.addAll(m.keySet()));
        md.append("| status | docs fields | errata fields |\n|---|---|---|\n");
        for (String s : List.of("documented", "accepted by BDS", "sent on wire", "inferred", "partial", "unresolved", "hand-rule",
            "dropped", "rejected", "no-evidence", "not-generated")) {
            md.append("| ").append(s).append(" | ").append(fields.get("docs").getOrDefault(s, 0)).append(" | ")
                .append(fields.get("errata").getOrDefault(s, 0)).append(" |\n");
        }
        md.append("""

            `inferred`: every wire leaf the field moves is explained by an automatic rule; `partial`: some are; `unresolved`: none is
            (needs a hand rule); `hand-rule`: unresolved or partial and named in `transforms.json`; `dropped`: BDS accepts the
            field but nothing on the wire follows it (server only); `rejected`: every variant setting it was rejected;
            `no-evidence`: only values equal to the base were accepted; `not-generated`: skipped (see `fixtures.json`).

            """);
        // Rule kinds and tags
        Map<String, Integer> kinds = new TreeMap<>();
        Map<String, Integer> tags = new TreeMap<>();
        for (JsonObject r : results.values()) {
            if (!r.has("fields")) {
                continue;
            }
            for (Map.Entry<String, JsonElement> f : r.getAsJsonObject("fields").entrySet()) {
                JsonObject field = f.getValue().getAsJsonObject();
                if (field.has("rules")) {
                    for (JsonElement rule : field.getAsJsonArray("rules")) {
                        kinds.merge(rule.getAsJsonObject().get("kind").getAsString(), 1, Integer::sum);
                        rule.getAsJsonObject().getAsJsonArray("tags").forEach(t -> tags.merge(t.getAsString().replaceAll(":.*", ":*"), 1, Integer::sum));
                    }
                }
            }
        }
        md.append("## Inferred rules (field -> wire leaf)\n\n| kind | rules |\n|---|---|\n");
        kinds.forEach((k, v) -> md.append("| ").append(k).append(" | ").append(v).append(" |\n"));
        md.append("\n| tag | rules |\n|---|---|\n");
        tags.forEach((k, v) -> md.append("| ").append(k).append(" | ").append(v).append(" |\n"));
        // Per component
        md.append("\n## Per component\n\n| component | docs status | BDS | wire | fields: inferred / partial / unresolved+hand / dropped / rejected / total |\n|---|---|---|---|---|\n");
        for (Component c : model.components()) {
            JsonObject r = results.get(c.id());
            String status = r == null ? (fixtures.skip(c.id(), null) != null ? "skipped" : "not tested") : r.get("status").getAsString();
            String wire = r == null || !r.has("wire") ? "" : String.join(", ", r.getAsJsonArray("wire").asList().stream().map(JsonElement::getAsString).toList());
            Map<String, Integer> f = new TreeMap<>();
            if (r != null && r.has("fields")) {
                r.getAsJsonObject("fields").entrySet().forEach(e -> f.merge(e.getValue().getAsJsonObject().get("status").getAsString(), 1, Integer::sum));
            }
            md.append("| `").append(c.id()).append("` | ").append(c.status()).append(c.experiments().isEmpty() ? "" : " (exp.)").append(" | ")
                .append(status).append(" | ").append(wire.length() > 80 ? wire.substring(0, 80) + "..." : wire).append(" | ")
                .append(f.getOrDefault("inferred", 0)).append(" / ").append(f.getOrDefault("partial", 0)).append(" / ")
                .append(f.getOrDefault("unresolved", 0) + f.getOrDefault("hand-rule", 0)).append(" / ").append(f.getOrDefault("dropped", 0))
                .append(" / ").append(f.getOrDefault("rejected", 0)).append(" / ").append(c.fields().size()).append(" |\n");
        }
        // Fields needing a hand rule
        md.append("\n## Fields that need a hand rule\n\n");
        int n = 0;
        for (Map.Entry<String, JsonObject> r : results.entrySet()) {
            for (String section : List.of("fields", "forms")) {
                if (!r.getValue().has(section)) {
                    continue;
                }
                for (Map.Entry<String, JsonElement> f : r.getValue().getAsJsonObject(section).entrySet()) {
                    String status = f.getValue().getAsJsonObject().get("status").getAsString();
                    if (List.of("unresolved", "partial", "hand-rule").contains(status)) {
                        n++;
                        JsonObject field = f.getValue().getAsJsonObject();
                        md.append("- `").append(r.getKey()).append("` ").append(section.equals("forms") ? "form " : "").append("`")
                            .append(f.getKey().isEmpty() ? "(value)" : f.getKey()).append("`: ").append(status);
                        if (field.has("transform")) {
                            md.append(" -> `").append(field.getAsJsonObject("transform").get("transform").getAsString()).append("`");
                        }
                        if (field.has("unexplained")) {
                            md.append(" (unexplained: ").append(String.join(", ", field.getAsJsonArray("unexplained").asList().stream()
                                .map(u -> "`" + Wire.generic(u.getAsJsonObject().get("wire").getAsString()) + "`").distinct().toList())).append(")");
                        }
                        md.append('\n');
                    }
                }
            }
        }
        if (n == 0) {
            md.append("None.\n");
        }
        // Docs vs BDS
        md.append("\n## Docs vs BDS\n\nFields BDS reports as \"not present in the Schema\" (docs describe them, BDS ").append(fixtures.formatVersion)
            .append(" does not take them):\n\n");
        List<String> unknown = new ArrayList<>();
        List<String> ranges = new ArrayList<>();
        for (Component c : model.components()) {
            JsonObject r = results.get(c.id());
            if (r == null || !r.has("fields")) {
                continue;
            }
            for (Model.Field f : c.fields()) {
                JsonObject field = r.getAsJsonObject("fields").getAsJsonObject(f.path());
                if (field == null) {
                    continue;
                }
                if (field.has("unknownToBds") && !field.get("status").getAsString().matches("inferred|dropped|partial|hand-rule|unresolved")) {
                    unknown.add("`" + c.id() + "` `" + f.path() + "`");
                }
                if (field.has("bdsRange")) {
                    String docs = f.range() == null ? "none" : "[" + f.range().min() + ", " + f.range().max() + "]";
                    ranges.add("| `" + c.id() + "` | `" + f.path() + "` | " + docs + " | " + field.get("bdsRange") + " |");
                }
            }
        }
        unknown.forEach(u -> md.append("- ").append(u).append('\n'));
        if (unknown.isEmpty()) {
            md.append("None.\n");
        }
        md.append("\nNumeric ranges BDS enforces (content log \"accepted range\") vs the docs:\n\n| component | field | docs | BDS |\n|---|---|---|---|\n");
        ranges.forEach(r -> md.append(r).append('\n'));
        // Format versions
        TreeSet<String> versions = new TreeSet<>((a, b) -> key(a).compareTo(key(b)));
        model.formatNotes().forEach(note -> versions.add(note.version()));
        model.components().forEach(c -> {
            if (c.minFormatVersion() != null) {
                versions.add(c.minFormatVersion());
            }
            c.fields().forEach(f -> {
                if (f.minFormatVersion() != null) {
                    versions.add(f.minFormatVersion());
                }
            });
        });
        md.append("\n## Format versions in the docs\n\n").append(versions.size()).append(" distinct versions are named (minimum format "
            + "versions of components and fields, behaviour changes): ").append(String.join(", ", versions)).append(".\n\n");
        Map<String, Integer> minimums = new TreeMap<>((a, b) -> key(a).compareTo(key(b)));
        model.components().forEach(c -> {
            if (c.minFormatVersion() != null) {
                minimums.merge(c.minFormatVersion(), 1, Integer::sum);
            }
        });
        md.append("Components by minimum format version: ");
        List<String> parts = new ArrayList<>();
        minimums.forEach((k, v) -> parts.add(k + " (" + v + ")"));
        md.append(String.join(", ", parts)).append(".\n\nStatements that change behaviour or shape at a format version:\n\n");
        for (FormatNote note : model.formatNotes()) {
            String text = note.text().toLowerCase(java.util.Locale.ROOT);
            if (text.contains("requires a format version of at least")) {
                continue;
            }
            md.append("- ").append(note.version()).append(" `").append(note.component()).append("`: ")
                .append(note.text().length() > 220 ? note.text().substring(0, 220) + "..." : note.text()).append('\n');
        }
        if (!captures.isEmpty() && !captures.getFirst().unattributed().isEmpty()) {
            md.append("\n## Content log lines without a variant\n\n");
            captures.getFirst().unattributed().stream().distinct().limit(20).forEach(l -> md.append("- `").append(l.replace("`", "'")).append("`\n"));
        }
        return md.toString();
    }

    private static String key(String version) {
        StringBuilder key = new StringBuilder();
        for (String part : version.split("\\.")) {
            key.append(String.format("%06d", part.matches("\\d+") ? Integer.parseInt(part) : 999999));
        }
        return key.toString();
    }
}
