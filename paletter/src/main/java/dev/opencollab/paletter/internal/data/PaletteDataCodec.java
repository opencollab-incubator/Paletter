/**
 * The bundled data format: one gzipped big endian NBT compound per version. Written by the generator, read at runtime.
 * <pre>
 * format: int                      {@value #FORMAT}
 * name: string, protocol: int      the data version
 * blocks: [{name, states}]         optional: vanilla block states in runtime id order. Without it (every bundled version),
 *                                  the states and defaults are those of the generated block definitions of the version
 *                                  ({@code VanillaBlocks}); the writer leaves out what those give
 * blocks_digest: {states, hash}    without blocks: the digest of the palette the file was written with ({@link #digest});
 *                                  reading fails unless the derived palette has it
 * items: [{name, id, version, component_based}]
 *                                  (the item components and the data driven blocks are in properties.nbt, see PropertyStore)
 * creative: {construction|nature|equipment|items: [node]}
 *     node: {group: name, icon?: stack, stacks: [stack]} or a stack
 *     stack: {id, damage?, count?, block?: {name, states}, nbt?}
 * item_tags: {tag: [identifier]}
 * fallbacks: {blocks: {name: {target, clear_states, force}}, items: {name: {target, force}}, unmapped: [name]}
 *                                  optional, and not part of the bundled data (consumers define fallbacks);
 *                                  custom data sources may carry it
 * block_defaults: {name: states}   optional, only with blocks: the defaults that are not the first state of their block
 * experiments: {toggle: {items: [name], blocks: [name], creative: [id or id:damage], creative_without_block?: [name]}}
 *                                  optional; only written when the version was captured with experiments.
 *                                  creative_without_block: the items of the toggle's stacks BDS sends without a block
 * block_items: {block: item}       optional: the item that places each block. With blocks_without_item only the blocks
 *                                  whose item has another identifier (or that are not in the palette)
 * blocks_without_item: [block]     optional: the blocks of the palette no item places; with it, every other block of the
 *                                  palette is placed by the item of its own identifier
 * </pre>
 */
@Internal
public final class PaletteDataCodec {
    /** Root key of every bundled data file that says who wrote it; readers ignore it, tests check it. */
    public static final String GENERATED_KEY = "_generated";
    /** Its value: bundled files are output of the tools, never edited by hand. */
    public static final String GENERATED = "Generated by the Paletter tools (:tools:run import / update, ./gradlew :tools:run --args=\"update ...\") "
        + "from the BDS captures under data/bds; do not edit by hand.";
    /** 2: the block states optional (with a digest when left out), the block to item relation without identities. */
    public static final int FORMAT = 2;

    private PaletteDataCodec() {
    }

    /**
     * Reads the root compound of a gzipped NBT file and closes the stream. The inflated side is buffered: the NBT reader
     * reads one primitive at a time, and without a buffer each of those is its own {@code Inflater} call
     * ({@code NbtUtils.createGZIPReader} has none).
     */
    public static @NonNull NbtMap readGzip(@NonNull InputStream stream) throws IOException {
        try (NBTInputStream input = NbtUtils.createReader(new BufferedInputStream(new GZIPInputStream(stream, 8192), 1 << 16))) {
            return (NbtMap) input.readTag();
        }
    }

    /** Reads data, checking the digest of a file without block states against the derived palette. */
    public static @NonNull VanillaData read(@NonNull InputStream stream) throws IOException {
        return read(stream, true);
    }

    /**
     * @param checkDigest whether to check the digest of a file without block states against the derived palette: off only
     *                    for the files bundled with the library, which the build checks ({@code checkBlocks}, tests), as
     *                    hashing every state again costs a cold load about 60 ms
     */
    public static @NonNull VanillaData read(@NonNull InputStream stream, boolean checkDigest) throws IOException {
        NbtMap root = readGzip(stream);
        int format = root.getInt("format", -1);
        if (format != FORMAT) {
            throw new IOException("Unsupported Paletter data format " + format + ", expected " + FORMAT);
        }
        DataVersion version = new DataVersion(root.getString("name"), root.getInt("protocol"));

        // States repeat a lot between blocks (e.g. every log has the same pillar_axis compound); share instances
        Map<NbtMap, NbtMap> interner = new HashMap<>();
        List<NbtMap> blocks = new ArrayList<>();
        Map<String, NbtMap> defaults = new HashMap<>();
        if (root.containsKey("blocks")) {
            for (NbtMap block : root.getList("blocks", NbtType.COMPOUND)) {
                NbtMap states = interner.computeIfAbsent(block.getCompound("states"), PaletteDataCodec::internStrings);
                blocks.add(BlockStates.of(block.getString("name").intern(), states));
            }
            root.getCompound("block_defaults", NbtMap.EMPTY).forEach((name, states) ->
                defaults.put(name, BlockStates.of(name.intern(), interner.computeIfAbsent((NbtMap) states, PaletteDataCodec::internStrings))));
        } else {
            // The block states of a bundled version are generated code, not data
            BlockDefinitions.Palette palette = VanillaBlocks.palette(version.name());
            if (palette == null) {
                List<String> generated = VanillaBlocks.versions();
                throw new IOException("The data of " + version.name() + " has no block states, and the library has no generated block "
                    + "definitions of it" + (generated.isEmpty() ? ": it has none at all (the class " + VanillaBlocks.DATA
                    + " is missing from the class path, e.g. dropped by a tool that minimises the jar)" : " (it has " + generated + ")"));
            }
            NbtMap digest = root.getCompound("blocks_digest", null);
            if (digest == null) {
                throw new IOException("The data of " + version.name() + " has neither block states nor the digest of the palette it was written with");
            }
            NbtMap derived = checkDigest ? digest(palette.states(), palette.defaults()) : digest;
            if (!derived.equals(digest)) {
                throw new IOException("The block states the library derives for " + version.name() + " (" + derived + ") are not the ones its data "
                    + "file was written with (" + digest + "): the generated block definitions and the data are of different palettes");
            }
            blocks = palette.states();
            defaults.putAll(palette.defaults());
            // The creative stacks share the palette's instances, as they share those of a file
            blocks.forEach(state -> interner.putIfAbsent(BlockStates.states(state), BlockStates.states(state)));
        }

        List<VanillaItem> items = new ArrayList<>();
        for (NbtMap item : root.getList("items", NbtType.COMPOUND)) {
            items.add(new VanillaItem(item.getString("name"), item.getInt("id"), item.getInt("version"),
                item.getBoolean("component_based"), null));
        }

        Map<CreativeCategory, List<RawNode>> categories = new EnumMap<>(CreativeCategory.class);
        NbtMap creative = root.getCompound("creative", NbtMap.EMPTY);
        for (CreativeCategory category : CreativeCategory.values()) {
            List<RawNode> nodes = new ArrayList<>();
            for (NbtMap node : creative.getList(category.bedrockName(), NbtType.COMPOUND, List.of())) {
                if (node.containsKey("group")) {
                    NbtMap icon = node.getCompound("icon", null);
                    List<RawStack> stacks = new ArrayList<>();
                    for (NbtMap stack : node.getList("stacks", NbtType.COMPOUND)) {
                        stacks.add(readStack(stack, interner));
                    }
                    nodes.add(new RawGroup(node.getString("group"), icon == null ? null : readStack(icon, interner), stacks));
                } else {
                    nodes.add(readStack(node, interner));
                }
            }
            categories.put(category, nodes);
        }

        Map<String, List<String>> tags = new LinkedHashMap<>();
        root.getCompound("item_tags", NbtMap.EMPTY).forEach((tag, list) -> {
            List<String> identifiers = new ArrayList<>();
            for (Object identifier : (List<?>) list) {
                identifiers.add((String) identifier);
            }
            tags.put(tag, identifiers);
        });

        NbtMap fallbacksNbt = root.getCompound("fallbacks", NbtMap.EMPTY);
        Map<String, BlockFallback> blockFallbacks = new HashMap<>();
        fallbacksNbt.getCompound("blocks", NbtMap.EMPTY).forEach((name, value) -> {
            NbtMap fallback = (NbtMap) value;
            BedrockBlockType target = BedrockBlockType.fromIdentifier(fallback.getString("target"));
            blockFallbacks.put(name, new BlockFallback(target, fallback.getBoolean("clear_states") ? target.defaultState() : null,
                fallback.getBoolean("force")));
        });
        Map<String, ItemFallback> itemFallbacks = new HashMap<>();
        fallbacksNbt.getCompound("items", NbtMap.EMPTY).forEach((name, value) -> {
            NbtMap fallback = (NbtMap) value;
            // Bundled data names the target type only: the base variant, aux 0
            BedrockItemType target = BedrockItemType.fromIdentifier(fallback.getString("target"));
            itemFallbacks.put(name, new ItemFallback(target, target.variant(), fallback.getBoolean("force")));
        });
        Set<String> unmapped = new HashSet<>(fallbacksNbt.getList("unmapped", NbtType.STRING, List.of()));

        Map<String, ExperimentContent> experiments = new HashMap<>();
        root.getCompound("experiments", NbtMap.EMPTY).forEach((toggle, value) -> {
            NbtMap content = (NbtMap) value;
            experiments.put(toggle, new ExperimentContent(content.getList("items", NbtType.STRING, List.of()),
                content.getList("blocks", NbtType.STRING, List.of()), content.getList("creative", NbtType.STRING, List.of()),
                content.getList("creative_without_block", NbtType.STRING, List.of())));
        });

        Map<String, String> blockItems = new HashMap<>();
        root.getCompound("block_items", NbtMap.EMPTY).forEach((block, item) -> blockItems.put(block, (String) item));
        if (root.containsKey("blocks_without_item")) {
            // Every other block is placed by the item of its own identifier
            Set<String> without = new HashSet<>(root.getList("blocks_without_item", NbtType.STRING));
            for (NbtMap state : blocks) {
                String name = BlockStates.name(state);
                if (!without.contains(name)) {
                    blockItems.putIfAbsent(name, name);
                }
            }
        }

        return new VanillaData(version, blocks, items, List.of(), RawLayout.of(categories), tags,
            new VersionFallbacks(blockFallbacks, itemFallbacks, unmapped), defaults, experiments, blockItems);
    }

    /**
     * Writes the data, without the block states and defaults where they are what the generated block definitions of the
     * version give ({@link VanillaBlocks}). Maps are written sorted by key, so the same data always produces the same bytes.
     */
    public static void write(@NonNull VanillaData data, @NonNull OutputStream stream) throws IOException {
        write(data, stream, !derivable(data));
    }

    /** @return whether the block states and defaults of the data are what the generated definitions of its version give */
    public static boolean derivable(@NonNull VanillaData data) {
        BlockDefinitions.Palette palette = VanillaBlocks.palette(data.version().name());
        return palette != null && palette.states().equals(data.blockStates())
            && exceptions(data.blockStates(), data.blockDefaults()).equals(palette.defaults());
    }

    /** @return the defaults that are not the first state of their block: a default that is says what no default says */
    private static Map<String, NbtMap> exceptions(List<NbtMap> states, Map<String, NbtMap> defaults) {
        Map<String, NbtMap> result = new HashMap<>(defaults);
        Map<String, NbtMap> first = new HashMap<>();
        states.forEach(state -> first.putIfAbsent(BlockStates.name(state), state));
        result.entrySet().removeIf(entry -> entry.getValue().equals(first.get(entry.getKey())));
        return result;
    }

    /**
     * The digest a file without block states stores of the palette it was written with, and that reading checks the
     * derived palette against: {@code {states: count, hash: FNV-1a 64}} over the hashed id of every state in order, then
     * the identifier and hashed id of every default that is not the first state of its block, by identifier.
     */
    public static @NonNull NbtMap digest(@NonNull List<NbtMap> states, @NonNull Map<String, NbtMap> defaults) {
        long hash = 0xcbf29ce484222325L;
        for (NbtMap state : states) {
            hash = fnv(hash, dev.opencollab.paletter.block.BlockHashes.hash(state));
        }
        for (Map.Entry<String, NbtMap> entry : new TreeMap<>(exceptions(states, defaults)).entrySet()) {
            for (byte b : entry.getKey().getBytes(java.nio.charset.StandardCharsets.UTF_8)) {
                hash = (hash ^ (b & 0xff)) * 0x100000001b3L;
            }
            hash = fnv(hash, dev.opencollab.paletter.block.BlockHashes.hash(entry.getValue()));
        }
        return NbtMap.builder().putInt("states", states.size()).putLong("hash", hash).build();
    }

    private static long fnv(long hash, int value) {
        for (int shift = 0; shift < 32; shift += 8) {
            hash = (hash ^ ((value >>> shift) & 0xff)) * 0x100000001b3L;
        }
        return hash;
    }

    /**
     * Writes the data. Maps are written sorted by key, so the same data always produces the same bytes.
     *
     * @param blocks whether to write the block states and defaults; without them, reading takes those of the generated
     *               definitions of the version
     */
    public static void write(@NonNull VanillaData data, @NonNull OutputStream stream, boolean blocks) throws IOException {
        NbtMapBuilder root = NbtMap.builder()
            .putString(GENERATED_KEY, GENERATED)
            .putInt("format", FORMAT)
            .putString("name", data.version().name())
            .putInt("protocol", data.version().protocolVersion());

        if (!blocks) {
            root.putCompound("blocks_digest", digest(data.blockStates(), data.blockDefaults()));
        }
        if (blocks) {
            root.putList("blocks", NbtType.COMPOUND, data.blockStates());
        }

        List<NbtMap> items = new ArrayList<>(data.items().size());
        for (VanillaItem item : data.items()) {
            items.add(NbtMap.builder()
                .putString("name", item.identifier())
                .putInt("id", item.runtimeId())
                .putInt("version", item.version())
                .putBoolean("component_based", item.componentBased())
                .build());
        }
        root.putList("items", NbtType.COMPOUND, items);

        NbtMapBuilder creative = NbtMap.builder();
        for (CreativeCategory category : CreativeCategory.values()) {
            List<NbtMap> nodes = new ArrayList<>();
            for (RawNode node : data.creative().nodes(category)) {
                switch (node) {
                    case RawStack stack -> nodes.add(writeStack(stack));
                    case RawGroup group -> {
                        NbtMapBuilder builder = NbtMap.builder().putString("group", group.name());
                        if (group.icon() != null) {
                            builder.putCompound("icon", writeStack(group.icon()));
                        }
                        builder.putList("stacks", NbtType.COMPOUND, group.stacks().stream().map(PaletteDataCodec::writeStack).toList());
                        nodes.add(builder.build());
                    }
                }
            }
            creative.putList(category.bedrockName(), NbtType.COMPOUND, nodes);
        }
        root.putCompound("creative", creative.build());

        NbtMapBuilder tags = NbtMap.builder();
        new TreeMap<>(data.itemTags()).forEach((tag, identifiers) -> tags.putList(tag, NbtType.STRING, identifiers));
        root.putCompound("item_tags", tags.build());

        // Bundled data has no fallbacks (consumers define them); only data that carries some writes them
        if (!data.fallbacks().blocks().isEmpty() || !data.fallbacks().items().isEmpty() || !data.fallbacks().unmapped().isEmpty()) {
            writeFallbacks(data, root);
        }

        if (blocks) {
            NbtMapBuilder defaults = NbtMap.builder();
            new TreeMap<>(data.blockDefaults()).forEach((name, state) -> defaults.putCompound(name, BlockStates.states(state)));
            root.putCompound("block_defaults", defaults.build());
        }

        writeRest(data, root);

        try (NBTOutputStream output = NbtUtils.createGZIPWriter(stream)) {
            output.writeTag(root.build());
        }
    }

    private static void writeFallbacks(VanillaData data, NbtMapBuilder root) {
        NbtMapBuilder blockFallbacks = NbtMap.builder();
        new TreeMap<>(data.fallbacks().blocks()).forEach((name, fallback) -> blockFallbacks.putCompound(name, NbtMap.builder()
            .putString("target", fallback.target().identifier())
            .putBoolean("clear_states", fallback.state() != null)
            .putBoolean("force", fallback.force())
            .build()));
        NbtMapBuilder itemFallbacks = NbtMap.builder();
        new TreeMap<>(data.fallbacks().items()).forEach((name, fallback) -> itemFallbacks.putCompound(name, NbtMap.builder()
            .putString("target", fallback.target().identifier())
            .putBoolean("force", fallback.force())
            .build()));
        root.putCompound("fallbacks", NbtMap.builder()
            .putCompound("blocks", blockFallbacks.build())
            .putCompound("items", itemFallbacks.build())
            .putList("unmapped", NbtType.STRING, new ArrayList<>(new TreeSet<>(data.fallbacks().unmapped())))
            .build());
    }

    private static void writeRest(VanillaData data, NbtMapBuilder root) {
        // Only when present, so versions captured without experiments keep their bytes
        if (!data.experiments().isEmpty()) {
            NbtMapBuilder experiments = NbtMap.builder();
            new TreeMap<>(data.experiments()).forEach((toggle, content) -> {
                NbtMapBuilder entry = NbtMap.builder()
                    .putList("items", NbtType.STRING, new ArrayList<>(new TreeSet<>(content.items())))
                    .putList("blocks", NbtType.STRING, new ArrayList<>(new TreeSet<>(content.blocks())))
                    .putList("creative", NbtType.STRING, new ArrayList<>(new TreeSet<>(content.creative())));
                // Only when present, so content without such items keeps its bytes
                if (!content.creativeWithoutBlock().isEmpty()) {
                    entry.putList("creative_without_block", NbtType.STRING, new ArrayList<>(new TreeSet<>(content.creativeWithoutBlock())));
                }
                experiments.putCompound(toggle, entry.build());
            });
            root.putCompound("experiments", experiments.build());
        }

        if (!data.blockItems().isEmpty()) {
            // Only what the palette does not give: a block of the palette is placed by the item of its own identifier
            // unless it is listed with another item or as having none
            Set<String> palette = new TreeSet<>();
            data.blockStates().forEach(state -> palette.add(BlockStates.name(state)));
            NbtMapBuilder blockItems = NbtMap.builder();
            new TreeMap<>(data.blockItems()).forEach((block, item) -> {
                if (!item.equals(block) || !palette.contains(block)) {
                    blockItems.putString(block, item);
                }
            });
            root.putCompound("block_items", blockItems.build());
            List<String> without = palette.stream().filter(block -> !data.blockItems().containsKey(block)).toList();
            root.putList("blocks_without_item", NbtType.STRING, new ArrayList<>(without));
        }
    }

    /** The keys and string values of the states of a block repeat in thousands of states: one String instance of each. */
    private static NbtMap internStrings(NbtMap states) {
        NbtMapBuilder builder = NbtMap.builder();
        states.forEach((key, value) -> builder.put(key.intern(), value instanceof String text ? text.intern() : value));
        return builder.build();
    }

    private static RawStack readStack(NbtMap nbt, Map<NbtMap, NbtMap> interner) {
        NbtMap block = nbt.getCompound("block", null);
        if (block != null) {
            block = BlockStates.of(block.getString("name").intern(), interner.computeIfAbsent(block.getCompound("states"), PaletteDataCodec::internStrings));
        }
        return new RawStack(nbt.getString("id"), nbt.getInt("damage", 0), nbt.getInt("count", 1), block, nbt.getCompound("nbt", null));
    }

    private static NbtMap writeStack(RawStack stack) {
        NbtMapBuilder builder = NbtMap.builder().putString("id", stack.identifier());
        if (stack.damage() != 0) {
            builder.putInt("damage", stack.damage());
        }
        if (stack.count() != 1) {
            builder.putInt("count", stack.count());
        }
        if (stack.blockState() != null) {
            builder.putCompound("block", stack.blockState());
        }
        if (stack.tag() != null) {
            builder.putCompound("nbt", stack.tag());
        }
        return builder.build();
    }
}
