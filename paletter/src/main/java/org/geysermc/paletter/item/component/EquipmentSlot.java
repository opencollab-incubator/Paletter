package org.geysermc.paletter.item.component;

/**
 * Where a wearable item is worn (add-on JSON {@code minecraft:wearable.slot}).
 *
 * @since 2.0.0
 */
public enum EquipmentSlot {
    HEAD,
    CHEST,
    LEGS,
    FEET,
    /**
     * The body armour slot of animals (horses, wolves).
     */
    BODY,
    OFFHAND
}
