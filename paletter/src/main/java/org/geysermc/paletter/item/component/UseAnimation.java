package org.geysermc.paletter.item.component;

/**
 * The animation the player plays while using an item (add-on JSON {@code minecraft:use_animation}).
 *
 * @since 2.0.0
 */
public enum UseAnimation {
    NONE,
    EAT,
    DRINK,
    BLOCK,
    BOW,
    /**
     * The trident and spear animation.
     */
    SPEAR,
    CROSSBOW,
    SPYGLASS,
    BRUSH
}
