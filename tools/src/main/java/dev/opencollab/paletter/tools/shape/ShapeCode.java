package dev.opencollab.paletter.tools.shape;

import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.CodeBlock;
import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.ParameterizedTypeName;
import com.palantir.javapoet.TypeSpec;
import dev.opencollab.paletter.internal.shape.VoxelGrid;
import dev.opencollab.paletter.internal.shape.VoxelShapeList;
import dev.opencollab.paletter.internal.shape.VoxelShapeStore;
import dev.opencollab.paletter.tools.codegen.Chunks;

import javax.lang.model.element.Modifier;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;

/**
 * Writes the vanilla voxel shapes ({@code internal.vanilla.shapes}) with JavaPoet: every distinct shape once as a constant
 * of its boxes ({@code VoxelShapeTable}: {@code ANVIL} for a shape BDS names, {@code BOX_0_0_0_16_8_16} for one box on
 * whole pixels, else {@code SHAPE_} and the first block it is made for, the boxes in pixels in its Javadoc), each
 * registry as its shapes in id order ({@code VoxelShapes26_40}), and {@code VoxelShapeData}, which the bundled data source
 * calls. A shape whose boxes do not give its grid again fails.
 */
final class ShapeCode {
    static final String PACKAGE = "dev.opencollab.paletter.internal.vanilla.shapes";
    static final String DIRECTORY = "paletter/src/generated/java/" + PACKAGE.replace('.', '/');
    /** How the first line of every generated file starts: also how stale files are recognised. */
    static final String GENERATOR = "// Generated by `voxel-shapes import`";
    /** The most floats of boxes in one class of constants: its static initializer stays far below 64 KB. */
    static final int CLASS_FLOATS = 3000;
    private static final ClassName GRID = ClassName.get(VoxelGrid.class);
    private static final ClassName LIST = ClassName.get(VoxelShapeList.class);
    private static final ClassName STORE = ClassName.get(VoxelShapeStore.class);
    private static final ClassName REGISTRY = STORE.nestedClass("Registry");

    private ShapeCode() {
    }

    /** @return the files of a store by path from the repository root */
    static Map<String, String> generate(VoxelShapeStore store) {
        Map<VoxelGrid, float[]> boxes = new LinkedHashMap<>();
        Map<VoxelGrid, String> names = new LinkedHashMap<>();
        java.util.Set<String> taken = new java.util.HashSet<>();
        for (VoxelShapeStore.Registry registry : store.registries()) {
            for (VoxelShapeStore.Entry entry : registry.shapes()) {
                if (entry.name() == null && entry.block() == null) {
                    throw new IllegalStateException("A shape of " + registry.versions() + " has neither a name nor a block");
                }
                if (!names.containsKey(entry.grid())) {
                    float[] merged = boxes(entry.grid());
                    boxes.put(entry.grid(), merged);
                    String name = name(entry, merged);
                    String unique = name;
                    for (int i = 2; !taken.add(unique); i++) {
                        unique = name + "_" + i;
                    }
                    names.put(entry.grid(), unique);
                }
            }
        }
        List<TypeSpec> types = new ArrayList<>();
        TypeSpec.Builder table = null;
        int floats = 0;
        int tables = 0;
        for (Map.Entry<VoxelGrid, float[]> shape : boxes.entrySet()) {
            if (table == null || floats + shape.getValue().length > CLASS_FLOATS) {
                if (table != null) {
                    types.add(table.build());
                }
                tables++;
                table = TypeSpec.classBuilder(tables == 1 ? "VoxelShapeTable" : "VoxelShapeTablePart" + tables).addModifiers(Modifier.FINAL)
                    .addJavadoc("The vanilla voxel shapes of every registry, each once" + (tables == 1 ? "" : " (continued)") + ".\n")
                    .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
                floats = 0;
            }
            floats += shape.getValue().length;
            table.addField(FieldSpec.builder(GRID, names.get(shape.getKey()), Modifier.STATIC, Modifier.FINAL)
                .addJavadoc("$L (in pixels).\n", pixels(shape.getValue()))
                .initializer("$T.ofBoxes($L)", GRID, floatList(shape.getValue())).build());
        }
        if (table != null) {
            types.add(table.build());
        }
        MethodSpec.Builder load = MethodSpec.methodBuilder("load").addModifiers(Modifier.PUBLIC, Modifier.STATIC).returns(STORE)
            .addJavadoc("@return the vanilla voxel shape registries of every bundled version, built now\n")
            .addStatement("$T registries = new $T<>()", ParameterizedTypeName.get(ClassName.get(List.class), REGISTRY), ArrayList.class);
        Map<String, Integer> classNames = new TreeMap<>();
        for (VoxelShapeStore.Registry registry : store.registries()) {
            String base = "VoxelShapes" + registry.versions().getFirst().replaceAll("[^A-Za-z0-9]", "_") + (registry.experiment() ? "Experiment" : "");
            int count = classNames.merge(base, 1, Integer::sum);
            String name = count == 1 ? base : base + "_" + count;
            List<CodeBlock> statements = new ArrayList<>();
            for (VoxelShapeStore.Entry entry : registry.shapes()) {
                String constant = names.get(entry.grid());
                if (entry.name() != null) {
                    statements.add(CodeBlock.builder().addStatement("s.named($S, $N)", entry.name(), constant).build());
                } else if (entry.block() == null) {
                    throw new IllegalStateException("A shape of " + registry.versions() + " has neither a name nor a block");
                } else if (entry.block().equals(entry.lastBlock())) {
                    statements.add(CodeBlock.builder().addStatement("s.block($N, $S)", constant, entry.block()).build());
                } else {
                    statements.add(CodeBlock.builder().addStatement("s.block($N, $S, $S)", constant, entry.block(), entry.lastBlock()).build());
                }
            }
            types.addAll(Chunks.chunked(name, "The vanilla voxel shapes of " + String.join(", ", registry.versions())
                + (registry.experiment() ? " with the experiment " + VoxelShapeStore.EXPERIMENT : "") + ", in id order.", statements, LIST, "s"));
            String list = Character.toLowerCase(name.charAt(0)) + name.substring(1);
            load.addStatement("$T $N = new $T()", LIST, list, LIST).addStatement("$N.load($N)", name, list);
            load.addStatement("registries.add(new $T($T.of($L), $L, $N.entries()))", REGISTRY, List.class,
                CodeBlock.join(registry.versions().stream().map(v -> CodeBlock.of("$S", v)).toList(), ", "), registry.experiment(), list);
        }
        load.addStatement("return new $T(registries)", STORE);
        types.add(TypeSpec.classBuilder("VoxelShapeData").addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("The vanilla voxel shape registries the captures in data/bds give: what the bundled data source serves.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build()).addMethod(load.build()).build());
        Map<String, String> files = new TreeMap<>();
        String header = GENERATOR.substring(3) + " (:tools:run) from data/bds/*/voxel-shapes.\nDo not edit; see docs/data-pipeline.md.";
        for (TypeSpec type : types) {
            JavaFile.Builder file = JavaFile.builder(PACKAGE, type).addFileComment(header).indent("    ").skipJavaLangImports(true);
            // The registries name the shapes by their constants alone
            if (type.name().startsWith("VoxelShapes")) {
                for (int i = 1; i <= tables; i++) {
                    file.addStaticImport(ClassName.get(PACKAGE, i == 1 ? "VoxelShapeTable" : "VoxelShapeTablePart" + i), "*");
                }
            }
            files.put(DIRECTORY + "/" + type.name() + ".java", file.build().toString());
        }
        return files;
    }

    private static String name(VoxelShapeStore.Entry entry, float[] boxes) {
        if (entry.name() != null) {
            return constant(entry.name().replaceFirst("^minecraft:", ""));
        }
        if (boxes.length == 6) {
            StringBuilder name = new StringBuilder("BOX");
            for (float coordinate : boxes) {
                float pixels = coordinate * 16;
                if (pixels != Math.rint(pixels)) {
                    return "SHAPE_" + constant(entry.block().replaceFirst("^minecraft:", ""));
                }
                name.append('_').append((int) pixels);
            }
            return name.toString();
        }
        return "SHAPE_" + constant(entry.block().replaceFirst("^minecraft:", ""));
    }

    /** UPPER_SNAKE of a name; one that would be empty or start with a digit starts with {@code SHAPE_}. */
    static String constant(String name) {
        String constant = name.toUpperCase(Locale.ROOT).replaceAll("[^A-Z0-9]+", "_").replaceAll("^_|_$", "");
        return constant.isEmpty() || Character.isDigit(constant.charAt(0)) ? "SHAPE_" + constant : constant;
    }

    /**
     * The grid as few boxes as a greedy merge of its cells gives (along z, then y, then x), checked: the boxes must give
     * the grid again.
     */
    static float[] boxes(VoxelGrid grid) {
        float[] x = grid.coordinates(0);
        float[] y = grid.coordinates(1);
        float[] z = grid.coordinates(2);
        int xs = x.length - 1;
        int ys = y.length - 1;
        int zs = z.length - 1;
        boolean[] cells = grid.cells();
        boolean[] taken = new boolean[cells.length];
        List<Float> boxes = new ArrayList<>();
        for (int i = 0; i < cells.length; i++) {
            if (!cells[i] || taken[i]) {
                continue;
            }
            int x0 = i / (ys * zs);
            int y0 = i / zs % ys;
            int z0 = i % zs;
            int z1 = z0 + 1;
            while (z1 < zs && free(cells, taken, x0, x0 + 1, y0, y0 + 1, z1, z1 + 1, ys, zs)) {
                z1++;
            }
            int y1 = y0 + 1;
            while (y1 < ys && free(cells, taken, x0, x0 + 1, y1, y1 + 1, z0, z1, ys, zs)) {
                y1++;
            }
            int x1 = x0 + 1;
            while (x1 < xs && free(cells, taken, x1, x1 + 1, y0, y1, z0, z1, ys, zs)) {
                x1++;
            }
            for (int a = x0; a < x1; a++) {
                for (int b = y0; b < y1; b++) {
                    for (int c = z0; c < z1; c++) {
                        taken[(a * ys + b) * zs + c] = true;
                    }
                }
            }
            for (float coordinate : new float[] {x[x0], y[y0], z[z0], x[x1], y[y1], z[z1]}) {
                boxes.add(coordinate);
            }
        }
        float[] result = new float[boxes.size()];
        for (int i = 0; i < result.length; i++) {
            result[i] = boxes.get(i);
        }
        if (!VoxelGrid.ofBoxes(result).equals(grid)) {
            throw new IllegalStateException("The shape " + grid + " is not the grid of its boxes (not minimal): the generated code cannot say it");
        }
        return result;
    }

    private static boolean free(boolean[] cells, boolean[] taken, int x0, int x1, int y0, int y1, int z0, int z1, int ys, int zs) {
        for (int a = x0; a < x1; a++) {
            for (int b = y0; b < y1; b++) {
                for (int c = z0; c < z1; c++) {
                    int i = (a * ys + b) * zs + c;
                    if (!cells[i] || taken[i]) {
                        return false;
                    }
                }
            }
        }
        return true;
    }

    private static CodeBlock floatList(float[] values) {
        List<CodeBlock> list = new ArrayList<>();
        for (float value : values) {
            list.add(CodeBlock.of("$Lf", Float.toString(value)));
        }
        return CodeBlock.join(list, ", ");
    }

    private static String pixels(float[] boxes) {
        if (boxes.length == 0) {
            return "No boxes";
        }
        List<String> out = new ArrayList<>();
        for (int at = 0; at < boxes.length; at += 6) {
            List<String> box = new ArrayList<>();
            for (int i = 0; i < 6; i++) {
                float pixels = boxes[at + i] * 16;
                box.add(pixels == Math.rint(pixels) ? Integer.toString((int) pixels) : Float.toString(pixels));
            }
            out.add("[" + String.join(", ", box) + "]");
        }
        return String.join(", ", out);
    }
}
