package dev.opencollab.paletter.tools.codegen.constants;

import dev.opencollab.paletter.tools.data.Importer;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * The blocks and items of the Bedrock release before the oldest bundled one: constants of them are older than any bundled
 * data says, so they get no {@code First in Bedrock} line. The file is {@code data/model/baseline-<release>.txt}, one
 * {@code blocks <identifier>} or {@code items <identifier>} per line, written by the {@code baseline} command from a
 * CloudburstMC/Data checkout (so that it can be reproduced) and not edited by hand.
 */
public final class Baseline {
    /** The committed baseline: the release before 26.30, the oldest bundled one. */
    public static final String FILE = "data/model/baseline-26.20.txt";
    static final Baseline NONE = new Baseline(Set.of(), Set.of());

    private final Set<String> blocks;
    private final Set<String> items;

    private Baseline(Set<String> blocks, Set<String> items) {
        this.blocks = blocks;
        this.items = items;
    }

    boolean has(String kind, String identifier) {
        return (kind.equals("blocks") ? blocks : items).contains(identifier);
    }

    /** @return the baseline a file holds ({@code #} lines are comments) */
    public static Baseline read(Path file) throws IOException {
        Set<String> blocks = new HashSet<>();
        Set<String> items = new HashSet<>();
        for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
            line = line.strip();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            String[] parts = line.split("\s+");
            if (parts.length != 2 || !(parts[0].equals("blocks") || parts[0].equals("items"))) {
                throw new IllegalStateException(file + ": expected `blocks|items <identifier>`, got `" + line + "`");
            }
            (parts[0].equals("blocks") ? blocks : items).add(parts[1]);
        }
        return new Baseline(blocks, items);
    }

    /**
     * Writes the baseline of a CloudburstMC/Data checkout.
     *
     * @param source the checkout, at the commit of the release before the oldest bundled one
     * @param name the release's name, e.g. {@code 26.20}
     * @param commit the CloudburstMC/Data commit the checkout is at
     */
    public static void write(Path source, String name, String commit, Path out) throws IOException {
        Map<String, List<String>> identifiers = Importer.identifiers(source, name);
        List<String> lines = new ArrayList<>(List.of(
            "# Block and item identifiers of Bedrock " + name + ", the release before the oldest bundled one.",
            "# Generated by `baseline` (:tools:run) from CloudburstMC/Data commit " + commit + " (" + name + "); do not edit by hand.",
            "# Source: https://github.com/CloudburstMC/Data, Apache License 2.0, Copyright CloudburstMC; only the identifiers are kept.",
            "# The constants generator gives no `First in Bedrock` line to content listed here that the oldest bundled release has."));
        for (String kind : List.of("blocks", "items")) {
            identifiers.get(kind).forEach(identifier -> lines.add(kind + " " + identifier));
        }
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.write(out, lines, StandardCharsets.UTF_8);
    }
}
