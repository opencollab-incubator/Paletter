package dev.opencollab.paletter.tools.blocks;

import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.CodeBlock;
import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.TypeSpec;
import dev.opencollab.paletter.internal.vanilla.BlockDefinition;
import dev.opencollab.paletter.internal.vanilla.BlockDefinitions;
import dev.opencollab.paletter.internal.vanilla.StateValues;
import dev.opencollab.paletter.internal.vanilla.VanillaBlocks;
import dev.opencollab.paletter.tools.codegen.Chunks;

import javax.lang.model.element.Modifier;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Writes the generated vanilla block definitions ({@code internal.vanilla.blocks}) with JavaPoet: the shared value lists
 * ({@code BlockValues}), the oldest version block by block ({@code BlockBase}), each newer version as its changes
 * ({@code BlockChanges26_40}), each change with the capture it comes from, and {@code BlockData}, which
 * {@code VanillaBlocks} calls to build them. No lambdas; long lists are split ({@link Chunks}).
 */
final class BlockCode {
    static final String PACKAGE = "dev.opencollab.paletter.internal.vanilla.blocks";
    static final String DIRECTORY = "paletter/src/generated/java/" + PACKAGE.replace('.', '/');
    /** How the first line of every generated file starts: also how stale files are recognised. */
    static final String GENERATOR = "// Generated by :tools:generateBlocks";
    private static final ClassName VALUES = ClassName.get(PACKAGE, "BlockValues");
    private static final ClassName DEFINITIONS = ClassName.get(BlockDefinitions.class);
    private static final ClassName STATE_VALUES = ClassName.get(StateValues.class);

    private BlockCode() {
    }

    /**
     * @param versions the definitions of each version, oldest first
     * @param captures what each version was imported from, named in the comments ({@code BDS 1.26.52.3})
     * @param input what the files say they were generated from
     * @return the files by path from the repository root
     */
    static Map<String, String> generate(Map<String, BlockDefinitions> versions, Map<String, String> captures, String input) {
        if (versions.isEmpty()) {
            throw new IllegalArgumentException("No versions to generate");
        }
        List<StateValues> lists = new ArrayList<>();
        versions.values().forEach(definitions -> definitions.blocks().forEach(block -> lists.addAll(block.properties())));
        Map<StateValues, String> names = BlockNames.of(lists);
        List<TypeSpec> types = new ArrayList<>();
        types.add(values(names));
        MethodSpec.Builder load = MethodSpec.methodBuilder("load").addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .addParameter(ClassName.get(VanillaBlocks.Versions.class), "versions");
        String before = null;
        for (Map.Entry<String, BlockDefinitions> version : versions.entrySet()) {
            String name = version.getKey();
            String capture = captures.getOrDefault(name, "no BDS capture in data/bds");
            String suffix = name.replaceAll("[^A-Za-z0-9]", "_");
            String type;
            List<CodeBlock> statements = new ArrayList<>();
            if (before == null) {
                type = "BlockBase";
                for (BlockDefinition block : BlockModel.sorted(version.getValue())) {
                    statements.add(define("v.block", block, names));
                }
                types.addAll(Chunks.chunked(type, "The vanilla blocks of " + name + ", the oldest generated version, imported from " + capture
                    + ": each block with its properties, the slowest changing first, and its default state where that is not the first.",
                    statements, DEFINITIONS, "v"));
            } else {
                type = "BlockChanges" + suffix;
                for (BlockDiff.Op op : BlockDiff.diff(name, versions.get(before), version.getValue())) {
                    statements.add(change(op, capture, names));
                }
                types.addAll(Chunks.chunked(type, "What changed in the vanilla blocks of " + name + " against " + before
                    + ", each change with the capture it comes from. A position counts in a block's property order, 0 the slowest changing.",
                    statements, DEFINITIONS, "v"));
            }
            load.addStatement("$T v$L = versions.version($S)", DEFINITIONS, suffix, name);
            load.addStatement("$N.load(v$L)", type, suffix);
            before = name;
        }
        types.add(TypeSpec.classBuilder("BlockData").addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("The vanilla block definitions of every generated version: what {@code VanillaBlocks} derives the block states of a "
                + "version from.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build()).addMethod(load.build()).build());
        Map<String, String> files = new TreeMap<>();
        String header = GENERATOR.substring(3) + " from " + input + ".\nDo not edit; see docs/data-pipeline.md.";
        for (TypeSpec type : types) {
            JavaFile.Builder file = JavaFile.builder(PACKAGE, type).addFileComment(header).indent("    ").skipJavaLangImports(true);
            if (type.name().startsWith("BlockBase") || type.name().startsWith("BlockChanges")) {
                file.addStaticImport(VALUES, "*");
            }
            files.put(DIRECTORY + "/" + type.name() + ".java", file.build().toString());
        }
        return files;
    }

    private static TypeSpec values(Map<StateValues, String> names) {
        TypeSpec.Builder type = TypeSpec.classBuilder(VALUES).addModifiers(Modifier.FINAL)
            .addJavadoc("The value lists of the block properties of every generated version, each once, the values in Bedrock's order.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
        names.forEach((values, name) -> type.addField(FieldSpec.builder(STATE_VALUES, name, Modifier.STATIC, Modifier.FINAL)
            .initializer(initializer(values)).build()));
        return type.build();
    }

    private static CodeBlock initializer(StateValues values) {
        List<Object> list = values.values();
        if (list.getFirst() instanceof Byte) {
            return CodeBlock.of("$T.bool($S)", STATE_VALUES, values.name());
        }
        if (list.getFirst() instanceof Integer first) {
            boolean run = true;
            for (int i = 1; i < list.size(); i++) {
                run &= (Integer) list.get(i) == first + i;
            }
            return run ? CodeBlock.of("$T.ints($S, $L, $L)", STATE_VALUES, values.name(), first, list.getLast())
                : CodeBlock.of("$T.intList($S, $L)", STATE_VALUES, values.name(), CodeBlock.join(list.stream().map(v -> CodeBlock.of("$L", v)).toList(), ", "));
        }
        return CodeBlock.of("$T.strings($S, $L)", STATE_VALUES, values.name(),
            CodeBlock.join(list.stream().map(v -> CodeBlock.of("$S", v)).toList(), ", "));
    }

    /** {@code v.block("id", A, B).defaultState(...)}, or {@code v.redefine(...)}. */
    private static CodeBlock define(String call, BlockDefinition block, Map<StateValues, String> names) {
        CodeBlock.Builder code = CodeBlock.builder().add("$L($S", call, block.identifier());
        for (StateValues property : block.properties()) {
            code.add(", $N", names.get(property));
        }
        code.add(")");
        if (block.defaultState() != 0) {
            code.add(".defaultState($L)", literals(BlockDiff.defaultValues(block)));
        }
        return CodeBlock.builder().addStatement(code.build()).build();
    }

    private static CodeBlock literals(Object[] values) {
        List<CodeBlock> literals = new ArrayList<>();
        for (Object value : values) {
            literals.add(switch (value) {
                case Byte b -> CodeBlock.of("$L", b != 0);
                case String s -> CodeBlock.of("$S", s);
                default -> CodeBlock.of("$L", value);
            });
        }
        return CodeBlock.join(literals, ", ");
    }

    private static CodeBlock change(BlockDiff.Op op, String capture, Map<StateValues, String> names) {
        CodeBlock.Builder code = CodeBlock.builder();
        switch (op) {
            case BlockDiff.Add add -> code.add("// new: $L\n", capture).add(define("v.block", add.definition(), names));
            case BlockDiff.Remove remove -> code.add("// removed: $L\n", capture).addStatement("v.remove($S)", remove.block());
            case BlockDiff.AddProperties add -> {
                CodeBlock.Builder call = CodeBlock.builder().add("v.addProperties($S, $L", add.block(), add.position());
                add.properties().forEach(p -> call.add(", $N", names.get(p)));
                code.add("// gains $L at position $L of its order: $L\n", safe(String.join(", ", add.properties().stream().map(StateValues::name).toList())),
                    add.position(), capture).addStatement(call.add(")").build());
            }
            case BlockDiff.RemoveProperty remove -> code.add("// loses $L: $L\n", safe(remove.property()), capture)
                .addStatement("v.removeProperty($S, $S)", remove.block(), remove.property());
            case BlockDiff.Redefine redefine -> code.add("// $L: $L\n", safe(redefine.why()), capture)
                .add(define("v.redefine", redefine.definition(), names));
            case BlockDiff.Default change -> code.add("// default state $L -> $L: $L\n", safe(java.util.Arrays.toString(change.before())),
                    safe(java.util.Arrays.toString(change.values())), capture)
                .addStatement("v.defaultState($S, $L)", change.block(), literals(change.values()));
        }
        return code.build();
    }

    /** Nothing in a comment that javac reads as code: characters outside printable ASCII and backslashes as {@code <U+XXXX>}. */
    static String safe(String text) {
        StringBuilder safe = new StringBuilder();
        text.codePoints().forEach(c -> {
            if (c >= 0x20 && c < 0x7f && c != '\\') {
                safe.appendCodePoint(c);
            } else {
                safe.append(String.format(java.util.Locale.ROOT, "<U+%04X>", c));
            }
        });
        return safe.toString();
    }
}
