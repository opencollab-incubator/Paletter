    /**
     * The files of the pack below its root, in the order they are written: {@code shapes/...} and {@code blocks/...}
     * to their JSON.
     */
    public static Map<String, JsonObject> files(String formatVersion) {
        Map<String, JsonObject> files = new LinkedHashMap<>();
        for (Map.Entry<String, List<Box>> variant : variants().entrySet()) {
            String name = variant.getKey();
            files.put("shapes/" + FILES.getOrDefault(name, name + ".json"), shapeFile(name, variant.getValue(), formatVersion));
            if (!NO_BLOCK.contains(name)) {
                files.put("blocks/shape_" + name + ".json", blockFile("shape_" + name, name, formatVersion));
            }
        }
        for (Map.Entry<String, String> block : blocks().entrySet()) {
            JsonObject root = new JsonObject();
            root.addProperty("format_version", formatVersion);
            root.add("minecraft:block", JsonParser.parseString(block.getValue()));
            files.put("blocks/" + block.getKey() + ".json", root);
        }
        return files;
    }

    /** Writes the behavior pack to {@code out}, replacing what is there. */
    public static void write(Path out, String formatVersion, String minEngine) throws IOException {
        BdsDistribution.deleteRecursively(out);
        Files.createDirectories(out.resolve("shapes"));
        Files.createDirectories(out.resolve("blocks"));
        Files.writeString(out.resolve("manifest.json"), MANIFEST.formatted("voxel shapes, varied", UUID, minEngine));
        for (Map.Entry<String, JsonObject> file : files(formatVersion).entrySet()) {
            Files.writeString(out.resolve(file.getKey()), GSON.toJson(file.getValue()) + "\n");
        }
    }

    /**
     * {@code addon-variants.json} of a capture: the files the pack had, one per line, so a capture is checked against
     * what its build was given.
     */
    public static String variantsJson(String bdsVersion, String formatVersion) {
        Gson compact = new GsonBuilder().disableHtmlEscaping().create();
        StringBuilder text = new StringBuilder("{\n");
        text.append("  \"_generated\": ").append(compact.toJson(ShapeProbe.GENERATED)).append(",\n");
        text.append("  \"bdsVersion\": ").append(compact.toJson(bdsVersion)).append(",\n");
        text.append("  \"files\": {");
        String separator = "\n";
        for (Map.Entry<String, JsonObject> file : files(formatVersion).entrySet()) {
            text.append(separator).append("    ").append(compact.toJson(file.getKey())).append(": ").append(compact.toJson(file.getValue()));
            separator = ",\n";
        }
        return text.append("\n  }\n}\n").toString();
    }

    /**
     * An anchor: a block whose name sorts (by {@link BlockRegistry#nameHash}, the order BDS walks the blocks in) just
     * before one vanilla block, with a shape of its own that no other block has.
     *
     * @param block the block name of the anchor, without the namespace
     * @param before the vanilla block that follows it, or null for the anchor after the last vanilla block
     * @param box the one box of its shape, which is named like the block
     */
    public record Anchor(String block, String before, Box box) {
    }

    /** How many names {@link #anchors} tries. */
    private static final int ANCHOR_CANDIDATES = 4_000_000;

    /**
     * An anchor before every vanilla block that a name can be found for, and one after the last. Their shapes differ in
     * width by 1/128 of a pixel, which no other shape uses, so the shapes BDS derives from them mark where in its walk
     * over the blocks it was.
     * <p>
     * Vanilla blocks whose names differ in their last characters only ({@code element_10}, {@code element_11}) have
     * hashes next to each other, and no name of another namespace is found between them: such a run of blocks gets one
     * anchor, before its first block.
     *
     * @param vanillaBlocks the names of the vanilla blocks
     */
    public static List<Anchor> anchors(Collection<String> vanillaBlocks) {
        List<String> sorted = new ArrayList<>(new TreeSet<>(vanillaBlocks));
        sorted.sort(Comparator.comparing(BlockRegistry::nameHash, Long::compareUnsigned));
        long[] hashes = sorted.stream().mapToLong(BlockRegistry::nameHash).toArray();
        String[] names = new String[hashes.length + 1];
        for (int candidate = 0; candidate < ANCHOR_CANDIDATES; candidate++) {
            // The number first: FNV-1 carries a byte into the high bits, which decide the order, only through the bytes after it
            String name = Integer.toString(candidate, 36) + "_anchor";
            long hash = BlockRegistry.nameHash(NAMESPACE + ":" + name);
            int low = 0;
            int high = hashes.length;
            while (low < high) {
                int middle = (low + high) >>> 1;
                if (Long.compareUnsigned(hashes[middle], hash) < 0) {
                    low = middle + 1;
                } else {
                    high = middle;
                }
            }
            if (names[low] == null) {
                names[low] = name;
            }
        }
        List<Anchor> anchors = new ArrayList<>();
        for (int gap = 0; gap < names.length; gap++) {
            if (names[gap] != null) {
                anchors.add(new Anchor(names[gap], gap < sorted.size() ? sorted.get(gap) : null, new Box(0, 0, 0, (2 * gap + 1) / 256f, 8, 8)));
            }
        }
        return anchors;
    }

    /** The files of the pack of the anchors, like {@link #files}: a shape and a block per anchor. */
    public static Map<String, JsonObject> anchorFiles(List<Anchor> anchors, String formatVersion) {
        Map<String, JsonObject> files = new LinkedHashMap<>();
        for (Anchor anchor : anchors) {
            files.put("shapes/" + anchor.block() + ".json", shapeFile(anchor.block(), List.of(anchor.box()), formatVersion));
            files.put("blocks/" + anchor.block() + ".json", blockFile(anchor.block(), anchor.block(), formatVersion));
        }
        return files;
    }

    /** Writes the behavior pack of the anchors to {@code out}, replacing what is there. */
    public static void writeAnchors(Path out, List<Anchor> anchors, String formatVersion, String minEngine) throws IOException {
        BdsDistribution.deleteRecursively(out);
        Files.createDirectories(out.resolve("shapes"));
        Files.createDirectories(out.resolve("blocks"));
        Files.writeString(out.resolve("manifest.json"), MANIFEST.formatted("anchors: one block before every vanilla block", UUID, minEngine));
        Gson compact = new Gson();
        for (Map.Entry<String, JsonObject> file : anchorFiles(anchors, formatVersion).entrySet()) {
            Files.writeString(out.resolve(file.getKey()), compact.toJson(file.getValue()));
        }
    }

    static JsonObject shapeFile(String name, List<Box> boxes, String formatVersion) {
        JsonArray array = new JsonArray();
        for (Box box : boxes) {
            JsonObject json = new JsonObject();
            json.add("min", vector(box.minX(), box.minY(), box.minZ()));
            json.add("max", vector(box.maxX(), box.maxY(), box.maxZ()));
            array.add(json);
        }
        JsonObject description = new JsonObject();
        description.addProperty("identifier", NAMESPACE + ":" + name);
        JsonObject shape = new JsonObject();
        shape.add("boxes", array);
        JsonObject body = new JsonObject();
        body.add("description", description);
        body.add("shape", shape);
        JsonObject root = new JsonObject();
        root.addProperty("format_version", formatVersion);
        root.add("minecraft:voxel_shape", body);
        return root;
    }

    private static JsonObject blockFile(String block, String shape, String formatVersion) {
        JsonObject description = new JsonObject();
        description.addProperty("identifier", NAMESPACE + ":" + block);
        JsonObject geometry = new JsonObject();
        geometry.addProperty("identifier", "geometry.paletter");
        geometry.addProperty("culling_shape", NAMESPACE + ":" + shape);
        JsonObject texture = new JsonObject();
        texture.addProperty("texture", "dirt");
        JsonObject materials = new JsonObject();
        materials.add("*", texture);
        JsonObject components = new JsonObject();
        components.add("minecraft:geometry", geometry);
        components.add("minecraft:material_instances", materials);
        JsonObject body = new JsonObject();
        body.add("description", description);
        body.add("components", components);
        JsonObject root = new JsonObject();
        root.addProperty("format_version", formatVersion);
        root.add("minecraft:block", body);
        return root;
    }

    private static JsonArray vector(float x, float y, float z) {
        JsonArray array = new JsonArray();
        for (float value : new float[] {x, y, z}) {
            // Whole numbers as integers, as add-ons write them
            if (value == Math.rint(value)) {
                array.add((int) value);
            } else {
                array.add(value);
            }
        }
        return array;
    }
