import org.cloudburstmc.protocol.bedrock.data.inventory.CreativeItemData;
import org.cloudburstmc.protocol.bedrock.data.inventory.CreativeItemGroup;
import org.cloudburstmc.protocol.bedrock.data.inventory.ItemData;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Base64;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

/**
 * Writes what a compiled {@link Palette} sends in the file formats of CloudburstMC/Data, and reads such a directory back
 * for {@link Diff#against}. The files are not byte-comparable with a cb/data checkout (gzip, key order, JSON layout, item
 * order): compare them with {@code verify --source <cb/data> --against <export>}.
 */
public final class Export {
    /** The marker file next to the data: NBT and JSON files cannot hold a comment. */
    public static final String MARKER = "_generated";

    private Export() {
    }

    /** The palette as {@link VanillaData}, with the runtime id of each block state in the same order. */
    public record Compiled(VanillaData data, int[] networkIds) {
    }

    /** Writes the palette's block palette, item registry and creative content into the directory. */
    public static void write(Palette palette, Path directory) throws IOException {
        Compiled compiled = compiled(palette);
        Files.createDirectories(directory);
        write(compiled.data(), directory, compiled.networkIds());
        Files.writeString(directory.resolve(MARKER), "Generated by `export --name " + palette.version().name() + "` (Paletter tools): the block palette, "
            + "item registry and creative content a compiled Paletter palette sends, in the file formats of CloudburstMC/Data.\n"
            + "Not data of CloudburstMC/Data: do not edit. block_palette.nbt lists the states in registry order, each with its "
            + "runtime id as network_id. Compare with a cb/data checkout: verify --source <cb/data> --name <version> --against <this directory>.\n");
    }

    /** What the palette sends, as data: states in registry index order, items by definition, the creative packet's layout. */
    public static Compiled compiled(Palette palette) {
        int size = palette.blocks().size();
        List<NbtMap> states = new ArrayList<>(size);
        int[] networkIds = new int[size];
        for (int i = 0; i < size; i++) {
            RegisteredBlockState block = palette.blocks().byIndex(i);
            states.add(state(block));
            networkIds[i] = block.getRuntimeId();
        }

        List<VanillaItem> items = new ArrayList<>();
        for (RegisteredItem item : palette.itemDefinitions()) {
            items.add(new VanillaItem(item.getIdentifier(), item.getRuntimeId(), item.getVersion().ordinal(), item.isComponentBased(),
                item.getComponentData() == null ? NbtMap.EMPTY : item.getComponentData()));
        }

        List<BlockPropertyData> dataDriven = palette.blocks().blockProperties();
        VanillaData data = new VanillaData(palette.version(), states, items, dataDriven, creative(palette), Map.of(), VersionFallbacks.NONE, Map.of());
        return new Compiled(data, networkIds);
    }

    private static NbtMap state(BlockDefinition definition) {
        RegisteredBlockState block = (RegisteredBlockState) definition;
        return BlockStates.of(block.identifier(), block.states());
    }

    private static RawLayout creative(Palette palette) {
        List<CreativeItemGroup> groups = palette.creative().groups();
        List<List<RawStack>> stacks = new ArrayList<>();
        groups.forEach(group -> stacks.add(new ArrayList<>()));
        for (CreativeItemData item : palette.creative().items()) {
            stacks.get(item.getGroupId()).add(stack(item.getItem()));
        }
        Map<CreativeCategory, List<RawNode>> categories = new EnumMap<>(CreativeCategory.class);
        for (CreativeCategory category : CreativeCategory.values()) {
            categories.put(category, new ArrayList<>());
        }
        for (int i = 0; i < groups.size(); i++) {
            CreativeItemGroup group = groups.get(i);
            List<RawNode> nodes = categories.get(CreativeCategory.fromProtocol(group.getCategory()));
            if (group.getName().isEmpty()) {
                nodes.addAll(stacks.get(i));
            } else {
                ItemData icon = group.getIcon();
                boolean air = icon == null || icon.getDefinition() == null || icon.getDefinition().getIdentifier().equals("minecraft:air");
                nodes.add(new RawGroup(group.getName(), air ? null : stack(icon), stacks.get(i)));
            }
        }
        return RawLayout.of(categories);
    }

    private static RawStack stack(ItemData item) {
        NbtMap block = item.getBlockDefinition() == null ? null : state(item.getBlockDefinition());
        return new RawStack(item.getDefinition().getIdentifier(), item.getDamage(), item.getCount(), block, item.getTag());
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Reading back

    /** The export as data, with the block palette entries as written (they carry {@code network_id}). */
    record Read(VanillaData data, Importer.Source source) {
    }

    static Read read(Path directory, String name) throws IOException {
        Importer.Source source = Importer.readSource(directory, name);
        VanillaData data = new VanillaData(new dev.opencollab.paletter.data.DataVersion(name, 0), source.blocks(), source.items(),
            source.dataDriven() == null ? List.of() : source.dataDriven(), source.creative(), Map.of(), VersionFallbacks.NONE, Map.of());
        return new Read(data, source);
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Writing in the CloudburstMC/Data layout (what ProxyPass and the capture client write)

    /**
     * Writes the data in the CloudburstMC/Data layout.
     *
     * @param networkIds the {@code network_id} of each block state in order, or null to write the states without one
     */
    public static void write(VanillaData data, Path directory, int @Nullable [] networkIds) throws IOException {
        List<NbtMap> blocks = new ArrayList<>();
        for (int i = 0; i < data.blockStates().size(); i++) {
            NbtMap state = data.blockStates().get(i);
            blocks.add(networkIds == null ? state : state.toBuilder().putInt("network_id", networkIds[i]).build());
        }
        writeGzip(directory.resolve("block_palette.nbt"), NbtMap.builder().putList("blocks", NbtType.COMPOUND, blocks).build());

        JsonArray states = new JsonArray();
        NbtMapBuilder components = NbtMap.builder();
        for (VanillaItem item : data.items()) {
            JsonObject json = new JsonObject();
            json.addProperty("name", item.identifier());
            json.addProperty("id", item.runtimeId());
            json.addProperty("version", item.version());
            json.addProperty("componentBased", item.componentBased());
            states.add(json);
            if (item.componentData() != null) {
                components.putCompound(item.identifier(), item.componentData());
            }
        }
        Files.writeString(directory.resolve("runtime_item_states.json"), new Gson().toJson(states));
        writeGzip(directory.resolve("item_components.nbt"), components.build());

        NbtMapBuilder dataDriven = NbtMap.builder();
        data.dataDrivenBlocks().forEach(block -> dataDriven.putCompound(block.getName(), block.getProperties()));
        writeGzip(directory.resolve("data_driven_blocks.nbt"), dataDriven.build());

        JsonArray groups = new JsonArray();
        JsonArray items = new JsonArray();
        for (CreativeCategory category : CreativeCategory.values()) {
            boolean looseGroupOpen = false;
            for (RawNode node : data.creative().nodes(category)) {
                if (node instanceof RawGroup group) {
                    groups.add(group(group.name(), category, group.icon()));
                    for (RawStack stack : group.stacks()) {
                        items.add(stack(stack, groups.size() - 1));
                    }
                    looseGroupOpen = false;
                } else {
                    if (!looseGroupOpen) {
                        groups.add(group("", category, null));
                        looseGroupOpen = true;
                    }
                    items.add(stack((RawStack) node, groups.size() - 1));
                }
            }
        }
        JsonObject creative = new JsonObject();
        creative.add("groups", groups);
        creative.add("items", items);
        Files.writeString(directory.resolve("creative_items.json"), new Gson().toJson(creative));
    }

    private static JsonObject group(String name, CreativeCategory category, @Nullable RawStack icon) throws IOException {
        JsonObject json = new JsonObject();
        json.addProperty("name", name);
        json.addProperty("category", category.bedrockName());
        if (icon == null) {
            JsonObject air = new JsonObject();
            air.addProperty("id", "minecraft:air");
            json.add("icon", air);
        } else {
            json.add("icon", stack(icon, -1));
        }
        return json;
    }

    private static JsonObject stack(RawStack stack, int groupId) throws IOException {
        JsonObject json = new JsonObject();
        json.addProperty("id", stack.identifier());
        if (stack.damage() != 0) {
            json.addProperty("damage", stack.damage());
        }
        if (stack.count() != 1) {
            json.addProperty("count", stack.count());
        }
        if (stack.blockState() != null) {
            json.addProperty("block_state_b64", base64(stack.blockState()));
        }
        if (stack.tag() != null) {
            json.addProperty("nbt_b64", base64(stack.tag()));
        }
        if (groupId >= 0) {
            json.addProperty("groupId", groupId);
        }
        return json;
    }

    private static String base64(NbtMap tag) throws IOException {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        try (NBTOutputStream output = NbtUtils.createWriterLE(bytes)) {
            output.writeTag(tag);
        }
        return Base64.getEncoder().encodeToString(bytes.toByteArray());
    }

    private static void writeGzip(Path file, NbtMap tag) throws IOException {
        try (OutputStream stream = Files.newOutputStream(file); NBTOutputStream output = NbtUtils.createGZIPWriter(stream)) {
            output.writeTag(tag);
        }
    }
}
