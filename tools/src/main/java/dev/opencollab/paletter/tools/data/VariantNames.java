package dev.opencollab.paletter.tools.data;

import dev.opencollab.paletter.internal.data.VanillaData;
import dev.opencollab.paletter.tools.Layout;
import dev.opencollab.paletter.tools.bds.BdsDump;
import org.checkerframework.checker.nullness.qual.Nullable;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * {@code data/model/variant_names.txt}: the names of item aux variants (potions, tipped arrows, beds, banners)
 * that the constants generator turns into {@code BedrockItemVariants}. The names are BDS's own, from the item variants of
 * the Script API dump ({@link BdsDump#itemVariants()}):
 * <ul>
 *     <li>a variant with a potion effect ({@code minecraft:long_nightvision}) is {@code <ITEM>_<EFFECT>}:
 *     {@code POTION_LONG_NIGHTVISION};</li>
 *     <li>else one whose localization key is {@code item.<item>.<name>.name} is {@code <ITEM>_<NAME>}, camelCase as snake
 *     case: {@code item.bed.lightBlue.name} is {@code BED_LIGHT_BLUE};</li>
 *     <li>any other has no name (the plain arrow).</li>
 * </ul>
 * A bundled version only lists the variants its creative inventory has, as only those are variants of the item type, and
 * every creative variant of an item the dump covers must get a name (except the plain arrow): a dump that missed some
 * fails instead of silently dropping constants.
 */
public final class VariantNames {
    public static final String FILE = Layout.MODEL + "/variant_names.txt";
    private static final String HEADER = "# <first data version>..[<last>] <item identifier> <aux> <constant name> [<potion type>]: the variant is in the data versions "
        + "from <first> to <last>, both included; without <last>, in every version from <first> on; a potion or tipped arrow names its potion type. Generated by `update` / `script-dump` / `variant-names` "
        + "(:tools:run) from the item variants of BDS's Script API dump; do not edit by hand.";
    private static final Pattern KEY = Pattern.compile("item\\.([a-z_]+)\\.([A-Za-z_]+)\\.name");

    private VariantNames() {
    }

    /**
     * @param name the constant name, e.g. {@code POTION_LONG_NIGHTVISION}
     * @param potion the potion type BDS gives the variant, e.g. {@code minecraft:long_nightvision}, or null if it has none
     *               (beds, banners)
     */
    public record Entry(String identifier, int aux, String name, @Nullable String potion) {
        public Entry(String identifier, int aux, String name) {
            this(identifier, aux, name, null);
        }
    }

    /**
     * Sets the names of a bundled version from a dump. A dump without item variants (before format 3, or a failed variant
     * section) leaves the version's names as they are.
     *
     * @param all data version to its names, as {@link #read} gives them
     */
    public static void update(Map<String, List<Entry>> all, String version, BdsDump dump, VanillaData data) {
        if (dump.itemVariants().isEmpty()) {
            System.out.println("  the dump has no item variants: the variant names of " + version + " stay as they are");
            return;
        }
        all.put(version, of(dump, data));
    }

    /**
     * Writes the file from the committed dumps: per bundled version, the names of the dump of its build
     * ({@code data/bds/<build>/dump.json.gz}, older builds first, so the newest build of a version decides). What a recapture
     * does after its captures: each capture leg writes the dump of its build, none writes the file.
     *
     * @return the versions whose names a dump gave
     */
    public static List<String> regenerate(Path root) throws IOException {
        Path data = root.resolve("paletter/src/main/resources/paletter");
        List<String> versions = versions(data);
        Map<String, List<Entry>> all = read(root.resolve(FILE), versions);
        List<String> named = new ArrayList<>();
        List<Path> builds;
        try (java.util.stream.Stream<Path> list = Files.list(root.resolve(Layout.BDS))) {
            builds = list.filter(b -> Files.exists(b.resolve("dump.json.gz")))
                .sorted(Comparator.comparing(b -> b.getFileName().toString(), dev.opencollab.paletter.tools.Versions.ORDER)).toList();
        }
        for (Path build : builds) {
            String version = dev.opencollab.paletter.tools.BuildNumber.parse(build.getFileName().toString()).dataVersion();
            Path bundled = data.resolve(version + ".nbt");
            BdsDump dump = BdsDump.read(build.resolve("dump.json.gz"));
            if (!versions.contains(version) || !Files.exists(bundled) || dump.itemVariants().isEmpty()) {
                continue;
            }
            all.put(version, of(dump, BundledFiles.read(bundled)));
            named.add(version);
        }
        Files.writeString(root.resolve(FILE), render(all, versions));
        return named;
    }

    /** The names of the dump's variants that the creative inventory of {@code data} has. */
    static List<Entry> of(BdsDump dump, VanillaData data) {
        Set<String> creative = new HashSet<>();
        data.creative().forEachStack(stack -> creative.add(stack.identifier() + "@" + stack.damage()));
        List<Entry> entries = new ArrayList<>();
        Set<String> named = new HashSet<>();
        Map<String, String> used = new TreeMap<>();
        dump.itemVariants().forEach((identifier, variants) -> variants.forEach((aux, variant) -> {
            String name = name(identifier, variant);
            if (name == null || !creative.contains(identifier + "@" + aux)) {
                return;
            }
            String other = used.put(name, identifier + "@" + aux);
            if (other != null) {
                throw new IllegalStateException("BDS names " + other + " and " + identifier + "@" + aux + " both " + name);
            }
            entries.add(new Entry(identifier, aux, name, variant.potion()));
            named.add(identifier + "@" + aux);
        }));
        List<String> missing = new ArrayList<>();
        for (String stack : new TreeSet<>(creative)) {
            if (dump.itemVariants().containsKey(stack.substring(0, stack.indexOf('@'))) && !named.contains(stack) && !stack.equals("minecraft:arrow@0")) {
                missing.add(stack);
            }
        }
        if (!missing.isEmpty()) {
            throw new IllegalStateException("The dump names no creative variant " + missing + " of the items it covers: it is incomplete");
        }
        return entries;
    }

    static String name(String identifier, BdsDump.Variant variant) {
        String item = path(identifier);
        if (variant.potion() != null) {
            return (item + "_" + path(variant.potion())).toUpperCase(Locale.ROOT);
        }
        Matcher key = KEY.matcher(variant.localizationKey());
        if (key.matches() && key.group(1).equals(item)) {
            return (item + "_" + key.group(2).replaceAll("([a-z0-9])([A-Z])", "$1_$2")).toUpperCase(Locale.ROOT);
        }
        return null;
    }

    private static String path(String identifier) {
        return identifier.substring(identifier.indexOf(':') + 1);
    }

    /**
     * The bundled data versions in the order of the index ({@code versions.txt}, by protocol): the order the ranges of the
     * file are over.
     */
    public static List<String> versions(Path data) throws IOException {
        return Importer.readIndex(data).stream().map(Importer.IndexEntry::name).toList();
    }

    /**
     * Data version to its entries; empty if the file does not exist. A line is {@code <first>..<last> <item> <aux> <name>}:
     * the variant is in the versions from {@code first} to {@code last}, both included, of {@code versions}; without a
     * {@code last} it is in every version from {@code first} on.
     *
     * @param versions the bundled data versions in index order, as {@link #versions} gives them
     */
    public static Map<String, List<Entry>> read(Path file, List<String> versions) throws IOException {
        Map<String, List<Entry>> all = new TreeMap<>();
        if (file == null || !Files.exists(file)) {
            return all;
        }
        for (String line : Files.readAllLines(file)) {
            if (line.isBlank() || line.startsWith("#")) {
                continue;
            }
            String[] parts = line.split(" ");
            String[] range = parts[0].split("\\.\\.", -1);
            if ((parts.length != 4 && parts.length != 5) || range.length != 2) {
                throw new IllegalStateException(FILE + ": '" + line + "' is not '<first>..[<last>] <item> <aux> <name> [<potion type>]'");
            }
            int first = indexOf(versions, range[0], line);
            int last = range[1].isEmpty() ? versions.size() - 1 : indexOf(versions, range[1], line);
            if (first > last) {
                throw new IllegalStateException(FILE + ": the range of '" + line + "' ends before it starts");
            }
            Entry entry = new Entry(parts[1], Integer.parseInt(parts[2]), parts[3], parts.length == 5 ? parts[4] : null);
            for (String version : versions.subList(first, last + 1)) {
                all.computeIfAbsent(version, v -> new ArrayList<>()).add(entry);
            }
        }
        return all;
    }

    private static int indexOf(List<String> versions, String version, String line) {
        int index = versions.indexOf(version);
        if (index < 0) {
            throw new IllegalStateException(FILE + ": '" + line + "' names the version " + version + ", which is not bundled");
        }
        return index;
    }

    /**
     * The content of the file for these names: each variant once, with the versions it is in as a range. A range that
     * reaches the newest version is open ({@code 26.60..}), so a new version that still has the variant changes no line.
     *
     * @param versions the bundled data versions in index order
     */
    public static String render(Map<String, List<Entry>> all, List<String> versions) {
        for (String version : all.keySet()) {
            if (!versions.contains(version)) {
                throw new IllegalStateException("The variant names of " + version + " have no bundled version of that name (" + versions + ")");
            }
        }
        // The versions of each variant, as runs of consecutive versions of the index
        Map<Entry, List<Integer>> positions = new LinkedHashMap<>();
        for (int i = 0; i < versions.size(); i++) {
            for (Entry entry : all.getOrDefault(versions.get(i), List.of())) {
                positions.computeIfAbsent(entry, e -> new ArrayList<>()).add(i);
            }
        }
        record Line(Entry entry, int first, int last) {
        }
        List<Line> lines = new ArrayList<>();
        positions.forEach((entry, at) -> {
            int first = at.getFirst();
            for (int i = 1; i <= at.size(); i++) {
                if (i == at.size() || at.get(i) != at.get(i - 1) + 1) {
                    lines.add(new Line(entry, first, at.get(i - 1)));
                    if (i < at.size()) {
                        first = at.get(i);
                    }
                }
            }
        });
        lines.sort(Comparator.comparing((Line l) -> l.entry().identifier()).thenComparingInt(l -> l.entry().aux())
            .thenComparing(l -> l.entry().name()).thenComparingInt(Line::first));
        List<String> out = new ArrayList<>();
        out.add(HEADER);
        for (Line line : lines) {
            String last = line.last() == versions.size() - 1 ? "" : versions.get(line.last());
            out.add(versions.get(line.first()) + ".." + last + " " + line.entry().identifier() + " " + line.entry().aux() + " " + line.entry().name()
                + (line.entry().potion() != null ? " " + line.entry().potion() : ""));
        }
        return String.join("\n", out) + "\n";
    }
}
