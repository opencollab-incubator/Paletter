package dev.opencollab.paletter.tools.behaviour;

import org.cloudburstmc.nbt.NbtMap;
import dev.opencollab.paletter.behaviour.BehaviourKey;
import dev.opencollab.paletter.behaviour.BlockBehaviour;
import dev.opencollab.paletter.behaviour.BlockShape;
import dev.opencollab.paletter.behaviour.ItemBehaviour;
import dev.opencollab.paletter.internal.behaviour.WireRules;
import dev.opencollab.paletter.tools.codegen.component.BehaviourKeys;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.TreeMap;
import java.util.function.Function;

/**
 * {@code data/behaviour/REPORT.md}: which source decides each key in each version (or that the version inherits it),
 * where sources disagree, keys no source has, and source fields no key reads. Everything a human has to look at.
 */
final class BehaviourReport {
    private static final int EXAMPLES = 3;

    private final List<BehaviourImport.Bundled> bundled;
    private final List<BehaviourImport.Capture> captures;
    private final BehaviourStore store;
    private final List<String> log;
    private final List<BehaviourImport.CustomDefault> customDefaults;
    /** The section the generator writes ({@link ChangesSection}). */
    private final String changes;

    BehaviourReport(List<BehaviourImport.Bundled> bundled, List<BehaviourImport.Capture> captures, BehaviourStore store, List<String> log,
                    List<BehaviourImport.CustomDefault> customDefaults, String changes) {
        this.bundled = bundled;
        this.captures = captures;
        this.store = store;
        this.log = log;
        this.customDefaults = customDefaults;
        this.changes = changes;
    }

    String render() {
        StringBuilder out = new StringBuilder();
        out.append("<!-- Generated by `behaviour import` (tools module). Do not edit. Regenerate with: ").append(BehaviourImport.COMMAND)
            .append(". Sources: CloudburstMC/Data, AllayMC/Allay (git history), Paletter data/bds Script API dumps; "
                + "the exact commits are in the Captures table and in the metadata of data/behaviour/captures.nbt. -->\n\n");
        out.append("# Behaviour data report\n\n**Generated** by `behaviour import` (tools); do not edit. The same sources at the same "
            + "commits give the same file. The captures are stored in `data/behaviour/captures.nbt` (format and lookup rules: "
            + "`BehaviourStore` in the tools); the library's values are the Java code generated from it (`internal.behaviour.vanilla`, "
            + "one class per version with what changed).\n\n");
        ranking(out);
        keys(out);
        sources(out);
        coverage(out);
        out.append(changes);
        disputes(out);
        postProcessed(out);
        customDefaults(out);
        disagreements(out);
        unmapped(out);
        out.append("## Log\n\n");
        log.forEach(line -> out.append("- ").append(line).append('\n'));
        return out.toString();
    }

    private void ranking(StringBuilder out) {
        out.append("## Ranking\n\nValues come from BDS directly wherever possible; third-party dumps rank below and are marked "
            + "(`explain` says \"third party\"). Strongest first:\n\n"
            + "1. Paletter's own captures of BDS: native capture (`NATIVE`, none yet), Script API dumps (`SCRIPT_API`), experiments on BDS "
            + "(`BDS_PROBE`: `behaviour-probe`, the collision of doors and climbing) and what BDS sends clients (`WIRE`, ranked at runtime from the "
            + "component data of the palette).\n"
            + "2. `CLOUDBURST_DATA`: CloudburstMC/Data (Apache-2.0), a native BDS dump. Third party. It post-processes some values "
            + "(see Post-processed values).\n"
            + "3. `ALLAY_DATA`: AllayMC/Allay `data/` (MIT), the raw Endstone DevTools dump of BDS. Third party. Used only for what "
            + "CloudburstMC/Data does not have (items: attack damage, armour, toughness, enchant value, furnace fuel and XP; "
            + "CloudburstMC/Data has no item behaviour file in any commit of its history), and as the other opinion for disputes.\n\n"
            + "Where sources disagree and no BDS evidence settles it, the value of the stronger one is used and marked disputed "
            + "(`explain` lists the other values).\n\n");
    }

    /** The naming table: which BDS property each key is (BehaviourKeys), and the properties of the dump that are no key. */
    private void keys(StringBuilder out) {
        out.append("## Keys\n\nEach key is a BDS property (`BehaviourKeys` in tools, checked against the newest captures when the keys are "
            + "generated). `SAPI:` the Script API (`behaviour-dump`), `PROBE:` measured by `behaviour-probe`, `NATIVE:` BDS's own member "
            + "(no Paletter capture yet: filled from the third-party dumps).\n\n");
        out.append("| Key | BDS property, strongest first | Conversion |\n|---|---|---|\n");
        for (BehaviourKeys.Key key : BehaviourKeys.KEYS) {
            out.append("| `").append(key.owner().name().toLowerCase(java.util.Locale.ROOT)).append(':').append(key.name()).append("` | ")
                .append(String.join("<br>", key.sources().stream().map(source -> "`" + source + "`").toList())).append(" | ")
                .append(key.conversion() == BehaviourKeys.Conversion.NONE ? "" : key.conversion().name()).append(" |\n");
        }
        out.append("\nScript API properties that are no key, and why:\n\n");
        BehaviourKeys.IGNORED.forEach((property, reason) -> out.append("- `").append(property).append("`: ").append(reason).append('\n'));
        out.append('\n');
    }

    private void sources(StringBuilder out) {
        out.append("## Captures\n\nIn application order (per version the weakest source first; the strongest decides what it covers).\n\n");
        out.append("| Version | Source | Reference | Date | Identified by |\n|---|---|---|---|---|\n");
        for (BehaviourImport.Capture capture : captures) {
            out.append("| ").append(capture.version().name()).append(" | ").append(capture.source()).append(" | `")
                .append(capture.reference()).append("` | ").append(capture.date()).append(" | ").append(capture.match()).append(" |\n");
        }
        out.append('\n');
    }

    private void coverage(StringBuilder out) {
        out.append("## Coverage\n\nPer key and version: who decides the values of the version's block states / items. `inherited from V` means no capture of the version covers them and the value of version V applies.\n\n");
        out.append("| Key |");
        bundled.forEach(b -> out.append(' ').append(b.version().name()).append(" |"));
        out.append("\n|---|").append("---|".repeat(bundled.size())).append('\n');
        List<BehaviourKey<?>> keys = new ArrayList<>(BlockBehaviour.keys());
        keys.addAll(ItemBehaviour.keys());
        List<BehaviourKey<?>> notDumped = new ArrayList<>();
        for (BehaviourKey<?> key : keys) {
            out.append("| `").append(key).append("` |");
            boolean dumped = false;
            for (BehaviourImport.Bundled version : bundled) {
                Map<String, Integer> counts = new TreeMap<>();
                Collection<?> ids = key.owner() == BehaviourKey.Owner.BLOCK ? version.states().keySet() : version.items();
                for (Object id : ids) {
                    BehaviourStore.Resolved resolved = key.owner() == BehaviourKey.Owner.BLOCK
                        ? store.block(key, (Integer) id, version.version()) : store.item(key, (String) id, version.version());
                    String label = resolved == null ? "none"
                        : resolved.capture().version().name().equals(version.version().name()) ? resolved.capture().source().name()
                        : "inherited from " + resolved.capture().version().name() + " " + resolved.capture().source();
                    counts.merge(label, 1, Integer::sum);
                    dumped |= resolved != null;
                }
                out.append(' ');
                counts.forEach((label, count) -> out.append(label).append(' ').append(count).append("<br>"));
                out.append(" |");
            }
            out.append('\n');
            if (!dumped) {
                notDumped.add(key);
            }
        }
        out.append("\nKeys no dump has:\n\n");
        notDumped.stream().sorted(java.util.Comparator.comparing(Object::toString))
            .forEach(key -> out.append("- `").append(key).append("`: ").append(insteadOfADump(key)).append('\n'));
        out.append('\n');
    }

    /** What serves a key no dump has: the component data if a wire rule reads the key, else nothing yet. */
    private static String insteadOfADump(BehaviourKey<?> key) {
        if (WireRules.components(key).isEmpty()) {
            return "no source: needs a native capture of BDS (LeviLamina), run by hand";
        }
        String kind = key.owner() == BehaviourKey.Owner.BLOCK ? "blocks" : "items";
        return "read at runtime from the component data (WIRE) of component based " + kind + "; native " + kind + " need the native capture";
    }

    private void disputes(StringBuilder out) {
        out.append("## Disputed values\n\nStored values a second third-party source disagrees on, with no direct BDS capture of the key "
            + "in the version (a data driven block's wire data settles it at runtime and wins; the cross-check test shows no "
            + "disagreement there). `explain` lists the other source's value for these. "
            + "A dispute is carried to the versions where the source's value is unchanged and nothing else could be checked "
            + "(the alternative then names the version it was seen in).\n\n");
        Map<String, Map<String, Integer>> counts = new TreeMap<>();
        Map<String, String> examples = new TreeMap<>();
        for (BehaviourImport.Bundled version : bundled) {
            for (BehaviourKey<?> key : BlockBehaviour.keys()) {
                for (Map.Entry<Integer, NbtMap> state : version.states().entrySet()) {
                    BehaviourStore.Resolved resolved = store.block(key, state.getKey(), version.version());
                    if (resolved == null || resolved.disputes().isEmpty()) {
                        continue;
                    }
                    String name = state.getValue().getString("name").replace("minecraft:", "");
                    counts.computeIfAbsent(version.version().name() + " " + key, k -> new TreeMap<>()).merge(name, 1, Integer::sum);
                    String alternative = resolved.disputes().getFirst().capture().source() + "@" + resolved.disputes().getFirst().capture().version().name();
                    examples.putIfAbsent(version.version().name() + " " + key, describe(state.getValue(), state.getKey()) + ": "
                        + format(resolved.value()) + " (" + resolved.capture().source() + ") / " + format(resolved.disputes().getFirst().value())
                        + " (" + alternative + ")");
                }
            }
        }
        if (counts.isEmpty()) {
            out.append("None.\n\n");
            return;
        }
        out.append("| Version and key | States | Blocks | Example (used / alternative) |\n|---|---|---|---|\n");
        counts.forEach((label, byName) -> out.append("| ").append(label).append(" | ").append(byName.values().stream().mapToInt(Integer::intValue).sum())
            .append(" | ").append(byName.size() <= 30 ? String.join(", ", byName.keySet()) : byName.size() + " blocks")
            .append(" | ").append(examples.get(label)).append(" |\n"));
        out.append('\n');
    }

    private void postProcessed(StringBuilder out) {
        out.append("## Post-processed values\n\nValues the source itself says it post-processed after reading BDS "
            + "(`explain` says so), e.g. CloudburstMC/Data's `shapeSource: door_state_correction`.\n\n");
        Map<String, Integer> counts = new TreeMap<>();
        for (BehaviourImport.Bundled version : bundled) {
            for (BehaviourKey<?> key : BlockBehaviour.keys()) {
                for (Integer hash : version.states().keySet()) {
                    BehaviourStore.Resolved resolved = store.block(key, hash, version.version());
                    if (resolved != null && resolved.postProcessing() != null) {
                        counts.merge(version.version().name() + " " + key + ": " + resolved.postProcessing(), 1, Integer::sum);
                    }
                }
            }
        }
        if (counts.isEmpty()) {
            out.append("None.\n\n");
        }
        counts.forEach((label, count) -> out.append("- ").append(label).append(" (").append(count).append(" states)\n"));
        out.append('\n');
    }

    private void customDefaults(StringBuilder out) {
        out.append("## Custom content: defaults\n\nBehaviour of custom blocks and items matches BDS: "
            + "`explain` tells a component the user set (`USER`) from a BDS default. The default of a key (what BDS uses when "
            + "the component is absent) is what the newest behaviour probe capture measured, with that capture as reference; a key "
            + "it did not measure has no value (`UNKNOWN_DEFAULT`: `get` throws, `getOrElse` gives the fallback).\n\n");
        if (customDefaults.isEmpty()) {
            out.append("Known defaults: none yet. Every default of a custom block or item is unknown.\n\n");
        } else {
            customDefaults.forEach(d -> out.append("- `").append(d.key()).append("` = ").append(format(d.value())).append(" (")
                .append(d.source()).append(": ").append(d.reference()).append(")\n"));
            out.append('\n');
        }
        out.append("The friction of a custom block is 1 minus the `minecraft:friction` value, confirmed on BDS by the probe "
            + "(`friction.components` of its capture).\n\n");
    }

    private void disagreements(StringBuilder out) {
        out.append("## Disagreements\n\nEvery pair of captures of the same version, on the ids both cover. The stronger source is stored; check the other.\n\n");
        boolean any = false;
        for (int i = 0; i < captures.size(); i++) {
            for (int j = i + 1; j < captures.size(); j++) {
                BehaviourImport.Capture a = captures.get(i);
                BehaviourImport.Capture b = captures.get(j);
                if (!a.version().equals(b.version())) {
                    continue;
                }
                BehaviourImport.Bundled palette = bundled.stream().filter(v -> v.version().equals(a.version())).findFirst().orElseThrow();
                List<String> rows = new ArrayList<>();
                compare(a.blocks(), b.blocks(), palette.states().keySet(), id -> describe(palette.states().get(id), id), rows);
                compare(a.items(), b.items(), palette.items(), id -> id, rows);
                if (rows.isEmpty()) {
                    continue;
                }
                any = true;
                out.append("### ").append(a.version().name()).append(": ").append(a.source()).append(" vs ").append(b.source()).append("\n\n");
                out.append("| Key | Compared | Different | Examples (").append(a.source()).append(" / ").append(b.source()).append(") |\n|---|---|---|---|\n");
                rows.forEach(out::append);
                out.append('\n');
            }
        }
        if (!any) {
            out.append("None.\n\n");
        }
    }

    /**
     * One row per key that differs: how many ids, the first examples and, for blocks, which blocks (the name before
     * the first {@code [} of an example).
     */
    private static <I> void compare(Values<I> a, Values<I> b, Set<I> palette, Function<I, String> name, List<String> rows) {
        for (Map.Entry<BehaviourKey<?>, Map<I, Object>> entry : a.byKey.entrySet()) {
            Map<I, Object> other = b.byKey.get(entry.getKey());
            if (other == null) {
                continue;
            }
            int compared = 0;
            List<String> different = new ArrayList<>();
            Map<String, Integer> byName = new TreeMap<>();
            int differentCount = 0;
            for (Map.Entry<I, Object> value : entry.getValue().entrySet()) {
                I id = value.getKey();
                if (!palette.contains(id) || !other.containsKey(id)) {
                    continue;
                }
                compared++;
                if (!Objects.equals(value.getValue(), other.get(id))) {
                    differentCount++;
                    String described = name.apply(id);
                    byName.merge(described.contains("[") ? described.substring(0, described.indexOf('[')) : described, 1, Integer::sum);
                    if (different.size() < EXAMPLES) {
                        different.add(described + ": " + format(value.getValue()) + " / " + format(other.get(id)));
                    }
                }
            }
            if (differentCount > 0) {
                String names = byName.size() <= 1 ? "" : "<br>in " + byName.entrySet().stream().limit(40)
                    .map(e -> e.getKey() + " " + e.getValue()).collect(java.util.stream.Collectors.joining(", "))
                    + (byName.size() > 40 ? ", ... (" + byName.size() + " in all)" : "");
                rows.add("| `" + entry.getKey() + "` | " + compared + " | " + differentCount + " | "
                    + String.join("<br>", different) + names + " |\n");
            }
        }
    }

    private void unmapped(StringBuilder out) {
        Map<String, Integer> fields = new TreeMap<>();
        for (BehaviourImport.Capture capture : captures) {
            capture.blocks().unmappedFields.forEach((field, count) -> fields.merge(capture.source() + " block " + field, count, Integer::sum));
            capture.items().unmappedFields.forEach((field, count) -> fields.merge(capture.source() + " item " + field, count, Integer::sum));
        }
        out.append("## Unmapped source fields\n\nFields a source has that no key reads (add a key and a line in `EndstoneDump`, or ignore them there).\n\n");
        if (fields.isEmpty()) {
            out.append("None.\n\n");
        }
        fields.forEach((field, count) -> out.append("- ").append(field).append(" (").append(count).append(")\n"));
        out.append('\n');
    }

    private static String describe(NbtMap state, int hash) {
        StringBuilder out = new StringBuilder(state.getString("name").replace("minecraft:", "")).append('[');
        new TreeMap<>(state.getCompound("states")).forEach((key, value) -> out.append(out.charAt(out.length() - 1) == '[' ? "" : ",")
            .append(key.replace("minecraft:", "")).append('=').append(value instanceof Byte b ? b != 0 : value));
        return out.append("] (").append(Integer.toUnsignedString(hash)).append(')').toString();
    }

    private static String format(Object value) {
        if (value instanceof BlockShape shape) {
            return Arrays.toString(shape.coordinates());
        }
        return String.valueOf(value);
    }
}
