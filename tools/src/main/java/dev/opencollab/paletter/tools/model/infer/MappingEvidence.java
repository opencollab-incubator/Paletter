package dev.opencollab.paletter.tools.model.infer;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;

import java.util.List;
import java.util.Map;

/**
 * {@code data/model/mappings-evidence.json}: what the inference saw for each field and value form of each protocol window,
 * which no generator reads: the counts of accepted and rejected variants, BDS's messages and the values it refused, the
 * range it enforces, and the leaves no rule explains. {@code mappings.json} keeps what the generators read (windows,
 * statuses, rules, absent values, transforms). Both are written by {@code infer} from one result: {@link Coverage} reads
 * these keys from that result before the split, {@code check-mappings} compares both files.
 * <p>
 * The file has the shape of {@code mappings.json}: {@code components -> id -> windows[] -> {protocols, fields, forms}},
 * the windows those of {@code mappings.json}, a field only where it has evidence.
 */
public final class MappingEvidence {
    public static final String FILE = "mappings-evidence.json";
    /** The keys of a field or form result that are evidence only, in the order they are written. */
    static final List<String> KEYS = List.of("accepted", "rejected", "rejectedValues", "bdsErrors", "bdsRange", "unexplained",
        "unexplainedMore");

    private MappingEvidence() {
    }

    /**
     * Moves the evidence keys of every field and form of the components out of {@code mappings} (in place).
     *
     * @return the evidence file's JSON
     */
    public static JsonObject split(JsonObject mappings) {
        JsonObject components = new JsonObject();
        for (Map.Entry<String, JsonElement> component : mappings.getAsJsonObject("components").entrySet()) {
            JsonArray windows = new JsonArray();
            for (JsonElement element : component.getValue().getAsJsonObject().getAsJsonArray("windows")) {
                JsonObject window = element.getAsJsonObject();
                JsonObject evidence = new JsonObject();
                evidence.add("protocols", window.get("protocols").deepCopy());
                for (String group : List.of("fields", "forms")) {
                    JsonObject moved = new JsonObject();
                    if (window.has(group)) {
                        for (Map.Entry<String, JsonElement> field : window.getAsJsonObject(group).entrySet()) {
                            JsonObject kept = field.getValue().getAsJsonObject();
                            JsonObject out = new JsonObject();
                            for (String key : KEYS) {
                                if (kept.has(key)) {
                                    out.add(key, kept.remove(key));
                                }
                            }
                            if (!out.isEmpty()) {
                                moved.add(field.getKey(), out);
                            }
                        }
                    }
                    if (!moved.isEmpty()) {
                        evidence.add(group, moved);
                    }
                }
                windows.add(evidence);
            }
            JsonObject out = new JsonObject();
            out.add("windows", windows);
            components.add(component.getKey(), out);
        }
        JsonObject file = new JsonObject();
        file.addProperty("_generated", "Generated by `./gradlew :tools:inferMappings` with mappings.json: what the spec captures"
            + " showed for each field (variant counts, BDS's messages and refused values, ranges, unexplained leaves), which no"
            + " generator reads. Do not edit; see docs/data-pipeline.md.");
        file.add("components", components);
        return file;
    }
}
