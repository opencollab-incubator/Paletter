    /**
     * What the member tags of the constants say. {@code @since} is the Paletter version everywhere (as {@code @Deprecated(since)}
     * is); the Bedrock release a constant is first in is its own line.
     *
     * @param oldest the oldest bundled release
     */
    private static List<String> sinceDoc(String oldest) {
        return List.of("<p>",
            "{@code @since} is the Paletter version that added a constant, and only written if newer than the class. The line",
            "{@code First in Bedrock} is the bundled Bedrock release it first appears in, without an experiment toggle (decided from",
            "the BDS captures in {@code data/bds}); {@code " + oldest + "} is the oldest bundled release, so it may be older.",
            "{@link dev.opencollab.paletter.annotation.Education @Education} marks content BDS only offers to worlds with Education",
            "Edition features, which {@code isEducation()} of the type answers at runtime.");
    }

    /** What the class javadoc says about the constants of the bundled preview. */
    private static final List<String> PREVIEW_DOC = List.of(
        "{@link dev.opencollab.paletter.annotation.SincePreview @SincePreview} marks content only the bundled Bedrock preview",
        "has. The constants are linked to the newest release, so it is never {@code isAvailable()}; what a palette sends for",
        "it, with previews and without, is told by the annotation. The mark goes when a release has it; the constant goes if a newer preview drops it.");

    private static String file(String packageName, TypeSpec type) {
        return JavaFile.builder(packageName, type).addFileComment(HEADER).indent("    ").skipJavaLangImports(true).build().toString();
    }

    private static TypeSpec.Builder classType(String name, List<String> doc) {
        return TypeSpec.classBuilder(name).addModifiers(Modifier.PUBLIC, Modifier.FINAL).addJavadoc(javadoc(doc));
    }

    private static MethodSpec privateConstructor() {
        return MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build();
    }

    /** The lines of a javadoc: an empty one is a blank comment line. */
    private static CodeBlock javadoc(List<String> lines) {
        return CodeBlock.of("$L", String.join("\n", lines) + "\n");
    }

    private static AnnotationSpec sincePreview(String preview) {
        return AnnotationSpec.builder(SINCE_PREVIEW).addMember("value", "$S", preview).build();
    }

    private static AnnotationSpec deprecated(String since) {
        return AnnotationSpec.builder(Deprecated.class).addMember("since", "$S", since).build();
    }

    private static void since(List<String> doc, String since) {
        if (!since.equals(CLASS_SINCE)) {
            doc.add("");
            doc.add("@since " + since);
        }
    }

    /** The prose, the Bedrock release and the {@code @since} (the Paletter version, only if newer than the class) of a constant. */
    private static List<String> memberDoc(String first, Constant constant) {
        List<String> doc = new ArrayList<>();
        doc.add(first);
        if (constant.preview() != null) {
            doc.add("Only in the bundled preview " + constant.preview() + ".");
            return doc;
        }
        if (constant.education()) {
            doc.add("Education Edition content: BDS only offers it to worlds with Education Edition features.");
        }
        if (constant.gating() != null) {
            doc.add("Behind the experiment " + constant.gating() + ": without it the version does not have it.");
        }
        doc.add("First in Bedrock " + constant.bedrock() + ".");
        since(doc, constant.since());
        return doc;
    }

    /** A constant field with its annotations; the initializer is the caller's. */
    private static FieldSpec.Builder constantField(TypeName type, Constant constant, List<String> doc) {
        FieldSpec.Builder field = FieldSpec.builder(type, constant.name(), CONSTANT).addJavadoc(javadoc(doc));
        if (constant.education()) {
            field.addAnnotation(EDUCATION);
        }
        if (constant.preview() != null) {
            field.addAnnotation(sincePreview(constant.preview()));
        }
        if (constant.deprecated() != null) {
            field.addAnnotation(deprecated(constant.deprecated()));
        }
        return field;
    }

    /** Deprecated aliases come last: a static final field cannot refer to one declared after it. */
    private static void addAliases(TypeSpec.Builder type, List<Constant> aliases, List<Constant> constants, ClassName fieldType) {
        for (Constant alias : aliases) {
            Constant target = constants.stream().filter(c -> c.name().equals(alias.replacement())).findFirst().orElseThrow();
            List<String> doc = new ArrayList<>();
            doc.add("{@code " + alias.identifier() + "}.");
            List<String> tags = memberDoc("", alias);
            doc.addAll(tags.subList(1, tags.size()));
            doc.add("@deprecated " + (alias.identifier().equals(target.identifier()) ? "renamed" : "Bedrock renamed it")
                + " to {@link #" + alias.replacement() + "}");
            type.addField(FieldSpec.builder(fieldType, alias.name(), CONSTANT).addJavadoc(javadoc(doc))
                .addAnnotation(deprecated(alias.deprecated())).initializer("$L", alias.replacement()).build());
        }
    }

    private static TypeName stateType(StateConstant state) {
        return switch (state.kind) {
            case BOOL -> vanilla("BoolState");
            case INT -> vanilla("IntState");
            case ENUM -> ParameterizedTypeName.get(vanilla("EnumState"), enumType(state.enumName));
        };
    }

    private static ClassName enumType(String name) {
        return ClassName.get(ConstantsGenerator.STATE_PACKAGE, name);
    }

    private static String joined(List<Integer> values) {
        return String.join(", ", values.stream().map(String::valueOf).toList());
    }

    private static String itemName(Map<String, String> itemNames, String identifier) {
        return itemNames.getOrDefault(identifier, ConstantsGenerator.constantName(identifier));
    }

    private static boolean contiguous(List<Integer> values) {
        for (int i = 1; i < values.size(); i++) {
            if (values.get(i) != values.get(i - 1) + 1) {
                return false;
            }
        }
        return true;
    }
