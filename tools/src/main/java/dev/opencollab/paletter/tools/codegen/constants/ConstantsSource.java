    static String enumClass(EnumModel model, String version) {
        List<String> links = new ArrayList<>();
        model.states.forEach(state -> links.add("{@code " + state + "}"));
        List<String> doc = new ArrayList<>();
        doc.add("Values of " + String.join(", ", links) + "."
            + (model.preview != null ? " Only in the bundled preview " + model.preview + "." : ""));
        doc.add("");
        doc.add("@since " + model.since);
        TypeSpec.Builder type = TypeSpec.enumBuilder(model.name).addModifiers(Modifier.PUBLIC).addSuperinterface(STATE_VALUE)
            .addJavadoc(javadoc(doc));
        if (model.preview != null) {
            type.addAnnotation(sincePreview(model.preview));
        }
        for (EnumValue value : model.values.values()) {
            List<String> valueDoc = new ArrayList<>();
            valueDoc.add("{@code " + value.value() + "}" + (value.preview() != null ? ", only in the bundled preview " + value.preview() + "." : ""));
            if (value.preview() == null && !value.since().equals(model.since)) {
                valueDoc.add("");
                valueDoc.add("@since " + value.since());
            }
            if (value.deprecated() != null) {
                valueDoc.add("@deprecated no block state has this value anymore");
            }
            TypeSpec.Builder constant = TypeSpec.anonymousClassBuilder("$S", value.value()).addJavadoc(javadoc(valueDoc));
            if (value.preview() != null && model.preview == null) {
                constant.addAnnotation(sincePreview(value.preview()));
            }
            if (value.deprecated() != null) {
                constant.addAnnotation(deprecated(value.deprecated()));
            }
            type.addEnumConstant(value.constant(), constant.build());
        }
        type.addField(String.class, "value", Modifier.PRIVATE, Modifier.FINAL);
        type.addMethod(MethodSpec.constructorBuilder().addParameter(String.class, "value").addStatement("this.value = value").build());
        type.addMethod(MethodSpec.methodBuilder("value").addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(TypeName.get(String.class).annotated(AnnotationSpec.builder(NON_NULL).build())).addStatement("return value").build());
        return file(ConstantsGenerator.STATE_PACKAGE, type.build());
    }

    static String states(StateModel model, String release) {
        List<String> doc = new ArrayList<>(List.of(
            "Every block state name of Bedrock " + release + ", the newest bundled release, typed: {@link BoolState} for byte",
            "0/1 states, {@link IntState} for integers, {@link EnumState} for strings, with an enum in",
            "{@code dev.opencollab.paletter.vanilla.state} per distinct value set (states with the same values share one). Which",
            "values a block accepts is up to the block: {@link BedrockBlockType#values(BedrockState)}.",
            "<p>",
            "Constants are added when Bedrock adds states; states Bedrock removes stay, deprecated.",
            "",
            "@since " + CLASS_SINCE));
        TypeSpec.Builder type = classType("BedrockStates", doc);
        List<StateConstant> aliases = new ArrayList<>();
        for (StateConstant state : model.constants.values()) {
            if (state.replacement != null) {
                aliases.add(state);
                continue;
            }
            List<String> memberDoc = new ArrayList<>();
            String first = "{@code " + state.name + "}" + switch (state.kind) {
                case BOOL -> ": true or false";
                case INT -> ": " + (contiguous(state.ints) ? state.ints.getFirst() + " to " + state.ints.getLast() : state.ints.toString());
                case ENUM -> ": {@link " + state.enumName + "}";
            };
            memberDoc.add(first + (state.deprecated == null ? ". Used by " + state.blocks + (state.blocks == 1 ? " block." : " blocks.") : "."));
            if (state.preview != null) {
                memberDoc.add("Only in the bundled preview " + state.preview + ".");
            } else {
                since(memberDoc, state.since);
            }
            if (state.deprecated != null) {
                memberDoc.add("@deprecated no block of the bundled data has this state anymore");
            }
            CodeBlock value = switch (state.kind) {
                case BOOL -> CodeBlock.of("$T.of($S)", vanilla("BoolState"), state.name);
                case INT -> contiguous(state.ints)
                    ? CodeBlock.of("$T.range($S, $L, $L)", vanilla("IntState"), state.name, state.ints.getFirst(), state.ints.getLast())
                    : CodeBlock.of("$T.of($S, $L)", vanilla("IntState"), state.name, joined(state.ints));
                case ENUM -> CodeBlock.of("$T.of($S, $T.class)", vanilla("EnumState"), state.name, enumType(state.enumName));
            };
            FieldSpec.Builder field = FieldSpec.builder(stateType(state), state.constant, CONSTANT).addJavadoc(javadoc(memberDoc))
                .initializer("$T.state($L)", VANILLA_TYPES, value);
            if (state.preview != null) {
                field.addAnnotation(sincePreview(state.preview));
            }
            if (state.deprecated != null) {
                field.addAnnotation(deprecated(state.deprecated));
            }
            type.addField(field.build());
        }
        for (StateConstant alias : aliases) {
            List<String> memberDoc = new ArrayList<>();
            memberDoc.add("{@code " + alias.name + "}.");
            since(memberDoc, alias.since);
            memberDoc.add("@deprecated renamed to {@link #" + alias.replacement + "}");
            type.addField(FieldSpec.builder(stateType(model.constants.get(alias.replacement)), alias.constant, CONSTANT)
                .addJavadoc(javadoc(memberDoc)).addAnnotation(deprecated(alias.deprecated)).initializer("$L", alias.replacement).build());
        }
        type.addMethod(privateConstructor());
        type.addMethod(MethodSpec.methodBuilder("byName").addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .addJavadoc(javadoc(List.of("Finds a state constant by its name.", "", "@param name the state name, e.g. {@code weirdo_direction}",
                "@return the constant of a vanilla state name, or null if there is none")))
            .returns(ParameterizedTypeName.get(BEDROCK_STATE, WildcardTypeName.subtypeOf(Object.class)).annotated(AnnotationSpec.builder(NULLABLE).build()))
            .addParameter(ParameterSpec.builder(String.class, "name").addAnnotation(NON_NULL).build())
            .addStatement("return $T.STATES.get(name)", VANILLA_TYPES).build());
        return file(ConstantsGenerator.PACKAGE, type.build());
    }

    /**
     * @param previewStates the states of each block only the preview has, which its constant carries
     */
    static String blocks(List<Constant> constants, Map<String, BlockLayout> layouts, Map<String, ConstantsGenerator.PreviewStates> previewStates,
                         StateModel states, String version, String oldest) {
        List<String> doc = new ArrayList<>(List.of(
            "Every block type of Bedrock " + version + ", the newest bundled release. The constants are resolved against",
            "the newest data of {@link dev.opencollab.paletter.Paletter#bundled()} on first use; referencing them loads nothing.",
            "<p>",
            "Constants are added when Bedrock adds blocks (binary compatible). Blocks Bedrock removes stay, deprecated, and",
            "resolve to {@code minecraft:unknown}; renamed blocks keep their old constant, deprecated, as an alias of the new one."));
        doc.addAll(sinceDoc(oldest));
        doc.addAll(PREVIEW_DOC);
        doc.add("");
        doc.add("@since " + CLASS_SINCE);
        TypeSpec.Builder type = classType("BedrockBlocks", doc);
        List<Constant> aliases = new ArrayList<>();
        for (Constant constant : constants) {
            if (constant.replacement() != null) {
                aliases.add(constant);
                continue;
            }
            BlockLayout layout = layouts.get(constant.identifier());
            StringBuilder first = new StringBuilder("{@code " + constant.identifier() + "}");
            if (layout != null) {
                List<String> stateLinks = new ArrayList<>();
                for (String state : layout.properties()) {
                    StateConstant stateConstant = states.byName.get(state);
                    stateLinks.add(stateConstant == null ? "{@code " + state + "}" : "{@link BedrockStates#" + stateConstant.constant + "}");
                }
                if (!stateLinks.isEmpty()) {
                    first.append(": ").append(String.join(", ", stateLinks));
                }
                first.append(stateLinks.isEmpty() ? ", " : "; ").append(layout.count()).append(layout.count() == 1 ? " state" : " states");
                if (!layout.arithmetic()) {
                    first.append(" (").append(layout.problem()).append(": resolved with a lookup table)");
                }
                first.append('.');
            } else {
                first.append(", no longer in the bundled data.");
            }
            List<String> memberDoc = memberDoc(first.toString(), constant);
            if (constant.deprecated() != null) {
                memberDoc.add("@deprecated Bedrock removed the block; resolves to {@code minecraft:unknown}");
            }
            ConstantsGenerator.PreviewStates preview = constant.preview() == null ? null : previewStates.get(constant.identifier());
            CodeBlock value;
            if (preview != null) {
                // No release has the block: the constant carries the preview's states, so a release palette needs no preview data
                CodeBlock.Builder call = CodeBlock.builder().add("$T.previewBlock($S, $L$>", VANILLA_TYPES, constant.identifier(), preview.defaultOffset());
                for (int p = 0; p < preview.properties().size(); p++) {
                    call.add(",\n$T.property($S", VANILLA_TYPES, preview.properties().get(p));
                    for (Object property : preview.values().get(p)) {
                        call.add(", $L", literal(property));
                    }
                    call.add(")");
                }
                value = call.add("$<)").build();
            } else {
                value = CodeBlock.of("$T.$L($S)", VANILLA_TYPES, constant.education() ? "educationBlock" : "block", constant.identifier());
            }
            type.addField(constantField(BEDROCK_BLOCK_TYPE, constant, memberDoc).initializer(value).build());
        }
        addAliases(type, aliases, constants, BEDROCK_BLOCK_TYPE);
        type.addMethod(privateConstructor());
        return file(ConstantsGenerator.PACKAGE, type.build());
    }

    static String items(List<Constant> constants, Map<String, Integer> variants, String version, String oldest) {
        List<String> doc = new ArrayList<>(List.of(
            "Every item type of Bedrock " + version + ", the newest bundled release. The constants are resolved against",
            "the newest data of {@link dev.opencollab.paletter.Paletter#bundled()} on first use; referencing them loads nothing.",
            "Variants that differ by damage are {@link BedrockItemType#variant(int)}; the named ones are the constants of",
            "{@link BedrockItemVariants}.",
            "<p>",
            "Constants are added when Bedrock adds items (binary compatible). Items Bedrock removes stay, deprecated, and",
            "resolve to {@code minecraft:unknown}; renamed items keep their old constant, deprecated, as an alias of the new one."));
        doc.addAll(sinceDoc(oldest));
        doc.addAll(PREVIEW_DOC);
        doc.add("");
        doc.add("@since " + CLASS_SINCE);
        TypeSpec.Builder type = classType("BedrockItems", doc);
        List<Constant> aliases = new ArrayList<>();
        for (Constant constant : constants) {
            if (constant.replacement() != null) {
                aliases.add(constant);
                continue;
            }
            Integer count = variants.get(constant.identifier());
            String first = "{@code " + constant.identifier() + "}" + (constant.deprecated() != null ? ", no longer in the bundled data."
                : count != null ? ": " + count + " more variants by damage, see {@link BedrockItemType#variant(int)}." : ".");
            List<String> memberDoc = memberDoc(first, constant);
            if (constant.deprecated() != null) {
                memberDoc.add("@deprecated Bedrock removed the item; resolves to {@code minecraft:unknown}");
            }
            type.addField(constantField(BEDROCK_ITEM_TYPE, constant, memberDoc)
                .initializer("$T.$L($S)", VANILLA_TYPES, constant.education() ? "educationItem" : "item", constant.identifier()).build());
        }
        addAliases(type, aliases, constants, BEDROCK_ITEM_TYPE);
        type.addMethod(privateConstructor());
        return file(ConstantsGenerator.PACKAGE, type.build());
    }

    /**
     * {@code BedrockExperiments}: one String constant per toggle that a captured build had current, with {@code @BedrockSince}
     * and {@code @BedrockUntil} naming the bundled data versions. A toggle first seen in a preview has
     * {@code @SincePreview} instead (the constant goes if a newer preview drops it); only a release capture ends a toggle.
     */
    static String experiments(List<ExperimentToggles.Toggle> toggles, String oldest) {
        List<String> doc = List.of(
            "The experiment toggles of Bedrock: the ids to give {@code VanillaContent#experiments(String...)} and what",
            "{@link dev.opencollab.paletter.annotation.BedrockExperiment @BedrockExperiment} names. Every toggle a captured",
            "Bedrock Dedicated Server had current is here ({@code data/bds}); toggles retired before the oldest capture are not.",
            "{@code @BedrockSince} is the first bundled data version whose capture has the toggle ({@code " + oldest + "} is the oldest, so it may be older),",
            "{@code @BedrockUntil} the first bundled release where it no longer does: Bedrock released or retired the experiment, and the",
            "toggle does nothing. {@link dev.opencollab.paletter.annotation.SincePreview @SincePreview} marks a toggle only a bundled preview has.",
            "",
            "@since " + CLASS_SINCE);
        TypeSpec.Builder type = classType("BedrockExperiments", doc);
        for (ExperimentToggles.Toggle toggle : toggles) {
            FieldSpec.Builder field = FieldSpec.builder(String.class, toggle.id().toUpperCase(Locale.ROOT), CONSTANT)
                .addJavadoc(javadoc(List.of("{@code " + toggle.id() + "}" + (toggle.name() != null ? ": " + toggle.name() + "." : ""))))
                .addAnnotation(toggle.sincePreview() ? sincePreview(toggle.since())
                    : AnnotationSpec.builder(BEDROCK_SINCE).addMember("value", "$S", toggle.since()).build());
            if (toggle.until() != null) {
                field.addAnnotation(AnnotationSpec.builder(BEDROCK_UNTIL).addMember("value", "$S", toggle.until()).build());
            }
            type.addField(field.initializer("$S", toggle.id()).build());
        }
        type.addMethod(privateConstructor());
        return file(ConstantsGenerator.PACKAGE, type.build());
    }

    /**
     * @param itemNames item identifier to the name of its {@code BedrockItems} constant
     */
    static String variants(List<Variant> variants, Map<String, String> itemNames, String version) {
        List<String> doc = new ArrayList<>();
        List<String> families = variants.stream().map(Variant::constant).filter(c -> c.replacement() == null && c.deprecated() == null)
            .map(c -> "{@link BedrockItems#" + itemName(itemNames, c.identifier()) + "}").distinct().sorted().toList();
        String intro = "The named aux variants of Bedrock " + version + ", the newest bundled release";
        if (families.isEmpty()) {
            doc.add(intro + ".");
        } else {
            // The items wrap by words: a line stays within 110 characters of the comment
            doc.add(intro + ", of the items");
            StringBuilder line = new StringBuilder(" *");
            for (int i = 0; i < families.size(); i++) {
                String word = families.get(i) + (i == families.size() - 1 ? "." : ",");
                if (line.length() + word.length() > 110) {
                    doc.add(line.substring(3));
                    line = new StringBuilder(" *");
                }
                line.append(' ').append(word);
            }
            doc.add(line.substring(3));
        }
        doc.addAll(List.of(
            "The names are BDS's own spellings, taken from the Script API (the potion effect id, the localization key of the",
            "stack). Every constant is the very {@link BedrockItemVariant} of {@code type.variant(aux)}. Referencing them loads",
            "nothing.",
            "<p>",
            "Constants are added when Bedrock adds variants (binary compatible). A variant Bedrock removes keeps its constant,",
            "deprecated: {@code type.variant(aux)} is then a plain variant, equal to the constant. A name BDS changes stays as a deprecated alias of the new one.",
            "<p>",
            "{@code @since} is the Paletter version that added a constant, only written if newer than the class. The",
            "names come from BDS dumps of the newest builds only, so a variant says nothing of the Bedrock release it is first in: it may be older than the dumps.",
            "{@link dev.opencollab.paletter.annotation.SincePreview @SincePreview} marks variants only the bundled Bedrock preview",
            "has: the constants are linked to the newest release, so its type has no such variant and {@code type.variant(aux)}",
            "is a plain variant and the constant stays a plain key. The mark goes when a release has it; the constant goes if a newer",
            "preview drops it.",
            "",
            "@since " + CLASS_SINCE));
        TypeSpec.Builder type = classType("BedrockItemVariants", doc);
        List<Variant> aliases = new ArrayList<>();
        for (Variant variant : variants) {
            Constant constant = variant.constant();
            if (constant.replacement() != null) {
                aliases.add(variant);
                continue;
            }
            List<String> memberDoc = new ArrayList<>();
            memberDoc.add("{@code " + constant.identifier() + "} with aux " + variant.aux() + (constant.deprecated() != null ? ", no longer in the bundled data." : "."));
            if (constant.preview() != null) {
                memberDoc.add("Only in the bundled preview " + constant.preview() + ".");
            } else {
                since(memberDoc, constant.since());
            }
            if (constant.deprecated() != null) {
                memberDoc.add("@deprecated Bedrock removed the variant");
            }
            type.addField(constantField(BEDROCK_ITEM_VARIANT, constant, memberDoc)
                .initializer("$T.variant($T.$L, $L)", VANILLA_TYPES, BEDROCK_ITEMS, itemName(itemNames, constant.identifier()), variant.aux()).build());
        }
        // Aliases come last: a static final field cannot refer to one declared after it
        for (Variant alias : aliases) {
            Constant constant = alias.constant();
            List<String> memberDoc = new ArrayList<>();
            memberDoc.add("{@code " + constant.identifier() + "} with aux " + alias.aux() + ".");
            since(memberDoc, constant.since());
            memberDoc.add("@deprecated renamed to {@link #" + constant.replacement() + "}");
            type.addField(constantField(BEDROCK_ITEM_VARIANT, constant, memberDoc).initializer("$L", constant.replacement()).build());
        }
        type.addMethod(privateConstructor());
        return file(ConstantsGenerator.PACKAGE, type.build());
    }

    /** A block state value as a Java literal of its NBT type: {@code (byte) 1}, {@code 3} or {@code "north"}. */
    static String literal(Object value) {
        return switch (value) {
            case Byte b -> "(byte) " + b;
            case Integer i -> i.toString();
            case String s -> '"' + s.replace("\\", "\\\\").replace("\"", "\\\"") + '"';
            default -> throw new IllegalStateException("A block state value of type " + value.getClass().getSimpleName() + ": " + value);
        };
    }

