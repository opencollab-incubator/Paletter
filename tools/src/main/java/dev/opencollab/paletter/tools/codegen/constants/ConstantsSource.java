    /** The version the classes themselves appeared in; members only get a {@code @since} of their own if newer. */
    static final String CLASS_SINCE = "1.0.0";
    /** How the header of every generated file starts: also how {@link Main} recognizes the files it owns. */
    static final String GENERATOR = "// Generated by :tools:generateConstants";
    private static final String HEADER = "Generated by :tools:generateConstants from the bundled data and\n"
        + "data/model/constants-history.json. Do not edit; see docs/data-pipeline.md.";

    private static final ClassName NON_NULL = ClassName.get("org.checkerframework.checker.nullness.qual", "NonNull");
    private static final ClassName NULLABLE = ClassName.get("org.checkerframework.checker.nullness.qual", "Nullable");
    private static final ClassName EDUCATION = ClassName.get("dev.opencollab.paletter.annotation", "Education");
    private static final ClassName SINCE_PREVIEW = ClassName.get("dev.opencollab.paletter.annotation", "SincePreview");
    private static final ClassName BEDROCK_SINCE = ClassName.get("dev.opencollab.paletter.annotation", "BedrockSince");
    private static final ClassName BEDROCK_UNTIL = ClassName.get("dev.opencollab.paletter.annotation", "BedrockUntil");
    private static final ClassName STATE_VALUE = vanilla("StateValue");
    private static final ClassName VANILLA_TYPES = vanilla("VanillaTypes");
    private static final ClassName BEDROCK_STATE = vanilla("BedrockState");
    private static final ClassName BEDROCK_ITEMS = vanilla("BedrockItems");
    private static final ClassName BEDROCK_BLOCK_TYPE = vanilla("BedrockBlockType");
    private static final ClassName BEDROCK_ITEM_TYPE = vanilla("BedrockItemType");
    private static final ClassName BEDROCK_ITEM_VARIANT = vanilla("BedrockItemVariant");
    private static final Modifier[] CONSTANT = {Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL};

    private ConstantsSource() {
    }

    private static ClassName vanilla(String name) {
        return ClassName.get(ConstantsGenerator.PACKAGE, name);
    }

