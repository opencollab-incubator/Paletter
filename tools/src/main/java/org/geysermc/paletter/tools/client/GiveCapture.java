package org.geysermc.paletter.tools.client;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Function;

/**
 * Which item the client is given for a block: the capture runs {@code /give @s <identifier>} in a start of its own, for the block
 * identifier and for the bundled item identifier of each pair, and records the item (and the inventory slot) of the inventory slot
 * packet the server answers with, or that a command error answered. Evidence for {@code Palette#itemOf}, whose answer for a vanilla
 * block comes from the bundled block to item relation.
 * <p>
 * Only the blocks whose item has another identifier are given ({@link #blocks}): the others say nothing about the relation.
 * An identifier the server did not answer for is absent: that is "unverified", never a failure; one answered with a command error is
 * "rejected" (a block that is no item, probably). Whether {@code /give} takes a block identifier is unverified; the recapture settles it.
 */
public final class GiveCapture {
    public static final String FILE = "block-items.json";
    static final String REJECTED = "rejected";
    static final String GENERATED = "Generated by `update` (tools, GiveCapture) from /give in a start of its own; the pairs are the bundled "
        + "block to item relation where the identifiers differ. Do not edit: run `update` for the build again.";
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();

    private GiveCapture() {
    }

    /** What one {@code /give} answered: an item in a slot, or (item null) a command error. */
    public record Given(String item, int slot) {
        public static final Given REJECTED = new Given(null, -1);

        public boolean rejected() {
            return item == null;
        }
    }

    /** One pair of the file: the block, the item the data says, and what each identifier gave ({@code null}: no answer). */
    public record Entry(String block, String item, Given givenForBlock, Given givenForItem) {
    }

    /** The blocks to give: those whose item has another identifier, sorted. */
    public static List<String> blocks(Map<String, String> blockItems) {
        return blockItems.entrySet().stream().filter(e -> !e.getKey().equals(e.getValue())).map(Map.Entry::getKey).sorted().toList();
    }

    /** The identifiers to give: every block of {@link #blocks}, then their items, each once. */
    public static List<String> identifiers(Map<String, String> blockItems) {
        Set<String> identifiers = new LinkedHashSet<>(blocks(blockItems));
        blocks(blockItems).forEach(block -> identifiers.add(blockItems.get(block)));
        return List.copyOf(identifiers);
    }

    public static String render(String build, Map<String, String> blockItems, Map<String, Given> gives) {
        JsonObject json = new JsonObject();
        json.addProperty("_generated", GENERATED);
        json.addProperty("bdsVersion", build);
        JsonArray entries = new JsonArray();
        for (String block : blocks(blockItems)) {
            JsonObject entry = new JsonObject();
            entry.addProperty("block", block);
            entry.addProperty("item", blockItems.get(block));
            put(entry, "givenForBlock", gives.get(block));
            put(entry, "givenForItem", gives.get(blockItems.get(block)));
            entries.add(entry);
        }
        json.add("entries", entries);
        return GSON.toJson(json) + "\n";
    }

    private static void put(JsonObject entry, String name, Given given) {
        if (given == null) {
            return;
        }
        if (given.rejected()) {
            entry.addProperty(name, REJECTED);
            return;
        }
        JsonObject json = new JsonObject();
        json.addProperty("item", given.item());
        json.addProperty("slot", given.slot());
        entry.add(name, json);
    }

    public static List<Entry> read(Path file) throws IOException {
        JsonObject json = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject();
        List<Entry> entries = new ArrayList<>();
        for (JsonElement element : json.getAsJsonArray("entries")) {
            JsonObject entry = element.getAsJsonObject();
            entries.add(new Entry(entry.get("block").getAsString(), entry.get("item").getAsString(),
                given(entry.get("givenForBlock")), given(entry.get("givenForItem"))));
        }
        return entries;
    }

    private static Given given(JsonElement element) {
        if (element == null) {
            return null;
        }
        if (element.isJsonPrimitive()) {
            return Given.REJECTED;
        }
        return new Given(element.getAsJsonObject().get("item").getAsString(), element.getAsJsonObject().get("slot").getAsInt());
    }

    /**
     * The answers checked against an {@code itemOf}: no answer is unverified, a command error is rejected (evidence, no mismatch), an
     * item that differs from the answer is a mismatch.
     */
    public record Check(int matched, List<String> mismatches, List<String> unverified, List<String> rejected) {
    }

    /** @param itemOf the identifier of the item for a block identifier, or null */
    public static Check check(List<Entry> entries, Function<String, String> itemOf) {
        int[] matched = {0};
        List<String> mismatches = new ArrayList<>();
        List<String> unverified = new ArrayList<>();
        List<String> rejected = new ArrayList<>();
        for (Entry entry : entries) {
            String expected = itemOf.apply(entry.block());
            for (String kind : List.of("block", "item")) {
                Given given = kind.equals("block") ? entry.givenForBlock() : entry.givenForItem();
                String identifier = kind.equals("block") ? entry.block() : entry.item();
                String name = identifier + " (" + kind + " of " + entry.block() + ")";
                if (given == null) {
                    unverified.add(name);
                } else if (given.rejected()) {
                    rejected.add(name);
                } else if (given.item().equals(expected)) {
                    matched[0]++;
                } else {
                    mismatches.add(name + ": the client got " + given.item() + " (slot " + given.slot() + "), expected " + expected);
                }
            }
        }
        return new Check(matched[0], mismatches, unverified, rejected);
    }
}
