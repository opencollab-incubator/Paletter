package org.geysermc.paletter.tools.shape;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.cloudburstmc.protocol.bedrock.data.SerializableVoxelShape;
import org.cloudburstmc.protocol.bedrock.packet.VoxelShapesPacket;
import org.geysermc.paletter.block.BlockRegistry;
import org.geysermc.paletter.internal.data.PaletteDataCodec;
import org.geysermc.paletter.internal.shape.VoxelGrid;
import org.geysermc.paletter.internal.shape.VoxelShapeStore;
import org.geysermc.paletter.tools.Layout;
import org.geysermc.paletter.tools.client.VoxelShapeCapture;
import org.geysermc.paletter.tools.codegen.constants.ConstantsGenerator;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Stream;
import java.util.zip.GZIPInputStream;

/**
 * {@code voxel-shapes import}: the captures of {@code data/bds/<build>/voxel-shapes} ({@link ShapeProbe}) to the
 * bundled {@code voxel_shapes.nbt} ({@link VoxelShapeStore}). Per bundled data version, from the newest capture of its
 * protocols:
 * <ul>
 *     <li>the shapes and names of the vanilla packet, as sent;</li>
 *     <li>for every shape without a name the vanilla block BDS makes it for, read from the anchor capture: the shape
 *     comes after the shape BDS derived for the anchor before that block and before the one of the next anchor.</li>
 * </ul>
 * Nothing here is typed in: a shape the anchors do not place fails the import.
 */
public final class ShapeImport {
    public static final String FILE = org.geysermc.paletter.tools.data.BundledFiles.VOXEL_SHAPES;
    static final String GENERATED = "Generated by `voxel-shapes import` (:tools:run) from data/bds/*/voxel-shapes; do not edit by hand";

    private ShapeImport() {
    }

    /** One capture directory, read. */
    public record Captured(String bdsVersion, int protocol, Path directory) {
        public VoxelShapesPacket packet(String name) throws IOException {
            return VoxelShapeCapture.read(directory.resolve(name + ".json"));
        }

        public boolean has(String file) {
            return Files.exists(directory.resolve(file));
        }

        /**
         * The anchor capture: {@code anchors} (block, before, box) and {@code packet}.
         *
         * @param experiment the capture with the experiment on; the other one is only stored where it differs
         */
        public JsonObject anchors(boolean experiment) throws IOException {
            String file = !experiment && has("anchors-plain.json.gz") ? "anchors-plain.json.gz" : "anchors.json.gz";
            try (InputStream stream = new GZIPInputStream(Files.newInputStream(directory.resolve(file)))) {
                return JsonParser.parseReader(new InputStreamReader(stream, StandardCharsets.UTF_8)).getAsJsonObject();
            }
        }
    }

    /** The voxel shape captures under {@code data/bds}, oldest protocol first. */
    public static List<Captured> captures(Path root) throws IOException {
        List<Captured> captures = new ArrayList<>();
        try (Stream<Path> builds = Files.list(root.resolve(Layout.BDS))) {
            for (Path build : builds.sorted().toList()) {
                Path directory = build.resolve(ShapeProbe.DIRECTORY);
                if (Files.exists(directory.resolve("capture.json"))) {
                    JsonObject metadata = JsonParser.parseString(Files.readString(directory.resolve("capture.json"))).getAsJsonObject();
                    captures.add(new Captured(metadata.get("bdsVersion").getAsString(), metadata.get("protocol").getAsInt(), directory));
                }
            }
        }
        captures.sort(Comparator.comparingInt(Captured::protocol).thenComparing(Captured::bdsVersion));
        return captures;
    }

    /** The store the captures give: one registry per run of bundled versions with the same shapes. */
    public static VoxelShapeStore store(Path root) throws IOException {
        Path data = root.resolve(ConstantsGenerator.DATA);
        List<ConstantsGenerator.Bundle> bundles = ConstantsGenerator.readIndex(data);
        Map<String, Captured> byVersion = new TreeMap<>();
        for (Captured capture : captures(root)) {
            ConstantsGenerator.Bundle version = null;
            for (ConstantsGenerator.Bundle bundle : bundles) {
                if (bundle.protocol() <= capture.protocol()) {
                    version = bundle;
                }
            }
            if (version != null) {
                // The newest capture of a version wins
                byVersion.put(version.name(), capture);
            }
        }
        List<VoxelShapeStore.Registry> registries = new ArrayList<>();
        for (ConstantsGenerator.Bundle bundle : bundles) {
            Captured capture = byVersion.get(bundle.name());
            if (capture == null) {
                continue;
            }
            List<String> blocks;
            try (InputStream stream = Files.newInputStream(data.resolve(bundle.name() + ".nbt"))) {
                blocks = PaletteDataCodec.read(stream).blockStates().stream().map(state -> state.getString("name")).toList();
            }
            add(registries, bundle.name(), false, entries(capture, false, blocks));
            if (capture.has("experiment.json")) {
                add(registries, bundle.name(), true, entries(capture, true, blocks));
            }
        }
        return new VoxelShapeStore(registries);
    }

    /** Adds the registry of a version: to the newest registry of its kind if that has the same shapes. */
    private static void add(List<VoxelShapeStore.Registry> registries, String version, boolean experiment, List<VoxelShapeStore.Entry> shapes) {
        for (int i = registries.size() - 1; i >= 0; i--) {
            VoxelShapeStore.Registry registry = registries.get(i);
            if (registry.experiment() == experiment) {
                if (registry.shapes().equals(shapes)) {
                    List<String> versions = new ArrayList<>(registry.versions());
                    versions.add(version);
                    registries.set(i, new VoxelShapeStore.Registry(versions, experiment, shapes));
                    return;
                }
                break;
            }
        }
        registries.add(new VoxelShapeStore.Registry(List.of(version), experiment, shapes));
    }

    /**
     * The vanilla registry of a capture.
     *
     * @param experiment the registry of the world with the experiment on ({@code experiment.json})
     * @param vanillaBlocks the names of the vanilla blocks of the capture's version
     */
    public static List<VoxelShapeStore.Entry> entries(Captured capture, boolean experiment, List<String> vanillaBlocks) throws IOException {
        VoxelShapesPacket vanilla = capture.packet(experiment ? "experiment" : "vanilla");
        if (vanilla.getCustomShapeCount() != 0) {
            throw new IOException("The vanilla capture of BDS " + capture.bdsVersion() + " counts " + vanilla.getCustomShapeCount() + " custom shapes");
        }
        Map<Integer, String> names = new HashMap<>();
        for (Map.Entry<String, Integer> name : vanilla.getNameMap().entrySet()) {
            if (names.put(name.getValue(), name.getKey()) != null) {
                throw new IOException("Two names for the vanilla shape " + name.getValue() + " of BDS " + capture.bdsVersion());
            }
        }
        List<SerializableVoxelShape> shapes = vanilla.getShapes();
        List<VoxelShapeStore.Entry> entries = new ArrayList<>();
        if (names.size() == shapes.size()) {
            // Every shape has a name: BDS makes none for blocks, and the anchors have nothing to say
            for (int i = 0; i < shapes.size(); i++) {
                entries.add(new VoxelShapeStore.Entry(VoxelGrid.ofWire(shapes.get(i)), names.get(i), null, null));
            }
            return entries;
        }
        // Where BDS was in its walk over the blocks: the ids of the shapes it derived for the anchors
        JsonObject anchorCapture = capture.anchors(experiment);
        Map<VoxelGrid, Integer> anchored = new HashMap<>();
        for (SerializableVoxelShape shape : VoxelShapeCapture.packet(anchorCapture.getAsJsonObject("packet")).getShapes()) {
            anchored.put(VoxelGrid.ofWire(shape), anchored.size());
        }
        List<String> sorted = new ArrayList<>(new TreeSet<>(vanillaBlocks));
        sorted.sort(Comparator.comparing(BlockRegistry::nameHash, Long::compareUnsigned));
        // Marker id and the index (in sorted) of the vanilla block the anchor is in front of
        List<int[]> markers = new ArrayList<>();
        for (JsonElement element : anchorCapture.getAsJsonArray("anchors")) {
            JsonObject anchor = element.getAsJsonObject();
            float[] box = new float[6];
            for (int i = 0; i < 6; i++) {
                box[i] = anchor.getAsJsonArray("box").get(i).getAsFloat() / 16;
            }
            // The shape of the north face of the anchor's shape: only this anchor has it
            Integer marker = anchored.get(VoxelGrid.ofBoxes(box).faces()[2]);
            if (marker == null) {
                throw new IOException("BDS " + capture.bdsVersion() + " sent no shape for the anchor " + anchor.get("block").getAsString());
            }
            // The anchor after the last vanilla block has no "before"
            int before = anchor.has("before") ? sorted.indexOf(anchor.get("before").getAsString()) : sorted.size();
            if (before < 0 || !markers.isEmpty() && (markers.getLast()[0] >= marker || markers.getLast()[1] >= before)) {
                throw new IOException("The anchors of BDS " + capture.bdsVersion() + " are not in the order of the block name hashes at "
                    + anchor.get("block").getAsString());
            }
            markers.add(new int[] {marker, before});
        }

        for (int i = 0; i < shapes.size(); i++) {
            VoxelGrid grid = VoxelGrid.ofWire(shapes.get(i));
            if (names.containsKey(i)) {
                entries.add(new VoxelShapeStore.Entry(grid, names.get(i), null, null));
                continue;
            }
            Integer position = anchored.get(grid);
            if (position == null) {
                throw new IOException("The anchor capture of BDS " + capture.bdsVersion() + " lacks the vanilla shape " + i);
            }
            // The blocks from the anchor before the shape to the next anchor
            int first = 0;
            int end = sorted.size();
            for (int[] marker : markers) {
                if (marker[0] < position) {
                    first = marker[1];
                } else {
                    end = marker[1];
                    break;
                }
            }
            if (first >= end) {
                throw new IOException("BDS " + capture.bdsVersion() + " made the vanilla shape " + i + " after the last vanilla block");
            }
            entries.add(new VoxelShapeStore.Entry(grid, null, sorted.get(first), sorted.get(end - 1)));
        }
        return entries;
    }

    public static byte[] bytes(Path root) throws IOException {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        store(root).write(bytes, GENERATED);
        return bytes.toByteArray();
    }

    /** Writes the bundled file. */
    public static void run(Path root) throws IOException {
        Path file = root.resolve(ConstantsGenerator.DATA).resolve(FILE);
        Files.write(file, bytes(root));
        VoxelShapeStore store = store(root);
        for (VoxelShapeStore.Registry registry : store.registries()) {
            long ambiguous = registry.shapes().stream().filter(entry -> entry.block() != null && !entry.block().equals(entry.lastBlock())).count();
            System.out.println(registry.versions() + (registry.experiment() ? " with the experiment" : "") + ": " + registry.shapes().size() + " shapes, "
                + registry.shapes().stream().filter(entry -> entry.name() != null).count() + " named; " + ambiguous
                + " made for one of several blocks with neighbouring hashes");
        }
        System.out.println("Wrote " + root.relativize(file));
    }

    /** @return whether the bundled file is what the captures give */
    public static boolean check(Path root) throws IOException {
        Path file = root.resolve(ConstantsGenerator.DATA).resolve(FILE);
        return Files.exists(file) && Arrays.equals(Files.readAllBytes(file), bytes(root));
    }
}
