package org.geysermc.paletter.tools.bds;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * The versions of the {@code @minecraft/server} Script API module a BDS build has, as its own documentation generator lists them
 * ({@code docs/script_modules}). {@code update} writes them to {@code data/bds/<build>/script-modules.json}; an add-on that needs the
 * beta module reads the file: no lookup elsewhere, and a build without the file fails (the add-on cannot be run without a module).
 *
 * <p>The layout of {@code docs/script_modules} is read as either {@code @minecraft/server/<version>} or {@code @minecraft/server_<version>}
 * (a directory or a file of that name). TODO: unverified against a real docgen tree (none is committed or cached); a run that finds
 * none fails and names what it found, so the first recapture settles it.
 */
public final class ScriptModules {
    public static final String FILE = "script-modules.json";
    private static final String MODULE = "@minecraft/server";
    private static final Pattern VERSION = Pattern.compile("\\d+\\.\\d+\\.\\d+(?:-[a-z]+)?");
    private static final Pattern NAMED = Pattern.compile("(?:@minecraft[/_])?server[_@-](" + VERSION.pattern() + ")(?:\\..*)?");
    static final String GENERATED = "Generated by `update` (tools, ScriptModules) from the script_modules BDS's documentation generator writes. "
        + "Do not edit: run `update` for the build again.";

    private ScriptModules() {
    }

    /**
     * The module versions in a docgen tree, sorted (by {@link #compare}).
     *
     * @throws IOException if the tree has none (the message lists what is under {@code script_modules})
     */
    public static List<String> parse(Path docs) throws IOException {
        Path modules = docs.resolve("script_modules");
        TreeSet<String> versions = new TreeSet<>(ScriptModules::compare);
        if (Files.isDirectory(modules)) {
            try (Stream<Path> walk = Files.walk(modules, 4)) {
                for (Path path : (Iterable<Path>) walk::iterator) {
                    Matcher named = NAMED.matcher(path.getFileName().toString());
                    if (named.matches()) {
                        versions.add(named.group(1));
                    } else if (path.getParent() != null && path.getParent().endsWith(MODULE) && Files.isDirectory(path)
                        && VERSION.matcher(path.getFileName().toString()).matches()) {
                        versions.add(path.getFileName().toString());
                    }
                }
            }
        }
        if (versions.isEmpty()) {
            List<String> found = new ArrayList<>();
            if (Files.isDirectory(modules)) {
                try (Stream<Path> list = Files.list(modules)) {
                    list.forEach(p -> found.add(p.getFileName().toString()));
                }
            }
            throw new IOException("no " + MODULE + " version under " + modules + "; found " + found);
        }
        return List.copyOf(versions);
    }

    /** {@code script-modules.json}: the build and its module versions. */
    public static String render(String build, List<String> versions) {
        JsonObject json = new JsonObject();
        json.addProperty("_generated", GENERATED);
        json.addProperty("bdsVersion", build);
        json.addProperty("module", MODULE);
        JsonArray array = new JsonArray();
        versions.forEach(array::add);
        json.add("versions", array);
        return json + "\n";
    }

    /** The versions a committed {@code script-modules.json} lists. */
    public static List<String> read(Path file) throws IOException {
        JsonObject json = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject();
        return json.getAsJsonArray("versions").asList().stream().map(JsonElement::getAsString).toList();
    }

    /** The file of a build in {@code data/bds}. */
    public static Path file(Path bdsData, String build) {
        return bdsData.resolve(build).resolve(FILE);
    }

    /** The versions of the committed file of a build; fails without it ({@code update} writes it). */
    public static List<String> versions(Path bdsData, String build) throws IOException {
        Path file = file(bdsData, build);
        if (!Files.isRegularFile(file)) {
            throw new IOException("no " + file + ": the Script API module of BDS " + build + " is not known; run update for the build");
        }
        return read(file);
    }

    /**
     * The dependency of the beta Script API: the newest {@code -beta} version of the build, as the manifest names it
     * ({@code 2.12.0-beta}).
     */
    public static String betaVersion(List<String> versions) {
        return versions.stream().filter(v -> v.endsWith("-beta")).max(ScriptModules::compare)
            .orElseThrow(() -> new IllegalStateException("the build has no beta " + MODULE + " module: " + versions));
    }

    /** Dotted versions by number, then a release before its pre-release ({@code 2.0.0-beta} before {@code 2.0.0}). */
    static int compare(String a, String b) {
        String[] p = a.split("-", 2);
        String[] q = b.split("-", 2);
        String[] x = p[0].split("\\.");
        String[] y = q[0].split("\\.");
        for (int i = 0; i < Math.max(x.length, y.length); i++) {
            int c = Integer.compare(i < x.length ? Integer.parseInt(x[i]) : 0, i < y.length ? Integer.parseInt(y[i]) : 0);
            if (c != 0) {
                return c;
            }
        }
        return p.length == q.length ? (p.length == 1 ? 0 : p[1].compareTo(q[1])) : p.length < q.length ? 1 : -1;
    }

    /** Sets the version of the manifest's {@code @minecraft/server} dependency. */
    static void setServerModule(JsonObject manifest, String version) {
        for (JsonElement dependency : manifest.getAsJsonArray("dependencies")) {
            JsonObject object = dependency.getAsJsonObject();
            if (object.has("module_name") && object.get("module_name").getAsString().equals(MODULE)) {
                object.addProperty("version", version);
            }
        }
    }
}
