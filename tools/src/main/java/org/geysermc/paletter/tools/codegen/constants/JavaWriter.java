package org.geysermc.paletter.tools.codegen.constants;

import org.geysermc.paletter.tools.codegen.constants.ConstantsGenerator.Constant;
import org.geysermc.paletter.tools.codegen.constants.ConstantsGenerator.EnumModel;
import org.geysermc.paletter.tools.codegen.constants.ConstantsGenerator.EnumValue;
import org.geysermc.paletter.tools.codegen.constants.ConstantsGenerator.Kind;
import org.geysermc.paletter.tools.codegen.constants.ConstantsGenerator.StateConstant;
import org.geysermc.paletter.tools.codegen.constants.ConstantsGenerator.StateModel;
import org.geysermc.paletter.internal.vanilla.BlockLayout;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

/**
 * Writes the constants classes.
 */
public final class JavaWriter {
    /** The version the classes themselves appeared in; members only get a {@code @since} of their own if newer. */
    static final String CLASS_SINCE = "1.0.0";
    private static final String HEADER = "// Generated by :tools:generateConstants from the bundled data, data/model/names.json and\n"
        + "// data/model/constants-history.json. Do not edit; see tools/docs/codegen.md.\n";

    private JavaWriter() {
    }

    static String enumClass(EnumModel model, String version) {
        StringBuilder out = new StringBuilder(HEADER);
        out.append("package ").append(ConstantsGenerator.STATE_PACKAGE).append(";\n\n");
        out.append("import org.checkerframework.checker.nullness.qual.NonNull;\n");
        out.append("import org.geysermc.paletter.vanilla.StateValue;\n\n");
        out.append("/**\n * Values of ");
        List<String> links = new ArrayList<>();
        for (String state : model.states) {
            links.add("{@code " + state + "}");
        }
        out.append(String.join(", ", links)).append(".\n *\n * @since ").append(model.since).append("\n */\n");
        out.append("public enum ").append(model.name).append(" implements StateValue {\n");
        List<EnumValue> values = new ArrayList<>(model.values.values());
        for (int i = 0; i < values.size(); i++) {
            EnumValue value = values.get(i);
            out.append("    /**\n     * {@code ").append(value.value()).append("}");
            if (!value.since().equals(model.since)) {
                out.append("\n     *\n     * @since ").append(value.since());
            }
            if (value.deprecated() != null) {
                out.append("\n     * @deprecated no block state has this value anymore");
            }
            out.append("\n     */\n");
            if (value.deprecated() != null) {
                out.append("    @Deprecated(since = \"").append(value.deprecated()).append("\", forRemoval = true)\n");
            }
            out.append("    ").append(value.constant()).append("(\"").append(value.value()).append("\")")
                .append(i == values.size() - 1 ? ";\n\n" : ",\n");
        }
        out.append("    private final String value;\n\n");
        out.append("    ").append(model.name).append("(String value) {\n        this.value = value;\n    }\n\n");
        out.append("    @Override\n    public @NonNull String value() {\n        return value;\n    }\n}\n");
        return out.toString();
    }

    static String states(StateModel model, String release) {
        StringBuilder out = new StringBuilder(HEADER);
        out.append("package ").append(ConstantsGenerator.PACKAGE).append(";\n\n");
        out.append("import org.checkerframework.checker.nullness.qual.NonNull;\n");
        out.append("import org.checkerframework.checker.nullness.qual.Nullable;\n");
        for (String enumName : new TreeSet<>(model.enums.keySet())) {
            out.append("import ").append(ConstantsGenerator.STATE_PACKAGE).append('.').append(enumName).append(";\n");
        }
        out.append("\n/**\n");
        out.append(" * Every block state name of Bedrock ").append(release).append(", the newest bundled release, typed: {@link BoolState} for byte\n");
        out.append(" * 0/1 states, {@link IntState} for integers, {@link EnumState} for strings, with an enum in\n");
        out.append(" * {@code org.geysermc.paletter.vanilla.state} per distinct value set (states with the same values share one). Which\n");
        out.append(" * values a block accepts is up to the block: {@link BedrockBlockType#values(BedrockState)}.\n");
        out.append(" * <p>\n * Constants are added when Bedrock adds states; states Bedrock removes stay, deprecated.\n");
        out.append(" *\n * @since ").append(CLASS_SINCE).append("\n */\n");
        out.append("public final class BedrockStates {\n");
        List<StateConstant> aliases = new ArrayList<>();
        for (StateConstant state : model.constants.values()) {
            if (state.replacement != null) {
                aliases.add(state);
                continue;
            }
            String type = switch (state.kind) {
                case BOOL -> "BoolState";
                case INT -> "IntState";
                case ENUM -> "EnumState<" + state.enumName + ">";
            };
            out.append("    /**\n     * {@code ").append(state.name).append("}");
            switch (state.kind) {
                case BOOL -> out.append(": true or false");
                case INT -> out.append(": ").append(contiguous(state.ints) ? state.ints.getFirst() + " to " + state.ints.getLast() : state.ints.toString());
                case ENUM -> out.append(": {@link ").append(state.enumName).append("}");
            }
            out.append(state.deprecated == null ? ". Used by " + state.blocks + (state.blocks == 1 ? " block." : " blocks.") : ".");
            appendSince(out, state.since, "    ");
            if (state.deprecated != null) {
                out.append("\n     * @deprecated no block of the bundled data has this state anymore");
            }
            out.append("\n     */\n");
            if (state.deprecated != null) {
                out.append("    @Deprecated(since = \"").append(state.deprecated).append("\", forRemoval = true)\n");
            }
            out.append("    public static final ").append(type).append(' ').append(state.constant).append(" = VanillaTypes.state(");
            switch (state.kind) {
                case BOOL -> out.append("BoolState.of(\"").append(state.name).append("\")");
                case INT -> {
                    if (contiguous(state.ints)) {
                        out.append("IntState.range(\"").append(state.name).append("\", ").append(state.ints.getFirst()).append(", ")
                            .append(state.ints.getLast()).append(")");
                    } else {
                        out.append("IntState.of(\"").append(state.name).append("\"");
                        state.ints.forEach(value -> out.append(", ").append(value));
                        out.append(")");
                    }
                }
                case ENUM -> out.append("EnumState.of(\"").append(state.name).append("\", ").append(state.enumName).append(".class)");
            }
            out.append(");\n\n");
        }
        for (StateConstant alias : aliases) {
            out.append("    /**\n     * {@code ").append(alias.name).append("}.");
            appendSince(out, alias.since, "    ");
            out.append("\n     * @deprecated renamed to {@link #").append(alias.replacement).append("}\n     */\n");
            out.append("    @Deprecated(since = \"").append(alias.deprecated).append("\", forRemoval = true)\n");
            StateConstant target = model.constants.get(alias.replacement);
            String type = switch (target.kind) {
                case BOOL -> "BoolState";
                case INT -> "IntState";
                case ENUM -> "EnumState<" + target.enumName + ">";
            };
            out.append("    public static final ").append(type).append(' ').append(alias.constant).append(" = ").append(alias.replacement).append(";\n\n");
        }
        out.append("    private BedrockStates() {\n    }\n\n");
        out.append("    /**\n     * @return the constant of a vanilla state name, or null if there is none\n     */\n");
        out.append("    public static @Nullable BedrockState<?> byName(@NonNull String name) {\n");
        out.append("        return VanillaTypes.STATES.get(name);\n    }\n}\n");
        return out.toString();
    }

    static String blocks(String className, List<Constant> constants, Map<String, BlockLayout> layouts, StateModel states, String version,
                         boolean preview) {
        StringBuilder out = new StringBuilder(HEADER);
        out.append("package ").append(ConstantsGenerator.PACKAGE).append(";\n\n");
        if (preview) {
            out.append("import org.geysermc.paletter.annotation.Experimental;\n\n");
        }
        out.append("/**\n");
        if (preview) {
            out.append(" * The block types of the bundled preview ").append(version).append(" that the newest release does not have. They are only\n");
            out.append(" * {@link BedrockBlockType#isAvailable() available} with previews loaded (system property {@code paletter.previews});\n");
            out.append(" * without, they resolve to {@code minecraft:unknown}. Experimental: constants move to {@link BedrockBlocks} when\n");
            out.append(" * the content is released, and disappear if the preview drops it.\n");
        } else {
            out.append(" * Every block type of Bedrock ").append(version).append(", the newest bundled release. The constants are resolved against\n");
            out.append(" * the newest data of {@link org.geysermc.paletter.Paletter#bundled()} on first use; referencing them loads nothing.\n");
            out.append(" * <p>\n * Constants are added when Bedrock adds blocks (binary compatible). Blocks Bedrock removes stay, deprecated, and\n");
            out.append(" * resolve to their fallback; renamed blocks keep their old constant, deprecated, as an alias of the new one.\n");
        }
        out.append(" *\n * @since ").append(CLASS_SINCE).append("\n */\n");
        if (preview) {
            out.append("@Experimental\n");
        }
        out.append("public final class ").append(className).append(" {\n");
        List<Constant> aliases = new ArrayList<>();
        for (Constant constant : constants) {
            if (constant.replacement() != null) {
                aliases.add(constant);
                continue;
            }
            BlockLayout layout = layouts.get(constant.identifier());
            out.append("    /**\n     * {@code ").append(constant.identifier()).append("}");
            if (layout != null) {
                List<String> stateLinks = new ArrayList<>();
                for (String state : layout.properties()) {
                    StateConstant stateConstant = states.byName.get(state);
                    stateLinks.add(stateConstant == null ? "{@code " + state + "}" : "{@link BedrockStates#" + stateConstant.constant + "}");
                }
                if (!stateLinks.isEmpty()) {
                    out.append(": ").append(String.join(", ", stateLinks));
                }
                out.append(stateLinks.isEmpty() ? ", " : "; ").append(layout.count()).append(layout.count() == 1 ? " state" : " states");
                if (!layout.arithmetic()) {
                    out.append(" (").append(layout.problem()).append(": resolved with a lookup table)");
                }
                out.append('.');
            } else {
                out.append(", no longer in the bundled data.");
            }
            if (!preview) {
                appendSince(out, constant.since(), "    ");
            }
            if (constant.deprecated() != null) {
                out.append("\n     * @deprecated Bedrock removed the block; resolves to {@code ").append(constant.fallback()).append("}");
            }
            out.append("\n     */\n");
            if (constant.deprecated() != null) {
                out.append("    @Deprecated(since = \"").append(constant.deprecated()).append("\", forRemoval = true)\n");
            }
            out.append("    public static final BedrockBlockType ").append(constant.name()).append(" = VanillaTypes.block(\"")
                .append(constant.identifier()).append('"');
            if (constant.deprecated() != null && !constant.fallback().equals("minecraft:unknown")) {
                out.append(", \"").append(constant.fallback()).append('"');
            }
            out.append(");\n\n");
        }
        appendAliases(out, aliases, constants, "BedrockBlockType");
        out.append("    private ").append(className).append("() {\n    }\n}\n");
        return out.toString();
    }

    static String items(String className, List<Constant> constants, Map<String, Integer> variants, String version, boolean preview) {
        StringBuilder out = new StringBuilder(HEADER);
        out.append("package ").append(ConstantsGenerator.PACKAGE).append(";\n\n");
        if (preview) {
            out.append("import org.geysermc.paletter.annotation.Experimental;\n\n");
        }
        out.append("/**\n");
        if (preview) {
            out.append(" * The item types of the bundled preview ").append(version).append(" that the newest release does not have. They are only\n");
            out.append(" * {@link BedrockItemType#isAvailable() available} with previews loaded (system property {@code paletter.previews});\n");
            out.append(" * without, they resolve to {@code minecraft:unknown}. Experimental: constants move to {@link BedrockItems} when\n");
            out.append(" * the content is released, and disappear if the preview drops it.\n");
        } else {
            out.append(" * Every item type of Bedrock ").append(version).append(", the newest bundled release. The constants are resolved against\n");
            out.append(" * the newest data of {@link org.geysermc.paletter.Paletter#bundled()} on first use; referencing them loads nothing.\n");
            out.append(" * Variants that differ by damage (potions, banners, ...) are {@link BedrockItemType#variant(int)}: the bundled data\n");
            out.append(" * does not name them.\n");
            out.append(" * <p>\n * Constants are added when Bedrock adds items (binary compatible). Items Bedrock removes stay, deprecated, and\n");
            out.append(" * resolve to their fallback; renamed items keep their old constant, deprecated, as an alias of the new one.\n");
        }
        out.append(" *\n * @since ").append(CLASS_SINCE).append("\n */\n");
        if (preview) {
            out.append("@Experimental\n");
        }
        out.append("public final class ").append(className).append(" {\n");
        List<Constant> aliases = new ArrayList<>();
        for (Constant constant : constants) {
            if (constant.replacement() != null) {
                aliases.add(constant);
                continue;
            }
            out.append("    /**\n     * {@code ").append(constant.identifier()).append("}");
            Integer count = variants.get(constant.identifier());
            if (constant.deprecated() != null) {
                out.append(", no longer in the bundled data.");
            } else if (count != null) {
                out.append(": ").append(count).append(" more variants by damage, see {@link BedrockItemType#variant(int)}.");
            } else {
                out.append('.');
            }
            if (!preview) {
                appendSince(out, constant.since(), "    ");
            }
            if (constant.deprecated() != null) {
                out.append("\n     * @deprecated Bedrock removed the item; resolves to {@code ").append(constant.fallback()).append("}");
            }
            out.append("\n     */\n");
            if (constant.deprecated() != null) {
                out.append("    @Deprecated(since = \"").append(constant.deprecated()).append("\", forRemoval = true)\n");
            }
            out.append("    public static final BedrockItemType ").append(constant.name()).append(" = VanillaTypes.item(\"")
                .append(constant.identifier()).append('"');
            if (constant.deprecated() != null && !constant.fallback().equals("minecraft:unknown")) {
                out.append(", \"").append(constant.fallback()).append('"');
            }
            out.append(");\n\n");
        }
        appendAliases(out, aliases, constants, "BedrockItemType");
        out.append("    private ").append(className).append("() {\n    }\n}\n");
        return out.toString();
    }

    /** Deprecated aliases come last: a static final field cannot refer to one declared after it. */
    private static void appendAliases(StringBuilder out, List<Constant> aliases, List<Constant> constants, String type) {
        for (Constant alias : aliases) {
            Constant target = constants.stream().filter(c -> c.name().equals(alias.replacement())).findFirst().orElseThrow();
            out.append("    /**\n     * {@code ").append(alias.identifier()).append("}.");
            appendSince(out, alias.since(), "    ");
            out.append("\n     * @deprecated ").append(alias.identifier().equals(target.identifier()) ? "renamed" : "Bedrock renamed it")
                .append(" to {@link #").append(alias.replacement()).append("}\n     */\n");
            out.append("    @Deprecated(since = \"").append(alias.deprecated()).append("\", forRemoval = true)\n");
            out.append("    public static final ").append(type).append(' ').append(alias.name()).append(" = ").append(alias.replacement()).append(";\n\n");
        }
    }

    private static void appendSince(StringBuilder out, String since, String indent) {
        if (!since.equals(CLASS_SINCE)) {
            out.append("\n").append(indent).append(" *\n").append(indent).append(" * @since ").append(since);
        }
    }

    private static boolean contiguous(List<Integer> values) {
        for (int i = 1; i < values.size(); i++) {
            if (values.get(i) != values.get(i - 1) + 1) {
                return false;
            }
        }
        return true;
    }

    static Kind kind(StateConstant state) {
        return state.kind;
    }
}
