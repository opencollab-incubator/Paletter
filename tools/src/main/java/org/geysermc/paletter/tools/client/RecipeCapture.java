import java.util.zip.GZIPOutputStream;

/**
 * A captured {@code CraftingDataPacket} ({@value #CRAFTING}) and {@code TrimDataPacket} ({@value #TRIM}), as BDS sent them:
 * one array per recipe list in wire order, one entry per line, nothing derived. Items are written by identifier (from the
 * capture's own item registry, never runtime ids) and block runtime ids of results as block states like the creative
 * capture; net ids, UUIDs, priorities, station tags and unlock requirements stay raw.
 */
public final class RecipeCapture {
    public static final String CRAFTING = "crafting_data.json.gz";
    public static final String TRIM = "trim_data.json";
    /** The recipe lists of the file, in wire order (the two chemistry lists are empty on BDS). */
    public static final List<String> LISTS = List.of("shaped", "shapeless", "shulker_box", "multi", "smithing_transform", "smithing_trim",
        "potion_mix", "container_mix", "material_reducer", "shaped_chemistry", "shapeless_chemistry");
    private static final String MARKER = "Generated by `capture` (:tools:run, also part of `update`) from the BDS CraftingDataPacket. Do not edit by hand";
    private static final String TRIM_MARKER = "Generated by `capture` (:tools:run, also part of `update`) from the BDS TrimDataPacket. Do not edit by hand";
    private static final Gson GSON = new Gson();

    /** Both files, parsed ({@code trim} is null if the capture has none). */
    public record Recipes(JsonObject crafting, JsonObject trim) {
        /** The entries of a recipe list ({@link #LISTS}). */
        public JsonArray list(String name) {
            return crafting.getAsJsonArray(name);
        }

        public int count(String name) {
            return list(name).size();
        }
    }

    private interface Converter<T> {
        JsonObject apply(T value) throws IOException;
    }

    private final Map<Integer, String> itemNames;
    private final IntFunction<NbtMap> blockStates;

    /**
     * @param itemNames item identifier by runtime id, for the potion and container mixes
     * @param blockStates the block state of a block runtime id (a hash), or null if unknown
     */
    public RecipeCapture(Map<Integer, String> itemNames, IntFunction<NbtMap> blockStates) {
        this.itemNames = itemNames;
        this.blockStates = blockStates;
    }

    /** Writes the files of the packets that were received (either may be null). */
    public void write(Path directory, CraftingDataPacket crafting, TrimDataPacket trim, String bdsVersion) throws IOException {
        if (crafting != null) {
            try (OutputStream out = new GZIPOutputStream(Files.newOutputStream(directory.resolve(CRAFTING)))) {
                out.write(craftingText(crafting, bdsVersion).getBytes(StandardCharsets.UTF_8));
            }
        }
        if (trim != null) {
            Files.writeString(directory.resolve(TRIM), trimText(trim, bdsVersion));
        }
    }

    public static Recipes read(Path directory) throws IOException {
        JsonObject crafting;
        try (var reader = new InputStreamReader(new GZIPInputStream(Files.newInputStream(directory.resolve(CRAFTING))), StandardCharsets.UTF_8)) {
            crafting = JsonParser.parseReader(reader).getAsJsonObject();
        }
        Path trimFile = directory.resolve(TRIM);
        JsonObject trim = Files.exists(trimFile) ? JsonParser.parseString(Files.readString(trimFile)).getAsJsonObject() : null;
        return new Recipes(crafting, trim);
    }

    // ---------------------------------------------------------------------------------------------------------------

    private String craftingText(CraftingDataPacket packet, String bdsVersion) throws IOException {
        StringBuilder text = new StringBuilder("{\n");
        text.append("  \"_generated\": ").append(GSON.toJson(MARKER)).append(",\n");
        text.append("  \"bdsVersion\": ").append(GSON.toJson(bdsVersion)).append(",\n");
        text.append("  \"cleanRecipes\": ").append(packet.isCleanRecipes());
        list(text, "shaped", packet.getShapedData(), this::shaped);
        list(text, "shapeless", packet.getShapelessData(), this::shapeless);
        list(text, "shulker_box", packet.getShapelessUserData(), this::shapeless);
        list(text, "multi", packet.getMultiData(), this::multi);
        list(text, "smithing_transform", packet.getSmithingTransformData(), this::smithingTransform);
        list(text, "smithing_trim", packet.getSmithingTrimData(), this::smithingTrim);
        list(text, "potion_mix", packet.getPotionMixData(), this::potionMix);
        list(text, "container_mix", packet.getContainerMixData(), this::containerMix);
        list(text, "material_reducer", packet.getMaterialReducers(), this::materialReducer);
        list(text, "shaped_chemistry", packet.getShapedChemistryData(), this::shaped);
        list(text, "shapeless_chemistry", packet.getShapelessChemistryData(), this::shapeless);
        return text.append("\n}\n").toString();
    }

    private static String trimText(TrimDataPacket packet, String bdsVersion) throws IOException {
        StringBuilder text = new StringBuilder("{\n");
        text.append("  \"_generated\": ").append(GSON.toJson(TRIM_MARKER)).append(",\n");
        text.append("  \"bdsVersion\": ").append(GSON.toJson(bdsVersion));
        list(text, "patterns", packet.getPatterns(), (TrimPattern pattern) -> {
            JsonObject json = new JsonObject();
            json.addProperty("itemName", pattern.getItemName());
            json.addProperty("patternId", pattern.getPatternId());
            return json;
        });
        list(text, "materials", packet.getMaterials(), (TrimMaterial material) -> {
            JsonObject json = new JsonObject();
            json.addProperty("materialId", material.getMaterialId());
            json.addProperty("color", material.getColor());
            json.addProperty("itemName", material.getItemName());
            return json;
        });
        return text.append("\n}\n").toString();
    }

    /** One array, one entry per line, so a diff of two builds shows the recipes that changed. */
    private static <T> void list(StringBuilder text, String name, List<T> entries, Converter<T> converter) throws IOException {
        text.append(",\n  ").append(GSON.toJson(name)).append(": [");
        String separator = "\n";
        for (T entry : entries) {
            text.append(separator).append("    ").append(GSON.toJson(converter.apply(entry)));
            separator = ",\n";
        }
        text.append(entries.isEmpty() ? "]" : "\n  ]");
    }

    private JsonObject shaped(ShapedRecipeData recipe) throws IOException {
        JsonObject json = new JsonObject();
        json.addProperty("id", recipe.getId());
        json.addProperty("width", recipe.getWidth());
        json.addProperty("height", recipe.getHeight());
        crafting(json, recipe);
        json.addProperty("assumeSymmetry", recipe.isAssumeSymetry());
        json.add("unlock", unlock(recipe.getRequirement()));
        return json;
    }

    private JsonObject shapeless(ShapelessRecipeData recipe) throws IOException {
        JsonObject json = new JsonObject();
        json.addProperty("id", recipe.getId());
        crafting(json, recipe);
        json.add("unlock", unlock(recipe.getRequirement()));
        return json;
    }

    /** Ingredients, results, UUID, station tag, priority and net id of a recipe on a crafting grid. */
    private void crafting(JsonObject json, CraftingRecipeData recipe) throws IOException {
        json.add("ingredients", descriptors(recipe.getIngredients()));
        JsonArray results = new JsonArray();
        for (ItemData result : recipe.getResults()) {
            results.add(item(result));
        }
        json.add("results", results);
        json.addProperty("uuid", String.valueOf(recipe.getUuid()));
        json.addProperty("tag", recipe.getTag());
        json.addProperty("priority", recipe.getPriority());
        json.addProperty("netId", recipe.getNetId());
    }

    private JsonObject multi(MultiRecipeData recipe) {
        JsonObject json = new JsonObject();
        json.addProperty("uuid", String.valueOf(recipe.getUuid()));
        json.addProperty("netId", recipe.getNetId());
        return json;
    }

    private JsonObject smithingTransform(SmithingTransformRecipeData recipe) throws IOException {
        JsonObject json = new JsonObject();
        json.addProperty("id", recipe.getId());
        json.add("template", descriptor(recipe.getTemplate()));
        json.add("base", descriptor(recipe.getBase()));
        json.add("addition", descriptor(recipe.getAddition()));
        json.add("result", item(recipe.getResult()));
        json.addProperty("tag", recipe.getTag());
        json.addProperty("netId", recipe.getNetId());
        return json;
    }

    private JsonObject smithingTrim(SmithingTrimRecipeData recipe) {
        JsonObject json = new JsonObject();
        json.addProperty("id", recipe.getId());
        json.add("template", descriptor(recipe.getTemplate()));
        json.add("base", descriptor(recipe.getBase()));
        json.add("addition", descriptor(recipe.getAddition()));
        json.addProperty("tag", recipe.getTag());
        json.addProperty("netId", recipe.getNetId());
        return json;
    }

    private JsonObject potionMix(PotionMixData mix) {
        JsonObject json = new JsonObject();
        json.add("input", plainItem(mix.getInputId(), mix.getInputMeta()));
        json.add("reagent", plainItem(mix.getReagentId(), mix.getReagentMeta()));
        json.add("output", plainItem(mix.getOutputId(), mix.getOutputMeta()));
        return json;
    }

    private JsonObject containerMix(ContainerMixData mix) {
        JsonObject json = new JsonObject();
        json.add("input", plainItem(mix.getInputId(), 0));
        json.add("reagent", plainItem(mix.getReagentId(), 0));
        json.add("output", plainItem(mix.getOutputId(), 0));
        return json;
    }

    private JsonObject materialReducer(MaterialReducer reducer) {
        JsonObject json = new JsonObject();
        json.addProperty("inputId", reducer.getInputId());
        JsonArray counts = new JsonArray();
        reducer.getItemCounts().forEach((item, count) -> {
            JsonObject entry = new JsonObject();
            entry.addProperty("id", identifier(item));
            entry.addProperty("count", count);
            counts.add(entry);
        });
        json.add("itemCounts", counts);
        return json;
    }

    /** An item of the potion and container mixes: raw runtime id resolved through the capture's item registry. */
    private JsonObject plainItem(int runtimeId, int aux) {
        JsonObject json = new JsonObject();
        json.addProperty("id", runtimeId == 0 ? "minecraft:air" : itemNames.getOrDefault(runtimeId, "unknown:" + runtimeId));
        json.addProperty("aux", aux);
        return json;
    }

    private static String identifier(ItemDefinition definition) {
        return definition == null || definition.getRuntimeId() == 0 ? "minecraft:air" : definition.getIdentifier();
    }

    private JsonObject unlock(RecipeUnlockingRequirement requirement) {
        if (requirement == null) {
            return null;
        }
        JsonObject json = new JsonObject();
        json.addProperty("context", requirement.getContext().name().toLowerCase(Locale.ROOT));
        json.add("ingredients", descriptors(requirement.getIngredients()));
        return json;
    }

    private JsonArray descriptors(List<ItemDescriptorWithCount> descriptors) {
        JsonArray array = new JsonArray();
        for (ItemDescriptorWithCount descriptor : descriptors) {
            array.add(descriptor(descriptor));
        }
        return array;
    }

    private JsonObject descriptor(ItemDescriptorWithCount counted) {
        if (counted == null) {
            return null;
        }
        ItemDescriptor descriptor = counted.getDescriptor();
        JsonObject json = new JsonObject();
        if (descriptor instanceof DefaultDescriptor item) {
            json.addProperty("kind", "default");
            json.addProperty("id", identifier(item.getItemId()));
            json.addProperty("aux", item.getAuxValue());
        } else if (descriptor instanceof ItemTagDescriptor tag) {
            json.addProperty("kind", "item_tag");
            json.addProperty("tag", tag.getItemTag());
        } else if (descriptor instanceof MolangDescriptor molang) {
            json.addProperty("kind", "molang");
            json.addProperty("expression", molang.getTagExpression());
            json.addProperty("version", molang.getMolangVersion());
        } else if (descriptor instanceof DeferredDescriptor deferred) {
            json.addProperty("kind", "deferred");
            json.addProperty("name", deferred.getFullName());
            json.addProperty("aux", deferred.getAuxValue());
        } else if (descriptor instanceof ComplexAliasDescriptor alias) {
            json.addProperty("kind", "complex_alias");
            json.addProperty("name", alias.getName());
        } else if (descriptor instanceof InvalidDescriptor) {
            json.addProperty("kind", "invalid");
        } else {
            throw new IllegalStateException("Unknown item descriptor " + descriptor);
        }
        json.addProperty("count", counted.getCount());
        return json;
    }

    private JsonObject item(ItemData item) throws IOException {
        JsonObject json = new JsonObject();
        if (item == null || item.getDefinition() == null || item.getDefinition().getRuntimeId() == 0) {
            json.addProperty("id", "minecraft:air");
            json.addProperty("aux", 0);
            json.addProperty("count", 0);
            return json;
        }
        json.addProperty("id", item.getDefinition().getIdentifier());
        json.addProperty("aux", item.getDamage());
        json.addProperty("count", item.getCount());
        BlockDefinition block = item.getBlockDefinition();
        if (block != null && block.getRuntimeId() != 0) {
            json.addProperty("block_runtime_id", Integer.toUnsignedString(block.getRuntimeId()));
            NbtMap state = blockStates.apply(block.getRuntimeId());
            if (state != null) {
                json.addProperty("block_state_b64", Nbt.writeLeBase64(state));
            }
        }
        if (item.getTag() != null) {
            json.addProperty("nbt_b64", Nbt.writeLeBase64(item.getTag()));
        }
        return json;
    }
}
