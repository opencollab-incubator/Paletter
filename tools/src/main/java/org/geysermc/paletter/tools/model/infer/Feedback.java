package org.geysermc.paletter.tools.model.infer;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonPrimitive;

import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * {@code codegen/model/bds-feedback.json}: what the BDS content log says about the JSON schema, per component and
 * field path: members it does not know, fields it requires, list/object expectations, numeric ranges, list lengths
 * ({@code minItems}, {@code maxItems}, {@code items}: exactly n), the limit of the sum of two vector members ({@code box}),
 * the strings an enum takes ({@code values}), and the whole steps of the rules inferred from it ({@link #step}). Generated by {@code spec infer} from the newest capture; the add-on generator reads it to build valid
 * bases and value sets in the next capture (BDS is the ground truth for validity, the docs are not always right).
 */
public final class Feedback {
    private static final Pattern PATH = Pattern.compile("-> (components|description|permutations\\[\\d+])(?: -> (.*?))?: (.*?)'?$");

    private static final Pattern BOX = Pattern.compile(
        "\"([a-z_]+)\" \\+ \"([a-z_]+)\".*following limit: Vec3\\(([-\\d.,]+)\\) and Vec3\\(([-\\d.,]+)\\)");

    private final Map<String, Map<String, TreeSet<String>>> facts = new TreeMap<>();

    /**
     * Where a content log line points: the component (as the model names it), the field path below it ({@code a.b},
     * {@code a[]}, {@code {}}) and BDS's message.
     */
    public record Located(String component, String path, String message) {
    }

    /**
     * @param kind {@code item} or {@code block}
     * @return where the line points, or null if it names no path ({@code Error Parsing Item 'x':})
     */
    public static Located locate(String kind, String line) {
        Matcher m = PATH.matcher(line);
        if (!m.find()) {
            return null;
        }
        String section = m.group(1);
        String rest = m.group(2) == null ? "" : m.group(2);
        String message = m.group(3).trim();
        List<String> parts = new java.util.ArrayList<>(List.of(rest.split(" -> ")));
        if (parts.size() == 1 && parts.get(0).isEmpty()) {
            parts.clear();
        }
        String component;
        if (section.equals("components")) {
            if (parts.isEmpty()) {
                return null;
            }
            component = kind + ":" + parts.remove(0).replaceAll("\\[\\d+]", "");
        } else if (section.startsWith("permutations")) {
            component = "block:permutations";
            parts.add(0, "[]");
        } else if (!parts.isEmpty() && parts.get(0).equals("traits") && parts.size() > 1) {
            parts.remove(0);
            component = "block:trait:" + parts.remove(0);
        } else if (!parts.isEmpty() && parts.get(0).equals("states")) {
            parts.remove(0);
            component = "block:states";
            if (!parts.isEmpty()) {
                parts.set(0, "{}" + parts.get(0).replaceAll("^[^\\[]*", ""));
            }
        } else {
            component = kind + ":description";
        }
        String path = String.join(".", parts).replaceAll("\\[\\d+]", "[]").replace(".[]", "[]").replace(".{}", "{}");
        return new Located(component, path, message);
    }

    void add(String kind, String line) {
        Located located = locate(kind, line);
        if (located == null) {
            return;
        }
        String component = located.component();
        String path = located.path();
        String message = located.message();
        String fact = null;
        Matcher range;
        Matcher nonEmpty = Pattern.compile("^'([a-z0-9_]+)' must define at least one").matcher(message);
        if (nonEmpty.find()) {
            // "'n_way_visual_rotation' must define at least one axis": reported on the object that holds the member
            path = path.isEmpty() ? nonEmpty.group(1) : path + "." + nonEmpty.group(1);
            fact = "nonEmpty";
        } else if (message.contains("not present in the Schema")) {
            fact = "unknown";
        } else if (message.contains("missing required field")) {
            fact = "required";
        } else if (message.contains("expected an array")) {
            fact = "array";
        } else if (message.contains("expected an object") || message.contains("expected a key/value object")) {
            fact = "object";
        } else if ((range = Pattern.compile("accepted range \\[(-?[\\d.]+), (-?[\\d.]+)]").matcher(message)).find()) {
            fact = "range " + range.group(1) + " " + range.group(2);
        } else if ((range = Pattern.compile("must be a number <= (-?[\\d.]+)").matcher(message)).find()) {
            fact = "max " + range.group(1);
        } else if ((range = Pattern.compile("must be a number >= (-?[\\d.]+)").matcher(message)).find()) {
            fact = "min " + range.group(1);
        } else if ((range = Pattern.compile("at least (\\d+) elements").matcher(message)).find()) {
            fact = "minItems " + range.group(1);
        } else if ((range = Pattern.compile("(?:no more than|at most) (\\d+)").matcher(message)).find()) {
            fact = "maxItems " + range.group(1);
        } else if ((range = Pattern.compile("fixed size container, expected exactly (\\d+)").matcher(message)).find()) {
            fact = "items " + range.group(1);
        } else if ((range = BOX.matcher(message)).find()) {
            // "origin" + "size", must be inside the following limit: Vec3(-8,0,-8) and Vec3(8,24,8)
            fact = "box " + range.group(1) + " " + range.group(2) + " " + range.group(3) + " " + range.group(4);
        } else if (message.contains("can only be used when") || message.contains("cannot be combined") || message.contains("Cannot have both")) {
            fact = "constraint " + message.replaceAll("for block: .*", "").trim();
        } else if (message.contains("expects one of the following strings")) {
            fact = "values " + message.replaceAll(".*following strings: ", "").replaceAll("\\.? ?Found:.*", "").trim();
        }
        if (fact != null) {
            facts.computeIfAbsent(component, k -> new TreeMap<>()).computeIfAbsent(path, k -> new TreeSet<>()).add(fact);
        }
    }

    /**
     * A step BDS takes a number in, found by the inference rather than in the content log: a linear rule onto an integer
     * leaf with a whole step ({@code rotation}: degrees / 90 gives {@code step 90}). The generator then asks for values off
     * the step.
     */
    void step(String component, String path, long step) {
        facts.computeIfAbsent(component, k -> new TreeMap<>()).computeIfAbsent(path, k -> new TreeSet<>()).add("step " + step);
    }

    /** Whether BDS said a fact of this kind ({@code values}, {@code range}, ...) about a field. */
    boolean has(String component, String path, String kind) {
        return facts.getOrDefault(component, new TreeMap<>()).getOrDefault(path, new TreeSet<>()).stream()
            .anyMatch(f -> f.equals(kind) || f.startsWith(kind + " "));
    }

    JsonObject json() {
        JsonObject json = new JsonObject();
        json.addProperty("_comment", "Generated by `./gradlew :tools:inferMappings` (spec infer) from the content log of the newest capture"
            + " and the steps of its rules; read by the add-on generator.");
        facts.forEach((component, paths) -> {
            JsonObject c = new JsonObject();
            paths.forEach((path, set) -> {
                JsonArray array = new JsonArray();
                set.forEach(f -> array.add(new JsonPrimitive(f)));
                c.add(path, array);
            });
            json.add(component, c);
        });
        return json;
    }
}
