import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

/**
 * {@code data/model/bds-feedback.json}: what the BDS content log says about the JSON schema, per component and
 * field path: members it does not know, fields it requires, list/object expectations, numeric ranges, list lengths
 * ({@code minItems}, {@code maxItems}, {@code items}: exactly n), the limit of the sum of two vector members ({@code box}),
 * the strings an enum takes ({@code values}), the fields BDS ties together ({@code order}, {@code conflicts},
 * {@code identifier}, see {@link #links}), and the whole steps of the rules inferred from it ({@link #step}). Generated by
 * {@code spec infer} from the newest capture; the add-on generator reads it to build valid bases, value sets and linked
 * variants in the next capture (BDS is the ground truth for validity, the docs are not always right).
 */
public final class Feedback {
    private static final Pattern PATH = Pattern.compile("-> (components|description|permutations\\[\\d+])(?: -> (.*?))?: (.*?)'?$");

    private static final Pattern ORDER = Pattern.compile("^([a-z_]+) value cannot be lower than ([a-z_]+) value");

    private static final Pattern BOX = Pattern.compile(
        "\"([a-z_]+)\" \\+ \"([a-z_]+)\".*following limit: Vec3\\(([-\\d.,]+)\\) and Vec3\\(([-\\d.,]+)\\)");

    private final Map<String, Map<String, TreeSet<String>>> facts = new TreeMap<>();

    /**
     * Where a content log line points: the component (as the model names it), the field path below it ({@code a.b},
     * {@code a[]}, {@code {}}) and BDS's message.
     */
    public record Located(String component, String path, String message) {
    }

    /**
     * @param kind {@code item} or {@code block}
     * @return where the line points, or null if it names no path ({@code Error Parsing Item 'x':})
     */
    public static Located locate(String kind, String line) {
        Matcher m = PATH.matcher(line);
        if (!m.find()) {
            return null;
        }
        String section = m.group(1);
        String rest = m.group(2) == null ? "" : m.group(2);
        String message = m.group(3).trim();
        List<String> parts = new java.util.ArrayList<>(List.of(rest.split(" -> ")));
        if (parts.size() == 1 && parts.get(0).isEmpty()) {
            parts.clear();
        }
        String component;
        if (section.equals("components")) {
            if (parts.isEmpty()) {
                return null;
            }
            component = kind + ":" + parts.remove(0).replaceAll("\\[\\d+]", "");
        } else if (section.startsWith("permutations")) {
            component = "block:permutations";
            parts.add(0, "[]");
        } else if (!parts.isEmpty() && parts.get(0).equals("traits") && parts.size() > 1) {
            parts.remove(0);
            component = "block:trait:" + parts.remove(0);
        } else if (!parts.isEmpty() && parts.get(0).equals("states")) {
            parts.remove(0);
            component = "block:states";
            if (!parts.isEmpty()) {
                parts.set(0, "{}" + parts.get(0).replaceAll("^[^\\[]*", ""));
            }
        } else {
            component = kind + ":description";
        }
        String path = String.join(".", parts).replaceAll("\\[\\d+]", "[]").replace(".[]", "[]").replace(".{}", "{}");
        return new Located(component, path, message);
    }

    /**
     * @param variant the variant the line belongs to, or null if it names none
     */
    void add(String kind, String line, SpecCaptures.Variant variant) {
        if (variant != null) {
            links(line, variant);
        }
        Located located = locate(kind, line);
        if (located == null) {
            return;
        }
        String component = located.component();
        String path = located.path();
        String message = located.message();
        String fact = null;
        Matcher range;
        Matcher nonEmpty = Pattern.compile("^'([a-z0-9_]+)' must define at least one").matcher(message);
        if (nonEmpty.find()) {
            // "'n_way_visual_rotation' must define at least one axis": reported on the object that holds the member
            path = path.isEmpty() ? nonEmpty.group(1) : path + "." + nonEmpty.group(1);
            fact = "nonEmpty";
        } else if (message.contains("not present in the Schema")) {
            fact = "unknown";
        } else if (message.matches("member \".*\" is deprecated")) {
            fact = "deprecated"; // the whole component is rejected at the current format
        } else if (message.contains("missing required field")) {
            fact = "required";
        } else if (message.contains("expected an array")) {
            fact = "array";
        } else if (message.contains("expected an object") || message.contains("expected a key/value object")) {
            fact = "object";
        } else if ((range = Pattern.compile("accepted range \\[(-?[\\d.]+), (-?[\\d.]+)]").matcher(message)).find()) {
            fact = "range " + range.group(1) + " " + range.group(2);
        } else if ((range = Pattern.compile("must be a number <= (-?[\\d.]+)").matcher(message)).find()) {
            fact = "max " + range.group(1);
        } else if ((range = Pattern.compile("must be a number >= (-?[\\d.]+)").matcher(message)).find()) {
            fact = "min " + range.group(1);
        } else if ((range = Pattern.compile("at least (\\d+) elements").matcher(message)).find()) {
            fact = "minItems " + range.group(1);
        } else if ((range = Pattern.compile("(?:no more than|at most) (\\d+)").matcher(message)).find()) {
            fact = "maxItems " + range.group(1);
        } else if ((range = Pattern.compile("fixed size container, expected exactly (\\d+)").matcher(message)).find()) {
            fact = "items " + range.group(1);
        } else if ((range = BOX.matcher(message)).find()) {
            // "origin" + "size", must be inside the following limit: Vec3(-8,0,-8) and Vec3(8,24,8)
            fact = "box " + range.group(1) + " " + range.group(2) + " " + range.group(3) + " " + range.group(4);
        } else if ((range = ORDER.matcher(message)).find()) {
            // "max value cannot be lower than min value", reported on the object that holds both
            fact = "order " + range.group(2) + " " + range.group(1);
        } else if (message.contains("can only be used when") || message.contains("cannot be combined") || message.contains("Cannot have both")) {
            fact = "constraint " + message.replaceAll("for block: .*", "").trim();
        } else if (message.contains("expects one of the following strings")) {
            fact = "values " + message.replaceAll(".*following strings: ", "").replaceAll("\\.? ?Found:.*", "").trim();
        } else if ((range = ALTERNATIVES.matcher(message)).find()) {
            // expected string to match the "none|all|sword" regex: a plain alternation lists the accepted strings
            fact = "values " + Arrays.stream(range.group(1).split("\\|")).map(v -> "'" + v + "'").collect(Collectors.joining(", "));
        }
        if (fact != null) {
            facts.computeIfAbsent(component, k -> new TreeMap<>()).computeIfAbsent(path, k -> new TreeSet<>()).add(fact);
        }
    }

    private static final Pattern ALTERNATIVES = Pattern.compile("expected string to match the \"\\^?(\\w+(?:\\|\\w+)+)\\$?\" regex");

    /**
     * The fields BDS ties to the field a variant varies, where a line of the variant quotes the value another field has in
     * the variant: {@code identifier <path> <kind>} when the line also names the variant's own identifier as what the other
     * field's {@code <kind>} must match ("Item identifier &lt;id&gt; does not match the block identifier minecraft:dirt"),
     * else {@code conflicts <path> '<value>'} ("Cannot use bone visibility feature with: minecraft:geometry.full_block"). Lines that
     * list allowed values or a pattern quote values without saying anything about them, and are skipped.
     * <p>
     * The same tie shows from the other side: a line that quotes the value the variant gives its own field and names another
     * field the variant sets (the same message for a variant of {@code identifier} whose base has {@code bone_visibility})
     * is a {@code conflicts} fact of that other field.
     */
    private void links(String line, SpecCaptures.Variant variant) {
        if (!variant.role().equals("field") || !variant.linked().isEmpty() || variant.json() == null) {
            return;
        }
        String message = message(line);
        if (message.contains("expects one of the following") || message.contains("to match the")) {
            return;
        }
        // a line that quotes what the variant gives its own field is about that value ("Bad expression: +1, for bone visibilities
        // of bone bone_a of geometry geometry.paletter_cube"), wherever it says the value sits
        JsonElement varied = variant.path().isEmpty() ? variant.json() : SpecCaptures.jsonAt(variant.json(), variant.path());
        List<String> ownValues = new ArrayList<>();
        leaves(varied, ownValues);
        boolean aboutOwnValue = ownValues.stream().anyMatch(value -> !value.isBlank()
            && Pattern.compile("(?<![\\w.:])" + Pattern.quote(value) + "(?![\\w:])").matcher(message).find());
        for (String other : aboutOwnValue ? List.<String>of() : quoted(variant.json(), variant.path(), message)) {
            String value = SpecCaptures.jsonAt(variant.json(), other).getAsString();
            Matcher identifier = Pattern.compile("([a-z]+) identifier " + Pattern.quote(value)).matcher(message);
            String fact = message.contains(OWN_IDENTIFIER) && identifier.find() ? "identifier " + other + " " + identifier.group(1) : "conflicts " + other + " '" + value + "'";
            facts.computeIfAbsent(variant.component(), k -> new TreeMap<>()).computeIfAbsent(variant.path(), k -> new TreeSet<>()).add(fact);
        }
        JsonElement own = variant.path().isEmpty() ? null : SpecCaptures.jsonAt(variant.json(), variant.path());
        if (own != null && own.isJsonPrimitive() && own.getAsJsonPrimitive().isString() && !message.contains(OWN_IDENTIFIER)
            && quotes(message, own.getAsString())) {
            members(variant.json(), "", other -> {
                if (!related(other, variant.path()) && names(message, AddonGenerator.tokens(other).getLast())) {
                    facts.computeIfAbsent(variant.component(), k -> new TreeMap<>()).computeIfAbsent(other, k -> new TreeSet<>())
                        .add("conflicts " + variant.path() + " '" + own.getAsString() + "'");
                }
            });
        }
    }

    /** Whether a message quotes a value of at least three characters as a whole. */
    private static boolean quotes(String message, String value) {
        return value.length() >= 3 && Pattern.compile("(?<![\\w.:])" + Pattern.quote(value) + "(?![\\w:])").matcher(message).find();
    }

    /** Whether a message names a field by its key, as BDS writes it in prose ({@code bone_visibility}: "bone visibility"). */
    static boolean names(String message, String key) {
        return key.contains("_") && Pattern.compile("(?<![a-z0-9_])" + Pattern.quote(key).replace("_", "\\E[ _]\\Q") + "(?![a-z0-9_])")
            .matcher(message.toLowerCase(java.util.Locale.ROOT)).find();
    }

    /** Every string in a JSON value. */
    private static void leaves(JsonElement json, List<String> out) {
        if (json == null || json.isJsonNull()) {
            return;
        }
        if (json.isJsonObject()) {
            json.getAsJsonObject().asMap().values().forEach(value -> leaves(value, out));
        } else if (json.isJsonArray()) {
            json.getAsJsonArray().forEach(value -> leaves(value, out));
        } else if (json.getAsJsonPrimitive().isString()) {
            out.add(json.getAsString());
        }
    }

    /** The path of every member of the objects of a JSON value ({@code a}, {@code a.b}). */
    private static void members(JsonElement json, String path, java.util.function.Consumer<String> out) {
        if (json != null && json.isJsonObject()) {
            json.getAsJsonObject().entrySet().forEach(e -> {
                String member = path.isEmpty() ? e.getKey() : path + "." + e.getKey();
                out.accept(member);
                members(e.getValue(), member, out);
            });
        }
    }

    /** How {@link #message} writes the identifier of the variant a line belongs to. */
    static final String OWN_IDENTIFIER = "<id>";

    /**
     * What a content log line says, without where it points: after the last {@code ->}, without a leading item or component
     * name ({@code "minecraft:block_placer":}), the variants' identifiers as {@code <id>}.
     */
    static String message(String line) {
        return SpecCaptures.errorText(line).replaceFirst("^\\[[A-Za-z]+]\\s+(\"[^\"]+\"|'[^']+'):\\s*", "");
    }

    /**
     * The other fields of a variant's JSON whose string value a message quotes: fields that are not the varied one, inside it
     * or around it, with a value of at least three characters.
     */
    static List<String> quoted(JsonElement json, String varied, String message) {
        List<String> out = new ArrayList<>();
        strings(json, "", (path, value) -> {
            if (!related(path, varied) && quotes(message, value)) {
                out.add(path);
            }
        });
        return out;
    }

    /**
     * The other fields of a component a message names: by the last key of their path as a word of the message ("max value
     * cannot be lower than min value" names {@code min} for a variant of {@code max}), or by the value they have in the
     * variant ({@link #quoted}). Fields that are the varied one, inside it or around it are not other fields; neither is the
     * member the message is reported on (the text before its first colon).
     */
    static List<String> otherFields(Model.Component component, String varied, JsonElement json, String message) {
        String text = message.toLowerCase(java.util.Locale.ROOT).replaceFirst("^[a-z0-9_:\\[\\]]+: ", "");
        Set<String> words = new java.util.HashSet<>(List.of(text.split("[^a-z0-9_]+")));
        Set<String> out = new LinkedHashSet<>();
        for (Model.Field field : component.fields()) {
            String last = AddonGenerator.tokens(field.path()).stream().filter(t -> !t.equals("[]") && !t.equals("{}")).reduce((a, b) -> b).orElse("");
            if (!related(field.path(), varied) && words.contains(last)) {
                out.add(field.path());
            }
        }
        if (json != null && !message.contains("expects one of the following") && !message.contains("to match the")) {
            out.addAll(quoted(json, varied, message));
        }
        return List.copyOf(out);
    }

    /** Whether one path is the other or contains it ({@code a} and {@code a.b}, {@code a[]}). */
    static boolean related(String a, String b) {
        String x = a.length() <= b.length() ? a : b;
        String y = a.length() <= b.length() ? b : a;
        return x.isEmpty() || y.equals(x) || y.startsWith(x + ".") || y.startsWith(x + "[]") || y.startsWith(x + "{}");
    }

    /** Every string leaf of a JSON value with its path ({@code a.b}, {@code a[]}; map keys as keys). */
    private static void strings(JsonElement json, String path, java.util.function.BiConsumer<String, String> out) {
        if (json == null || json.isJsonNull()) {
            return;
        }
        if (json.isJsonObject()) {
            json.getAsJsonObject().entrySet().forEach(e -> strings(e.getValue(), path.isEmpty() ? e.getKey() : path + "." + e.getKey(), out));
        } else if (json.isJsonArray()) {
            if (!json.getAsJsonArray().isEmpty()) {
                strings(json.getAsJsonArray().get(0), path + "[]", out);
            }
        } else if (json.getAsJsonPrimitive().isString()) {
            out.accept(path, json.getAsString());
        }
    }

    /**
     * A step BDS takes a number in, found by the inference rather than in the content log: a linear rule onto an integer
     * leaf with a whole step ({@code rotation}: degrees / 90 gives {@code step 90}). The generator then asks for values off
     * the step.
     */
    void step(String component, String path, long step) {
        facts.computeIfAbsent(component, k -> new TreeMap<>()).computeIfAbsent(path, k -> new TreeSet<>()).add("step " + step);
    }

    /** The component is accepted at an older format ({@code format <F>}), with a wire that differs from the companions alone ({@link FormatInference}). */
    void format(String component, String format) {
        facts.computeIfAbsent(component, k -> new TreeMap<>()).computeIfAbsent("", k -> new TreeSet<>()).add("format " + format);
    }

    /** Forgets that a member is unknown where {@code other} (the newest preview's content log) does not say so. */
    void knownIn(Feedback other) {
        facts.forEach((component, paths) -> paths.forEach((path, set) -> {
            if (!other.has(component, path, "unknown")) {
                set.remove("unknown");
            }
        }));
        facts.values().forEach(paths -> paths.values().removeIf(Set::isEmpty));
        facts.values().removeIf(Map::isEmpty);
    }

    /** Whether BDS said a fact of this kind ({@code values}, {@code range}, ...) about a field. */
    boolean has(String component, String path, String kind) {
        return facts.getOrDefault(component, new TreeMap<>()).getOrDefault(path, new TreeSet<>()).stream()
            .anyMatch(f -> f.equals(kind) || f.startsWith(kind + " "));
    }

    JsonObject json() {
        JsonObject json = new JsonObject();
        json.addProperty(Model.GENERATED_KEY, "Generated by `./gradlew :tools:inferMappings` (spec infer) from the content log of the newest release"
            + " capture (members the newest preview knows are not unknown) and the steps of its rules; read by the add-on generator. Do not edit.");
        facts.forEach((component, paths) -> {
            JsonObject c = new JsonObject();
            paths.forEach((path, set) -> {
                JsonArray array = new JsonArray();
                set.forEach(f -> array.add(new JsonPrimitive(f)));
                c.add(path, array);
            });
            json.add(component, c);
        });
        return json;
    }

    /**
     * Feeds the whole steps of a component's newest rules back to the generator ({@link Feedback#step}): a linear rule onto
     * an integer leaf whose input step ({@code 1 / scale}) is a whole number of at least 2.
     */
    void steps(String componentId, JsonObject newest) {
        if (!newest.has("fields")) {
            return;
        }
        for (Map.Entry<String, JsonElement> field : newest.getAsJsonObject("fields").entrySet()) {
            JsonObject result = field.getValue().getAsJsonObject();
            for (Rule rule : Rule.all(result)) {
                if (rule instanceof Linear linear && "int".equals(rule.nbt)) {
                    double step = Math.abs(1 / linear.scale);
                    if (step >= 2 && Math.abs(step - Math.rint(step)) < 1e-3) {
                        step(componentId, field.getKey(), Math.round(step));
                    }
                }
            }
        }
    }
}
