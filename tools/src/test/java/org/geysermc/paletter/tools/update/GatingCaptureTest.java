package org.geysermc.paletter.tools.update;

import com.google.gson.JsonObject;
import org.geysermc.paletter.tools.codegen.component.Gating;
import org.geysermc.paletter.tools.model.Fixtures;
import org.geysermc.paletter.tools.model.Model;
import org.geysermc.paletter.tools.model.addon.AddonGenerator;
import org.geysermc.paletter.tools.model.rule.Leaf;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The gating capture: its add-on holds exactly the components the docs gate, and a synthetic BDS answer is classified per component. */
class GatingCaptureTest {
    private static final Path MODEL = Path.of(System.getProperty("paletter.root", ".."), "data/model");

    private static AddonGenerator generator() throws IOException {
        Model docs = Model.read(MODEL.resolve("components.json"));
        AddonGenerator generator = AddonGenerator.empty(docs, Fixtures.read(MODEL), "1.26.60");
        GatingCapture.plan(generator, "1.26.60");
        return generator;
    }

    @Test
    void theAddOnHoldsExactlyTheComponentsTheDocsGateEachWithABaseAndAControl() throws IOException {
        AddonGenerator generator = generator();
        Set<String> gated = generator.model().components().stream().filter(c -> !c.experiments().isEmpty()).map(Model.Component::id)
            .collect(Collectors.toSet());
        assertTrue(gated.containsAll(Set.of("block:minecraft:crafting_table", "block:minecraft:instrument_sound", "block:minecraft:collision_box",
            "block:trait:minecraft:multi_block", "block:minecraft:replaceable")), "the ones whose experiment is in no capture too: " + gated);
        assertEquals(gated, Set.copyOf(GatingCapture.gated(generator.model())));
        for (String id : gated) {
            assertEquals(List.of("base", "control"), generator.variants().stream().filter(v -> v.componentId().equals(id)).map(AddonGenerator.Variant::role).toList(), id);
        }
        assertEquals(gated.size() * 2, generator.variants().size(), "nothing else is in it");
    }

    @Test
    void rejectedIgnoredAndAcceptedComeFromTheLogAndTheWire() {
        Leaf base = new Leaf("a", 1);
        Map<String, Leaf> with = Map.of("x", base);
        Map<String, Leaf> without = Map.of();
        assertEquals(Gating.REJECTED, GatingCapture.without(false, with, without));
        assertEquals(Gating.IGNORED, GatingCapture.without(true, without, without));
        assertEquals(Gating.ACCEPTED, GatingCapture.without(true, with, without));
    }

    @Test
    void aSyntheticBdsAnswerBecomesTheMarkedFile(@TempDir Path noSpec) throws IOException {
        AddonGenerator generator = generator();
        List<String> ids = GatingCapture.gated(generator.model());
        Map<String, Map<String, Leaf>> leaves = new HashMap<>();
        Map<String, List<String>> log = new HashMap<>();
        for (int i = 0; i < ids.size(); i++) {
            String id = ids.get(i);
            AddonGenerator.Variant b = generator.variants().stream().filter(v -> v.componentId().equals(id) && v.role().equals("base")).findFirst().orElseThrow();
            AddonGenerator.Variant c = generator.variants().stream().filter(v -> v.componentId().equals(id) && v.role().equals("control")).findFirst().orElseThrow();
            leaves.put(c.kind() + " " + c.identifier(), Map.of());
            if (i == 0) {
                log.put(b.identifier(), List.of("ERROR [Blocks] blocks/x.json: not an experimental feature"));
                leaves.put(b.kind() + " " + b.identifier(), Map.of());
            } else if (i == 1) {
                leaves.put(b.kind() + " " + b.identifier(), Map.of());
            } else {
                leaves.put(b.kind() + " " + b.identifier(), Map.of("x", new Leaf("a", 1)));
            }
        }
        JsonObject json = GatingCapture.report(generator, "1.2.3.4", 99, List.of("data_driven_vanilla_blocks_and_items=true"), leaves, log, noSpec);
        assertTrue(json.get("_generated").getAsString().startsWith("Generated by"), "marked as generated");
        JsonObject components = json.getAsJsonObject("components");
        assertEquals(ids.size(), components.size());
        assertEquals(Gating.REJECTED, components.getAsJsonObject(ids.get(0)).get("without").getAsString());
        assertEquals(Gating.IGNORED, components.getAsJsonObject(ids.get(1)).get("without").getAsString());
        assertEquals(Gating.ACCEPTED, components.getAsJsonObject(ids.get(2)).get("without").getAsString());
        assertTrue(!components.getAsJsonObject(ids.get(0)).has("with"), "no spec capture of this build: nothing is claimed for the experiments on");
    }
}
