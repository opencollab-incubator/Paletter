package org.geysermc.paletter.tools.codegen.component;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.geysermc.paletter.tools.codegen.component.BehaviourKeys.Hand;
import org.geysermc.paletter.tools.codegen.component.BehaviourKeys.Key;
import org.geysermc.paletter.tools.codegen.component.BehaviourKeys.Leaf;
import org.geysermc.paletter.tools.codegen.component.BehaviourKeys.Owner;
import org.geysermc.paletter.tools.codegen.component.ComponentGenerator.GenerationException;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The behaviour key generator on small hand-made mappings: rules read backwards, probe relations, and what fails. */
class BehaviourSourceTest {
    private static final String WIRE_RULES = "org/geysermc/paletter/internal/behaviour/WireRules.java";

    /** One component with a value form ({@code minecraft:glow}) and one with fields ({@code minecraft:use}). */
    private static JsonObject mappings(String glowRule, String useRule) {
        return JsonParser.parseString("""
            {"components": {
              "block:minecraft:glow": {"forms": {"base": {"status": "rejected"}, "number": {"rules": [%s]}}},
              "item:minecraft:use": {"fields": {"seconds": {"rules": [%s,
                {"kind": "identity", "wire": "minecraft:use.seconds"}]}}}
            }}""".formatted(glowRule, useRule)).getAsJsonObject();
    }

    private static final String IDENTITY = "{\"kind\": \"identity\", \"wire\": \"minecraft:glow.value\"}";
    private static final String TICKS = "{\"kind\": \"linear\", \"scale\": 20.0, \"offset\": 0.0, \"wire\": \"item_properties.use_ticks\"}";

    private static List<Key> keys(String glowType) {
        return List.of(
            new Key(Owner.BLOCK, "glow", glowType, "", new Leaf("minecraft:glow", "", "minecraft:glow.value")),
            new Key(Owner.BLOCK, "shape", "BlockShape", "The shape.", new Hand("collisionShape", List.of("minecraft:box", "minecraft:turn"))),
            new Key(Owner.BLOCK, "solid", "Boolean", "", null),
            new Key(Owner.ITEM, "use_ticks", "Integer", "", new Leaf("minecraft:use", "seconds", "item_properties.use_ticks")),
            new Key(Owner.ITEM, "use_seconds", "Float", "", new Leaf("minecraft:use", "seconds", "minecraft:use.seconds")));
    }

    private static JsonObject probe(double... pairs) {
        StringBuilder json = new StringBuilder("{\"glow\": {\"components\": [");
        for (int i = 0; i < pairs.length; i += 2) {
            json.append(i == 0 ? "" : ",").append("{\"component\": ").append(pairs[i]).append(", \"engine\": ").append(pairs[i + 1]).append('}');
        }
        return JsonParser.parseString(json.append("]}}").toString()).getAsJsonObject();
    }

    @Test
    void constantsListEveryKeyInTableOrder() {
        Map<String, String> files = BehaviourSource.generate(keys("Float"), mappings(IDENTITY, TICKS), null, "");
        String block = files.get("org/geysermc/paletter/behaviour/BlockBehaviour.java");
        assertTrue(block.startsWith("// Generated by :tools:generateComponentApi"), block);
        assertTrue(block.contains("public static final BehaviourKey<Float> GLOW = key(\"glow\", Float.class);"), block);
        assertTrue(block.contains("KEYS = List.of(GLOW, SHAPE, SOLID);"), block);
        assertTrue(block.contains("Custom blocks set it with {@code minecraft:box} and {@code minecraft:turn}."), block);
        String item = files.get("org/geysermc/paletter/behaviour/ItemBehaviour.java");
        assertTrue(item.contains("KEYS = List.of(USE_TICKS, USE_SECONDS);"), item);
    }

    @Test
    void rulesAreReadBackwards() {
        String wire = BehaviourSource.generate(keys("Float"), mappings(IDENTITY, TICKS), null, "").get(WIRE_RULES);
        assertTrue(wire.contains("return floatOf(properties.component(\"minecraft:glow\"), \"value\");"), wire);
        assertTrue(wire.contains("return ShapeRules.collisionShape(properties);"), wire);
        assertTrue(wire.contains("return List.of(\"minecraft:box\", \"minecraft:turn\");"), wire);
        // item_properties is read as BDS sends it, not converted back to seconds
        assertTrue(wire.contains("return intOf(properties.component(\"item_properties\"), \"use_ticks\");"), wire);
        assertTrue(wire.contains("return floatOf(properties.component(\"minecraft:use\"), \"seconds\");"), wire);
        assertTrue(!wire.contains("SOLID"), wire);
    }

    @Test
    void aLinearRuleIsInverted() {
        String rule = "{\"kind\": \"linear\", \"scale\": 16.0, \"offset\": 8.0, \"wire\": \"minecraft:glow.value\"}";
        String wire = BehaviourSource.generate(keys("Float"), mappings(rule, TICKS), null, "").get(WIRE_RULES);
        assertTrue(wire.contains("return value == null ? null : 0.0625f * value - 0.5f;"), wire);
        GenerationException integer = assertThrows(GenerationException.class,
            () -> BehaviourSource.generate(keys("Integer"), mappings(rule, TICKS), null, ""));
        assertTrue(integer.getMessage().contains("not an integer"), integer.getMessage());
    }

    @Test
    void theProbeRelationConvertsToEngineUnits() {
        JsonObject probe = probe(0.0, 1.0, 0.4, 0.6, 0.9, 0.1);
        String wire = BehaviourSource.generate(keys("Float"), mappings(IDENTITY, TICKS), probe, "data/bds/x/behaviour-probe/capture.json").get(WIRE_RULES);
        assertTrue(wire.contains("return value == null ? null : 1.0f - value;"), wire);
        assertTrue(wire.contains("engine = 1.0 - component, measured by behaviour-probe (data/bds/x/behaviour-probe/capture.json glow.components)"), wire);
    }

    @Test
    void aRelationThatIsNotLinearFails() {
        GenerationException e = assertThrows(GenerationException.class, () -> BehaviourSource.relation("block:glow", "glow",
            probe(0.0, 1.0, 0.5, 0.2, 0.9, 0.1), ""));
        assertTrue(e.getMessage().contains("no linear relation fits"), e.getMessage());
        assertNull(BehaviourSource.relation("block:glow", "other", probe(0.0, 1.0, 0.5, 0.5), ""));
    }

    @Test
    void aRenamedLeafFailsGeneration() {
        String renamed = "{\"kind\": \"identity\", \"wire\": \"minecraft:glow.level\"}";
        GenerationException e = assertThrows(GenerationException.class,
            () -> BehaviourSource.generate(keys("Float"), mappings(renamed, TICKS), null, ""));
        assertTrue(e.getMessage().contains("no rule of block:minecraft:glow (value forms) onto minecraft:glow.value"), e.getMessage());
    }

    @Test
    void aRuleThatCannotBeInvertedFails() {
        String table = "{\"kind\": \"table\", \"table\": {\"false\": \"-1.0\"}, \"wire\": \"minecraft:glow.value\"}";
        GenerationException e = assertThrows(GenerationException.class,
            () -> BehaviourSource.generate(keys("Float"), mappings(table, TICKS), null, ""));
        assertTrue(e.getMessage().contains("cannot be inverted"), e.getMessage());
    }

    @Test
    void protocolWindowsMustAgree() {
        JsonObject mappings = mappings(IDENTITY, TICKS);
        JsonObject glow = mappings.getAsJsonObject("components").getAsJsonObject("block:minecraft:glow");
        glow.add("protocol900", JsonParser.parseString("{\"forms\": {\"number\": {\"rules\": [{\"kind\": \"linear\", \"scale\": 2.0, "
            + "\"offset\": 0.0, \"wire\": \"minecraft:glow.value\"}]}}}"));
        GenerationException e = assertThrows(GenerationException.class, () -> BehaviourSource.generate(keys("Float"), mappings, null, ""));
        assertTrue(e.getMessage().contains("differ"), e.getMessage());
    }

    @Test
    void everyHandKeyNamesAPublicStaticMethodOfShapeRules() throws ClassNotFoundException {
        Class<?> shapes = Class.forName("org.geysermc.paletter.internal.behaviour.ShapeRules");
        for (Key key : BehaviourKeys.KEYS) {
            if (key.wire() instanceof Hand hand) {
                boolean exists = java.util.Arrays.stream(shapes.getMethods())
                    .anyMatch(m -> m.getName().equals(hand.method()) && java.lang.reflect.Modifier.isStatic(m.getModifiers()));
                assertTrue(exists, key.name() + " names ShapeRules." + hand.method() + ", which is not a public static method");
            }
        }
    }

    @Test
    void linearTerms() {
        assertEquals("x", BehaviourSource.linear("x", 1, 0));
        assertEquals("1.0 - x", BehaviourSource.linear("x", -1, 1));
        assertEquals("0.05 * x + 2.0", BehaviourSource.linear("x", 0.05, 2));
    }
}
