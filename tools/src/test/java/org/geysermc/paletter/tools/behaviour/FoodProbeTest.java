package org.geysermc.paletter.tools.behaviour;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.geysermc.paletter.behaviour.ItemBehaviour;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The rules from the food probe's observations to values, on observations made up to be what the add-on printed. */
class FoodProbeTest {
    private static String trial(boolean started, Object useDuration, boolean completed, double hungerAfter, double saturationAfter, int hungerBefore) {
        return "{\"started\":" + started + ",\"useDuration\":" + useDuration + ",\"completed\":" + completed + ",\"hunger\":[" + hungerBefore + "," + hungerAfter
            + "],\"saturation\":[0," + saturationAfter + "]}";
    }

    private static String hungry(Object useDuration, double hungerAfter, double saturationAfter) {
        return trial(true, useDuration, true, hungerAfter, saturationAfter, 10);
    }

    private static final String NOT_STARTED = "{\"started\":false,\"useDuration\":null,\"completed\":false,\"hunger\":[20,20],\"saturation\":[0,0]}";

    private static String food(String item, String hungry, String full) {
        return "[2026-11-09 20:30:30:000 WARN] [Scripting] PROBE food {\"item\":\"" + item + "\",\"hungry\":" + hungry + ",\"full\":" + full + "}";
    }

    private static String full(Object useDuration) {
        return trial(true, useDuration, true, 20, 0, 20);
    }

    private static List<String> controls() {
        List<String> lines = new ArrayList<>();
        // nutrition 4 and a modifier of 0.3 give 2 * 4 * 0.3 = 2.4 saturation; 1.6 s are 32 ticks; it cannot be eaten when full
        lines.add(food("probe:control_food", hungry(32, 14, 2.4), NOT_STARTED));
        lines.add(food("probe:control_snack", hungry(16, 12, 2.4), full(16)));
        return lines;
    }

    private static ProbeLog log(List<String> observations) {
        List<String> lines = new ArrayList<>();
        lines.add("[2026-11-09 20:30:06:870 INFO] Version: 1.26.63.1");
        lines.add("[2026-11-09 20:30:06:871 INFO] Build ID: 53340801");
        lines.addAll(observations);
        lines.add("[2026-11-09 20:30:40:000 WARN] [Scripting] PROBE-DONE");
        return ProbeLog.parse(lines);
    }

    private static JsonObject measure(String... items) {
        List<String> lines = controls();
        lines.addAll(List.of(items));
        return FoodProbe.measure(log(lines));
    }

    @Test
    void nutritionIsTheFoodLevelGainedAndTheModifierTheSaturationGainedOverTwiceThat() {
        JsonObject capture = measure(food("minecraft:golden_carrot", hungry(32, 16, 14.4), full(32)),
            food("minecraft:apple", hungry(32, 14, 2.4), NOT_STARTED));
        JsonObject carrot = capture.getAsJsonObject("items").getAsJsonObject("minecraft:golden_carrot");
        assertEquals(6, carrot.get("nutrition").getAsInt());
        assertEquals(1.2, carrot.get("saturation_modifier").getAsDouble());
        assertEquals(32, carrot.get("use_duration").getAsInt());
        assertTrue(carrot.get("can_always_eat").getAsBoolean(), "a full player could use it");
        JsonObject apple = capture.getAsJsonObject("items").getAsJsonObject("minecraft:apple");
        assertEquals(0.3, apple.get("saturation_modifier").getAsDouble());
        assertFalse(apple.get("can_always_eat").getAsBoolean());
        assertTrue(capture.getAsJsonObject("unclear").isEmpty());
        assertTrue(capture.get("generated").getAsString().startsWith("Generated by `food-probe`"));
    }

    @Test
    void anItemUsedButNotEatenHasOnlyAUseDurationAndOneNeverUsedHasNothing() {
        JsonObject capture = measure(food("minecraft:potion", hungry(32, 10, 0), full(32)),
            food("minecraft:bow", trial(true, 72000, false, 10, 0, 10), trial(true, 72000, false, 20, 0, 20)),
            food("minecraft:stick", NOT_STARTED, NOT_STARTED));
        JsonObject items = capture.getAsJsonObject("items");
        assertEquals("{\"use_duration\":32}", items.get("minecraft:potion").toString());
        assertEquals("{\"use_duration\":72000}", items.get("minecraft:bow").toString());
        assertFalse(items.has("minecraft:stick"));
        assertTrue(capture.getAsJsonObject("unclear").isEmpty());
    }

    @Test
    void whatTheTrialsDoNotDecideIsUnclearNotGuessed() {
        JsonObject capture = measure(
            food("minecraft:capped", hungry(32, 16, 16), full(32)),
            food("minecraft:big", hungry(32, 20, 5), full(32)),
            food("minecraft:odd", hungry(32, 14, 2.4), full(40)),
            food("minecraft:silent", trial(true, null, false, 10, 0, 10), NOT_STARTED));
        JsonObject unclear = capture.getAsJsonObject("unclear");
        assertEquals(Set.of("minecraft:capped", "minecraft:big", "minecraft:odd", "minecraft:silent"), unclear.keySet());
        assertTrue(unclear.get("minecraft:capped").getAsString().contains("capped"));
        assertTrue(unclear.get("minecraft:big").getAsString().contains("20"));
        assertTrue(unclear.get("minecraft:odd").getAsString().contains("hungry and 40 full"));
        // the capped item still has its nutrition and use duration, only the modifier is unknown
        JsonObject items = capture.getAsJsonObject("items");
        assertEquals(6, items.getAsJsonObject("minecraft:capped").get("nutrition").getAsInt());
        assertFalse(items.getAsJsonObject("minecraft:capped").has("saturation_modifier"));
        assertFalse(items.has("minecraft:big"));
    }

    @Test
    void aControlThatDoesNotReadAsItsComponentsSayMakesTheCaptureUnverified() {
        List<String> lines = controls();
        lines.set(0, food("probe:control_food", hungry(1.6, 14, 2.4), NOT_STARTED));
        lines.add(food("minecraft:apple", hungry(32, 14, 2.4), NOT_STARTED));
        JsonObject capture = FoodProbe.measure(log(lines));
        assertTrue(capture.get(StateProbe.UNVERIFIED).getAsString().contains("probe:control_food reads"), capture.toString());
        assertFalse(capture.has("items"));
        assertFalse(capture.has("controls"));
        assertTrue(FoodProbe.items(capture).isEmpty());
    }

    @Test
    void aControlThatWasNotTriedMakesTheCaptureUnverified() {
        List<String> lines = controls();
        lines.remove(1);
        assertTrue(FoodProbe.measure(log(lines)).get(StateProbe.UNVERIFIED).getAsString().contains("probe:control_snack was not tried"));
    }

    @Test
    void aSaturationModifierOfAControlThatIsOffIsNotTheOneItSets() {
        List<String> lines = controls();
        lines.set(0, food("probe:control_food", hungry(32, 14, 4.0), NOT_STARTED));
        assertTrue(FoodProbe.measure(log(lines)).has(StateProbe.UNVERIFIED), "2.4 expected, 4.0 read: the modifier is not the one set");
    }

    @Test
    void aLogWithoutFoodIsUnverifiedBecauseNoControlWasTried() {
        assertTrue(FoodProbe.measure(log(List.of())).has(StateProbe.UNVERIFIED));
    }

    @Test
    void theImporterGetsTheValuesOfVanillaItemsOnly() {
        JsonObject capture = measure(food("minecraft:golden_carrot", hungry(32, 16, 14.4), full(32)));
        Values<String> values = FoodProbe.items(capture);
        assertEquals(Set.of("minecraft:golden_carrot"), values.ids);
        assertEquals(6, values.byKey.get(ItemBehaviour.NUTRITION).get("minecraft:golden_carrot"));
        assertEquals(1.2f, values.byKey.get(ItemBehaviour.SATURATION_MODIFIER).get("minecraft:golden_carrot"));
        assertEquals(32, values.byKey.get(ItemBehaviour.USE_DURATION).get("minecraft:golden_carrot"));
        assertEquals(true, values.byKey.get(ItemBehaviour.CAN_ALWAYS_EAT).get("minecraft:golden_carrot"));
        assertNull(values.byKey.get(ItemBehaviour.MAX_STACK_SIZE));
    }

    @Test
    void theCaptureIsComparedWithoutTheBuild() {
        JsonObject capture = measure(food("minecraft:apple", hungry(32, 14, 2.4), NOT_STARTED));
        String text = Json.pretty(capture);
        assertTrue(FoodProbe.sameCapture(text, text.replace("53340801", "1")), "the build does not count");
        assertFalse(FoodProbe.sameCapture(text, text.replace("\"nutrition\":4", "\"nutrition\":5")));
    }

    @Test
    void theControlsAreItemsOfTheFoodPackWithTheComponentsTheRulesCheck() throws IOException {
        Path items = Path.of(System.getProperty("paletter.root", "..")).resolve("data/addons/food-probe/items");
        for (var control : FoodProbe.CONTROLS) {
            JsonObject item = JsonParser.parseString(Files.readString(items.resolve(control.item().substring("probe:".length()) + ".json"))).getAsJsonObject()
                .getAsJsonObject("minecraft:item");
            assertEquals(control.item(), item.getAsJsonObject("description").get("identifier").getAsString());
            JsonObject components = item.getAsJsonObject("components");
            JsonObject food = components.getAsJsonObject("minecraft:food");
            assertEquals(control.nutrition(), food.get("nutrition").getAsInt());
            assertEquals(control.saturationModifier(), food.get("saturation_modifier").getAsDouble());
            assertEquals(control.canAlwaysEat(), food.get("can_always_eat").getAsBoolean());
            assertEquals(control.useDuration(), Math.round(components.getAsJsonObject("minecraft:use_modifiers").get("use_duration").getAsDouble() * 20),
                "the component is in seconds");
        }
    }
}
