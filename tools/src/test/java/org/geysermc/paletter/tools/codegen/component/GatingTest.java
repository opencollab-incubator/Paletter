package org.geysermc.paletter.tools.codegen.component;

import com.google.gson.JsonObject;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class GatingTest {
    /**
     * The builds without a gating capture yet: the recapture's {@code update} writes {@code spec-gating/gating.json} (no BDS ran for it
     * here). The capture is not essential: a missing file only leaves {@code @BedrockExperiment} unverified. A build with the file that
     * is still listed fails, and so does one without it that is not listed.
     */
    private static final Set<String> PENDING = Set.of("1.26.36.1", "1.26.45.1", "1.26.52.3", "1.26.63.1", "1.26.70.24");

    private static void write(Path bds, String build, String component, String without, String with) throws IOException {
        Path file = bds.resolve(build).resolve(Gating.FILE);
        Files.createDirectories(file.getParent());
        JsonObject json = Gating.render(build, 1, List.of(), List.of(new Gating.Entry(component, without, with)));
        Files.writeString(file, json.toString());
    }

    @Test
    void theFileIsMarkedGeneratedAndReadBackOldestBuildFirst(@TempDir Path bds) throws IOException {
        write(bds, "1.26.45.1", "block:minecraft:support", "accepted", "accepted");
        write(bds, "1.26.9.1", "block:minecraft:support", "rejected", null);
        assertTrue(Gating.render("1.0.0.0", 1, List.of(), List.of()).get("_generated").getAsString().startsWith("Generated by"));
        List<Gating.Result> results = Gating.read(bds).get("block:minecraft:support");
        assertEquals(List.of("1.26.9.1", "1.26.45.1"), results.stream().map(Gating.Result::build).toList());
        assertEquals(List.of(true, false), results.stream().map(Gating.Result::gated).toList());
        assertTrue(Gating.read(bds.resolve("missing")).isEmpty(), "no captures: unverified, never a failure");
    }

    @Test
    void aComponentRejectedWithExperimentsOnIsReportedNotGated(@TempDir Path bds) throws IOException {
        write(bds, "1.26.9.1", "block:minecraft:never", "rejected", "rejected");
        write(bds, "1.26.45.1", "block:minecraft:never", "rejected", "rejected");
        write(bds, "1.26.45.1", "block:minecraft:later", "rejected", "accepted");
        Map<String, List<Gating.Result>> results = Gating.read(bds);
        assertEquals(List.of("block:minecraft:never"), Gating.rejectedEverywhere(results));
        assertFalse(results.get("block:minecraft:never").getFirst().gated());
    }

    @Test
    void everyBuildHasItsFileOrIsPending() throws IOException {
        Path data = Path.of("..", "data", "bds").toAbsolutePath().normalize();
        Set<String> without = new TreeSet<>();
        try (var builds = Files.list(data)) {
            builds.filter(Files::isDirectory).filter(b -> !Files.exists(b.resolve(Gating.FILE))).forEach(b -> without.add(b.getFileName().toString()));
        }
        assertEquals(PENDING, without, "the builds without gating.json must be PENDING exactly");
    }
}
