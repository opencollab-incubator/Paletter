package org.geysermc.paletter.tools.data;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.cloudburstmc.nbt.NbtMap;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Everything generated says so, and names its generator: generated sources, generated JSON ({@code _generated} first key),
 * bundled data, the API dump and the packs; hand-written inputs carry no such marker; captures from BDS are the
 * directories of {@code data/bds}, described in {@code docs/data-pipeline.md}. Every file of {@code data/model} and every
 * file directly in {@code data/bds} or in one of its builds is in exactly one of the sets below, so a new output fails
 * until someone says whether it is generated, hand-written or captured.
 */
class GeneratedMarkersTest {
    private static final Path ROOT = Path.of(System.getProperty("paletter.root", ".."));
    private static final Set<String> GENERATED_MODEL = Set.of("components.json", "mappings.json", "constants-history.json",
        "bds-feedback.json", "bds-keys.json", "coverage.md", "variant_names.txt");
    private static final Set<String> HAND_MODEL = Set.of("api.json", "fixtures.json", "constant-names.txt", "ATTRIBUTION.md");
    private static final Set<String> GENERATED_BDS = Set.of("builds.md");
    private static final Set<String> GENERATED_BUILD = Set.of("inventory.json", "whitebox.json", "whitebox-coverage.md", "update-report.md");
    /** What BDS (or its Script API dump) gave, kept as it came. */
    private static final Set<String> CAPTURED_BUILD = Set.of("dump.json.gz", "behaviour-dump.json.gz", "education.json", "experiments.json");

    private static String read(String file) throws IOException {
        return Files.readString(ROOT.resolve(file), StandardCharsets.UTF_8);
    }

    private static JsonObject json(String file) throws IOException {
        return JsonParser.parseString(read(file)).getAsJsonObject();
    }

    @Test
    void everyGeneratedSourceHasItsHeader() throws IOException {
        try (Stream<Path> files = Files.walk(ROOT.resolve("paletter/src/generated"))) {
            List<Path> sources = files.filter(Files::isRegularFile).toList();
            assertFalse(sources.isEmpty());
            for (Path source : sources) {
                String first = Files.readAllLines(source, StandardCharsets.UTF_8).getFirst();
                assertTrue(first.startsWith("// Generated by ") && !first.isBlank(), source + " lacks its generated header: " + first);
            }
        }
    }

    @Test
    void generatedJsonCarriesItsMarker() throws IOException {
        for (String file : GENERATED_MODEL.stream().filter(name -> name.endsWith(".json")).toList()) {
            String marker = json("data/model/" + file).get("_generated").getAsString();
            assertTrue(marker.startsWith("Generated by ") && marker.contains("Do not edit"), file + ": " + marker);
        }
        assertTrue(read("data/model/coverage.md").contains("Generated by `./gradlew :tools:inferMappings`"));
        assertTrue(read("data/bds/builds.md").startsWith("<!-- Generated by "));
        try (Stream<Path> builds = Files.list(ROOT.resolve("data/bds"))) {
            for (Path inventory : builds.map(build -> build.resolve("inventory.json")).filter(Files::isRegularFile).toList()) {
                String marker = JsonParser.parseString(Files.readString(inventory)).getAsJsonObject().get("_generated").getAsString();
                assertTrue(marker.startsWith("Generated by `bds-inventory`") && marker.contains("Do not edit"), inventory + ": " + marker);
            }
        }
        try (Stream<Path> builds = Files.list(ROOT.resolve("data/bds"))) {
            for (Path build : builds.toList()) {
                Path facts = build.resolve("whitebox.json");
                if (Files.isRegularFile(facts)) {
                    String marker = JsonParser.parseString(Files.readString(facts)).getAsJsonObject().get("_generated").getAsString();
                    assertTrue(marker.startsWith("Generated by `whitebox`") && marker.contains("Do not edit"), facts + ": " + marker);
                }
                Path coverage = build.resolve("whitebox-coverage.md");
                if (Files.isRegularFile(coverage)) {
                    assertTrue(Files.readString(coverage).startsWith("<!-- Generated by `whitebox-coverage`"), coverage.toString());
                }
            }
        }
        try (Stream<Path> builds = Files.list(ROOT.resolve("data/bds"))) {
            for (Path report : builds.map(build -> build.resolve("update-report.md")).filter(Files::isRegularFile).toList()) {
                assertTrue(Files.readString(report).startsWith("<!-- Generated by `./gradlew :tools:run --args=\"update "), report.toString());
            }
        }
    }

    @Test
    void handWrittenInputsAreNotMarkedGenerated() throws IOException {
        for (String file : HAND_MODEL) {
            assertFalse(read("data/model/" + file).contains("_generated"), file);
            assertFalse(read("data/model/" + file).toLowerCase().contains("generated by"), file);
        }
    }

    @Test
    void everyDataFileIsClassified() throws IOException {
        List<String> unclassified = new ArrayList<>();
        try (Stream<Path> files = Files.walk(ROOT.resolve("data/model"))) {
            for (Path file : files.filter(Files::isRegularFile).toList()) {
                String name = ROOT.resolve("data/model").relativize(file).toString().replace('\\', '/');
                if (!GENERATED_MODEL.contains(name) && !HAND_MODEL.contains(name)) {
                    unclassified.add("data/model/" + name);
                }
            }
        }
        try (Stream<Path> top = Files.list(ROOT.resolve("data/bds"))) {
            for (Path entry : top.toList()) {
                if (Files.isRegularFile(entry) && !GENERATED_BDS.contains(entry.getFileName().toString())) {
                    unclassified.add("data/bds/" + entry.getFileName());
                } else if (Files.isDirectory(entry)) {
                    try (Stream<Path> build = Files.list(entry)) {
                        for (Path file : build.filter(Files::isRegularFile).toList()) {
                            String name = file.getFileName().toString();
                            if (!GENERATED_BUILD.contains(name) && !CAPTURED_BUILD.contains(name)) {
                                unclassified.add("data/bds/" + entry.getFileName() + "/" + name);
                            }
                        }
                    }
                }
            }
        }
        assertEquals(List.of(), unclassified, "not classified as generated, hand-written or captured in GeneratedMarkersTest");
        for (String name : GENERATED_MODEL) {
            assertTrue(Files.isRegularFile(ROOT.resolve("data/model/" + name)), name + " is classified but does not exist");
        }
        for (String name : HAND_MODEL) {
            assertTrue(Files.isRegularFile(ROOT.resolve("data/model/" + name)), name + " is classified but does not exist");
        }
        for (String name : List.of("variant_names.txt", "coverage.md")) {
            assertTrue(String.join("\n", Files.readAllLines(ROOT.resolve("data/model/" + name)).subList(0, 5)).contains("Generated by"), name);
        }
    }

    @Test
    void bundledDataCarriesItsMarker() throws IOException {
        Path dir = ROOT.resolve("paletter/src/main/resources/paletter");
        List<String> versions = Files.readAllLines(dir.resolve("versions.txt"));
        assertTrue(versions.getFirst().contains("Generated by"));
        assertTrue(Files.readAllLines(ROOT.resolve(VariantNames.FILE)).getFirst().contains("Generated by"), VariantNames.FILE);
        // One <version>.nbt per bundled version (the first word of each line), preview included
        List<String> files = new ArrayList<>(versions.stream().filter(line -> !line.isBlank() && !line.startsWith("#"))
            .map(line -> line.split(" ")[0] + ".nbt").toList());
        assertFalse(files.isEmpty());
        files.add("properties.nbt");
        for (String file : files) {
            NbtMap root = Nbt.readGzip(dir.resolve(file));
            assertTrue(root.getString("_generated", "").startsWith("Generated by "), file);
        }
        assertTrue(Nbt.readGzip(dir.resolve("behaviour.nbt")).getString("_generated", "").startsWith("Generated by "), "behaviour.nbt");
        assertTrue(Nbt.readGzip(dir.resolve("voxel_shapes.nbt")).getString("_generated", "").startsWith("Generated by "), "voxel_shapes.nbt");
        assertTrue(read("data/behaviour/REPORT.md").startsWith("<!-- Generated by "), "data/behaviour/REPORT.md");
    }

    @Test
    void theApiDumpAndThePacksCarryTheirMarker() throws IOException {
        assertTrue(read("paletter/api/paletter.api").startsWith("// Generated by `./gradlew :paletter:apiDump`"));
        for (String pack : List.of("capture/behavior_pack", "capture/resource_pack", "creative/behavior_pack")) {
            assertTrue(read("data/addons/" + pack + "/manifest.json").contains("Generated by"), pack);
        }
    }
}
