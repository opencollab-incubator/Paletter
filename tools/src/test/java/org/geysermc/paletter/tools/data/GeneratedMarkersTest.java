package org.geysermc.paletter.tools.data;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.cloudburstmc.nbt.NbtMap;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Everything generated says so, and names its generator: generated sources, generated JSON ({@code _generated} first key),
 * bundled data, the API dump and the packs; hand-written inputs carry no such marker; captures from BDS are listed in
 * {@code data/bds/CAPTURED.md}.
 */
class GeneratedMarkersTest {
    private static final Path ROOT = Path.of(System.getProperty("paletter.root", ".."));

    private static String read(String file) throws IOException {
        return Files.readString(ROOT.resolve(file), StandardCharsets.UTF_8);
    }

    private static JsonObject json(String file) throws IOException {
        return JsonParser.parseString(read(file)).getAsJsonObject();
    }

    @Test
    void everyGeneratedSourceHasItsHeader() throws IOException {
        try (Stream<Path> files = Files.walk(ROOT.resolve("paletter/src/generated"))) {
            List<Path> sources = files.filter(Files::isRegularFile).toList();
            assertFalse(sources.isEmpty());
            for (Path source : sources) {
                String first = Files.readAllLines(source, StandardCharsets.UTF_8).getFirst();
                assertTrue(first.startsWith("// Generated by ") && !first.isBlank(), source + " lacks its generated header: " + first);
            }
        }
    }

    @Test
    void generatedJsonCarriesItsMarker() throws IOException {
        for (String file : List.of("components.json", "mappings.json", "constants-history.json")) {
            String marker = json("data/model/" + file).get("_generated").getAsString();
            assertTrue(marker.startsWith("Generated by ") && marker.contains("Do not edit"), file + ": " + marker);
        }
        // bds-feedback.json already used _comment
        assertTrue(json("data/model/bds-feedback.json").get("_comment").getAsString().startsWith("Generated by `./gradlew"));
        assertTrue(read("data/model/coverage.md").contains("Generated by `./gradlew :tools:inferMappings`"));
    }

    @Test
    void handWrittenInputsAreNotMarkedGenerated() throws IOException {
        for (String file : List.of("api.json", "fixtures.json", "transforms.json", "names.json")) {
            assertFalse(read("data/model/" + file).contains("_generated"), file);
            assertFalse(read("data/model/" + file).toLowerCase().contains("generated by"), file);
        }
    }

    @Test
    void bundledDataCarriesItsMarker() throws IOException {
        Path dir = ROOT.resolve("paletter/src/main/resources/paletter");
        for (String file : List.of("26.30.nbt", "26.40.nbt", "26.50.nbt", "26.60.nbt", "properties.nbt")) {
            NbtMap root = Nbt.readGzip(dir.resolve(file));
            assertTrue(root.getString("_generated", "").startsWith("Generated by "), file);
        }
        assertTrue(Files.readAllLines(dir.resolve("versions.txt")).getFirst().contains("Generated by"));
    }

    @Test
    void theApiDumpAndThePacksCarryTheirMarker() throws IOException {
        assertTrue(read("paletter/api/paletter.api").startsWith("// Generated by `./gradlew :paletter:apiDump`"));
        for (String pack : List.of("capture/behavior_pack", "capture/resource_pack", "creative/behavior_pack")) {
            assertTrue(read("data/addons/" + pack + "/manifest.json").contains("Generated by"), pack);
        }
    }

    @Test
    void everyCapturedBuildIsListedAsCaptured() throws IOException {
        String captured = read("data/bds/CAPTURED.md");
        try (Stream<Path> builds = Files.list(ROOT.resolve("data/bds"))) {
            for (Path build : builds.filter(Files::isDirectory).toList()) {
                assertTrue(captured.contains("`" + build.getFileName() + "`"), build.getFileName() + " is not listed in data/bds/CAPTURED.md");
            }
        }
    }
}
