import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The give capture with synthetic packets and files; the committed files are checked against {@code Palette#itemOf}. */
class GiveCaptureTest {
    /**
     * The builds without a {@code block-items.json} in their vanilla capture yet: the recapture's hashed vanilla start writes it. A build
     * with the file that is still listed fails, and so does one without it that is not listed.
     */
    private static final Set<String> PENDING = Set.of("1.26.36.1", "1.26.45.1", "1.26.52.3", "1.26.63.1", "1.26.70.24");

    private static final Map<String, String> DATA = Map.of(
        "minecraft:unpowered_repeater", "minecraft:repeater",
        "minecraft:stone", "minecraft:stone",
        "minecraft:wall_sign", "minecraft:oak_sign",
        "minecraft:lit_furnace", "minecraft:furnace");

    private static InventorySlotPacket slot(String item, int runtimeId, int slot) {
        ItemDefinition definition = new SimpleItemDefinition(item, runtimeId, ItemVersion.DATA_DRIVEN, false, null);
        InventorySlotPacket packet = new InventorySlotPacket();
        packet.setContainerId(ContainerId.INVENTORY);
        packet.setSlot(slot);
        packet.setItem(ItemData.builder().definition(definition).count(1).build());
        return packet;
    }

    @Test
    void onlyBlocksWithAnotherItemAreGiven() {
        assertEquals(List.of("minecraft:lit_furnace", "minecraft:unpowered_repeater", "minecraft:wall_sign"), GiveCapture.blocks(DATA));
    }

    @Test
    void theFileIsMarkedGeneratedAndReadBackWithUnansweredBlocksUnverified(@TempDir Path directory) throws IOException {
        String text = GiveCapture.render("1.2.3.4", DATA, Map.of("minecraft:unpowered_repeater", new GiveCapture.Given("minecraft:repeater", 4),
            "minecraft:wall_sign", new GiveCapture.Given("minecraft:spruce_sign", 5)));
        JsonObject json = JsonParser.parseString(text).getAsJsonObject();
        assertTrue(json.get("_generated").getAsString().startsWith("Generated by"));
        Path file = Files.writeString(directory.resolve(GiveCapture.FILE), text);
        List<GiveCapture.Entry> entries = GiveCapture.read(file);
        assertEquals(3, entries.size());
        assertEquals(new GiveCapture.Entry("minecraft:lit_furnace", "minecraft:furnace", null, -1), entries.get(0));
        assertEquals(new GiveCapture.Entry("minecraft:unpowered_repeater", "minecraft:repeater", "minecraft:repeater", 4), entries.get(1));

        GiveCapture.Check check = GiveCapture.check(entries, DATA::get);
        assertEquals(1, check.matched());
        assertEquals(List.of("minecraft:lit_furnace"), check.unverified());
        assertEquals(1, check.mismatches().size());
        assertTrue(check.mismatches().getFirst().contains("minecraft:spruce_sign (slot 5)"), check.mismatches().toString());
    }

    @Test
    void theClientGivesOneBlockAtATimeAndRecordsTheSlot() {
        CaptureClient client = new CaptureClient(null, null).give(List.of("minecraft:unpowered_repeater", "minecraft:wall_sign"));
        List<BedrockPacket> sent = new ArrayList<>();
        client.startGives(7, sent::add);
        assertEquals(7, ((SetLocalPlayerAsInitializedPacket) sent.get(0)).getRuntimeEntityId());
        assertEquals("/give @s minecraft:unpowered_repeater 1", ((CommandRequestPacket) sent.get(1)).getCommand());
        assertEquals(2, sent.size(), "the next one waits for the answer");

        client.inventorySlot(slot("minecraft:repeater", 5, 3));
        assertEquals("/give @s minecraft:wall_sign 1", ((CommandRequestPacket) sent.get(2)).getCommand());
        // Not an item: an empty slot is no answer
        client.inventorySlot(slot("minecraft:air", 0, 0));
        assertEquals(3, sent.size());
        // No answer in time: the block stays unanswered and the gives end
        client.giveTimeouts(Long.MAX_VALUE);
        assertEquals(3, sent.size());

        Map<String, GiveCapture.Given> gives = client.result().gives;
        assertEquals(new GiveCapture.Given("minecraft:repeater", 3), gives.get("minecraft:unpowered_repeater"));
        assertNull(gives.get("minecraft:wall_sign"));
    }

    @Test
    void theCommittedFilesAgreeWithItemOf() throws IOException {
        Path data = Path.of("..", "data", "bds").toAbsolutePath().normalize();
        Set<String> without = new TreeSet<>();
        String newest = null;
        try (var builds = Files.list(data)) {
            for (Path build : (Iterable<Path>) builds.filter(Files::isDirectory).sorted()::iterator) {
                if (Files.exists(build.resolve("vanilla").resolve(GiveCapture.FILE))) {
                    newest = build.getFileName().toString();
                } else {
                    without.add(build.getFileName().toString());
                }
            }
        }
        assertEquals(PENDING, without, "the builds without vanilla/block-items.json must be PENDING exactly");
        if (newest == null) {
            return;
        }
        // The newest build's file against the newest bundled data
        Paletter paletter = Paletter.builder().previews(true).build();
        Palette palette = paletter.vanilla(paletter.latest());
        GiveCapture.Check check = GiveCapture.check(GiveCapture.read(data.resolve(newest).resolve("vanilla").resolve(GiveCapture.FILE)), block -> {
            BedrockItemType item = palette.itemOf(BedrockBlockType.fromIdentifier(block));
            return item == null ? null : item.identifier();
        });
        assertTrue(check.mismatches().isEmpty(), "the client got another item than itemOf says: " + check.mismatches());
    }
}
