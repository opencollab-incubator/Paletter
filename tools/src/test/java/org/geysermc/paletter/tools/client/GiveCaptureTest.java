package org.geysermc.paletter.tools.client;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.cloudburstmc.protocol.bedrock.data.definitions.ItemDefinition;
import org.cloudburstmc.protocol.bedrock.data.definitions.SimpleItemDefinition;
import org.cloudburstmc.protocol.bedrock.data.inventory.ContainerId;
import org.cloudburstmc.protocol.bedrock.data.inventory.ItemData;
import org.cloudburstmc.protocol.bedrock.data.inventory.ItemVersion;
import org.cloudburstmc.protocol.bedrock.packet.BedrockPacket;
import org.cloudburstmc.protocol.bedrock.packet.CommandOutputPacket;
import org.cloudburstmc.protocol.bedrock.packet.CommandRequestPacket;
import org.cloudburstmc.protocol.bedrock.packet.InventorySlotPacket;
import org.cloudburstmc.protocol.bedrock.packet.SetLocalPlayerAsInitializedPacket;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The give capture with synthetic packets and files; the committed files are checked in BlockItemsCaptureTest. */
class GiveCaptureTest {
    private static final Map<String, String> DATA = Map.of(
        "minecraft:unpowered_repeater", "minecraft:repeater",
        "minecraft:stone", "minecraft:stone",
        "minecraft:wall_sign", "minecraft:oak_sign",
        "minecraft:lit_furnace", "minecraft:furnace");

    private static InventorySlotPacket slot(String item, int runtimeId, int slot) {
        ItemDefinition definition = new SimpleItemDefinition(item, runtimeId, ItemVersion.DATA_DRIVEN, false, null);
        InventorySlotPacket packet = new InventorySlotPacket();
        packet.setContainerId(ContainerId.INVENTORY);
        packet.setSlot(slot);
        packet.setItem(ItemData.builder().definition(definition).count(1).build());
        return packet;
    }

    private static CommandOutputPacket output(int successCount) {
        CommandOutputPacket packet = new CommandOutputPacket();
        packet.setSuccessCount(successCount);
        return packet;
    }

    @Test
    void onlyBlocksWithAnotherItemAreGivenAndTheirItems() {
        assertEquals(List.of("minecraft:lit_furnace", "minecraft:unpowered_repeater", "minecraft:wall_sign"), GiveCapture.blocks(DATA));
        assertEquals(List.of("minecraft:lit_furnace", "minecraft:unpowered_repeater", "minecraft:wall_sign", "minecraft:furnace", "minecraft:repeater",
            "minecraft:oak_sign"), GiveCapture.identifiers(DATA));
    }

    @Test
    void theFileIsMarkedGeneratedAndReadBackWithNoAnswerUnverifiedAndAnErrorRejected(@TempDir Path directory) throws IOException {
        String text = GiveCapture.render("1.2.3.4", DATA, Map.of(
            "minecraft:unpowered_repeater", GiveCapture.Given.REJECTED,
            "minecraft:repeater", new GiveCapture.Given("minecraft:repeater", 4),
            "minecraft:wall_sign", new GiveCapture.Given("minecraft:spruce_sign", 5),
            "minecraft:oak_sign", new GiveCapture.Given("minecraft:oak_sign", 6)));
        JsonObject json = JsonParser.parseString(text).getAsJsonObject();
        assertTrue(json.get("_generated").getAsString().startsWith("Generated by"));
        Path file = Files.writeString(directory.resolve(GiveCapture.FILE), text);
        List<GiveCapture.Entry> entries = GiveCapture.read(file);
        assertEquals(3, entries.size());
        assertEquals(new GiveCapture.Entry("minecraft:lit_furnace", "minecraft:furnace", null, null), entries.get(0));
        assertEquals(new GiveCapture.Entry("minecraft:unpowered_repeater", "minecraft:repeater", GiveCapture.Given.REJECTED,
            new GiveCapture.Given("minecraft:repeater", 4)), entries.get(1));

        GiveCapture.Check check = GiveCapture.check(entries, DATA::get);
        assertEquals(2, check.matched());
        assertEquals(List.of("minecraft:lit_furnace (block of minecraft:lit_furnace)", "minecraft:furnace (item of minecraft:lit_furnace)"), check.unverified());
        assertEquals(List.of("minecraft:unpowered_repeater (block of minecraft:unpowered_repeater)"), check.rejected());
        assertEquals(1, check.mismatches().size());
        assertTrue(check.mismatches().getFirst().contains("minecraft:spruce_sign (slot 5)"), check.mismatches().toString());
    }

    @Test
    void theClientGivesOneIdentifierAtATimeAndRecordsTheSlotOrTheError() {
        CaptureClient client = new CaptureClient(null, null).give(List.of("minecraft:unpowered_repeater", "minecraft:repeater", "minecraft:wall_sign"));
        List<BedrockPacket> sent = new ArrayList<>();
        client.startGives(7, sent::add);
        assertEquals(7, ((SetLocalPlayerAsInitializedPacket) sent.get(0)).getRuntimeEntityId());
        assertEquals("/give @s minecraft:unpowered_repeater 1", ((CommandRequestPacket) sent.get(1)).getCommand());
        assertEquals(2, sent.size(), "the next one waits for the answer");

        // A command error answers the block: rejected
        client.commandOutput(output(0));
        assertEquals("/give @s minecraft:repeater 1", ((CommandRequestPacket) sent.get(2)).getCommand());
        // An empty slot is no answer, and a successful output is not one either
        client.inventorySlot(slot("minecraft:air", 0, 0));
        client.commandOutput(output(1));
        assertEquals(3, sent.size());
        client.inventorySlot(slot("minecraft:repeater", 5, 3));
        assertEquals("/give @s minecraft:wall_sign 1", ((CommandRequestPacket) sent.get(3)).getCommand());
        // No answer in time: it stays unanswered and the gives end
        client.giveTimeouts(Long.MAX_VALUE);
        assertEquals(4, sent.size());

        Map<String, GiveCapture.Given> gives = client.result().gives;
        assertTrue(gives.get("minecraft:unpowered_repeater").rejected());
        assertEquals(new GiveCapture.Given("minecraft:repeater", 3), gives.get("minecraft:repeater"));
        assertNull(gives.get("minecraft:wall_sign"));
    }
}
