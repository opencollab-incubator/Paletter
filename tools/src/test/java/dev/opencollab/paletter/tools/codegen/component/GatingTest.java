package dev.opencollab.paletter.tools.codegen.component;

import com.google.gson.JsonObject;
import dev.opencollab.paletter.tools.CommittedBuilds;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class GatingTest {
    private static void write(Path bds, String build, String component, String without, String with) throws IOException {
        Path file = bds.resolve(build).resolve(Gating.FILE);
        Files.createDirectories(file.getParent());
        JsonObject json = Gating.render(build, 1, List.of(), List.of(new Gating.Entry(component, without, with)));
        Files.writeString(file, json.toString());
    }

    @Test
    void theFileIsMarkedGeneratedAndReadBackOldestBuildFirst(@TempDir Path bds) throws IOException {
        write(bds, "1.26.45.1", "block:minecraft:support", "accepted", "accepted");
        write(bds, "1.26.9.1", "block:minecraft:support", "rejected", "accepted");
        assertTrue(Gating.render("1.0.0.0", 1, List.of(), List.of()).get("_generated").getAsString().startsWith("Generated by"));
        List<Gating.Result> results = Gating.read(bds).get("block:minecraft:support");
        assertEquals(List.of("1.26.9.1", "1.26.45.1"), results.stream().map(Gating.Result::build).toList());
        assertEquals(List.of(true, false), results.stream().map(r -> r.gated(false)).toList());
        assertTrue(Gating.read(bds.resolve("missing")).isEmpty(), "no captures: unverified, never a failure");
    }

    @Test
    void aComponentRejectedWithExperimentsOnIsReportedNotGated(@TempDir Path bds) throws IOException {
        write(bds, "1.26.9.1", "block:minecraft:never", "rejected", "rejected");
        write(bds, "1.26.45.1", "block:minecraft:never", "rejected", "rejected");
        write(bds, "1.26.45.1", "block:minecraft:later", "rejected", "accepted");
        Map<String, List<Gating.Result>> results = Gating.read(bds);
        assertEquals(List.of("block:minecraft:never"), Gating.rejectedEverywhere(results));
        assertFalse(results.get("block:minecraft:never").getFirst().gated(false));
    }

    @Test
    void gatedNeedsTheComponentAcceptedWithExperimentsAndAServerOnlyOneNeedsARejection() {
        assertTrue(new Gating.Result("b", Gating.REJECTED, Gating.ACCEPTED).gated(false));
        assertTrue(new Gating.Result("b", Gating.REJECTED, Gating.ACCEPTED).gated(true));
        assertTrue(new Gating.Result("b", Gating.IGNORED, Gating.ACCEPTED).gated(false));
        assertFalse(new Gating.Result("b", Gating.IGNORED, Gating.ACCEPTED).gated(true), "the same wire as the control proves nothing for server-only");
        assertFalse(new Gating.Result("b", Gating.IGNORED, Gating.IGNORED).gated(false), "ignored with experiments too: nothing shown");
        assertFalse(new Gating.Result("b", Gating.REJECTED, null).gated(false), "no with-experiments run: unverified");
        assertFalse(new Gating.Result("b", Gating.REJECTED, Gating.REJECTED).gated(false));
        assertFalse(new Gating.Result("b", Gating.ACCEPTED, Gating.ACCEPTED).gated(false));
    }

    @Test
    void everyBuildHasItsFileOrIsPending() throws IOException {
        CommittedBuilds.assertPending(Gating.FILE, b -> Files.exists(CommittedBuilds.directory(b).resolve(Gating.FILE)));
    }
}
