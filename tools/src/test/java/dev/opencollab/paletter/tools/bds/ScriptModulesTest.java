package dev.opencollab.paletter.tools.bds;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class ScriptModulesTest {
    /**
     * The builds without a {@code script-modules.json} yet: the recapture's {@code update} writes it from each build's docgen output (none
     * is committed or cached to read it from now, and the manifest of the behaviour dump add-on is not known to come from a run of the
     * build). A build with the file that is still listed fails, and so does one without it that is not listed.
     */
    private static final Set<String> PENDING = Set.of("1.26.36.1", "1.26.45.1", "1.26.52.3", "1.26.63.1", "1.26.70.24");

    private static void touch(Path file) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, "x");
    }

    @Test
    void theVersionsOfADirectoryPerVersion(@TempDir Path docs) throws IOException {
        touch(docs.resolve("script_modules/@minecraft/server/1.0.0/index.d.ts"));
        touch(docs.resolve("script_modules/@minecraft/server/2.12.0-beta/index.d.ts"));
        touch(docs.resolve("script_modules/@minecraft/server/2.2.0/index.d.ts"));
        touch(docs.resolve("script_modules/@minecraft/server-ui/2.1.0-beta/index.d.ts"));
        assertEquals(List.of("1.0.0", "2.2.0", "2.12.0-beta"), ScriptModules.parse(docs));
    }

    @Test
    void theVersionsOfAFilePerVersion(@TempDir Path docs) throws IOException {
        touch(docs.resolve("script_modules/@minecraft_server_2.10.0-beta.json"));
        touch(docs.resolve("script_modules/@minecraft_server_2.10.0.json"));
        touch(docs.resolve("script_modules/@minecraft_server-gametest_1.0.0-beta.json"));
        assertEquals(List.of("2.10.0-beta", "2.10.0"), ScriptModules.parse(docs));
    }

    @Test
    void noVersionFailsAndSaysWhatIsThere(@TempDir Path docs) throws IOException {
        touch(docs.resolve("script_modules/other/readme.txt"));
        IOException e = assertThrows(IOException.class, () -> ScriptModules.parse(docs));
        assertTrue(e.getMessage().contains("other"), e.getMessage());
        assertThrows(IOException.class, () -> ScriptModules.parse(docs.resolve("missing")));
    }

    @Test
    void theBetaIsTheNewestBetaOfTheBuild() {
        assertEquals("2.12.0-beta", ScriptModules.betaVersion(List.of("1.0.0", "2.12.0-beta", "2.2.0", "2.9.0-beta", "2.12.0")));
        assertThrows(IllegalStateException.class, () -> ScriptModules.betaVersion(List.of("1.0.0", "2.2.0")));
    }

    @Test
    void theFileIsMarkedGeneratedAndReadBack(@TempDir Path data) throws IOException {
        Files.createDirectories(data.resolve("1.2.3.4"));
        Files.writeString(ScriptModules.file(data, "1.2.3.4"), ScriptModules.render("1.2.3.4", List.of("2.0.0", "2.1.0-beta")));
        JsonObject json = JsonParser.parseString(Files.readString(ScriptModules.file(data, "1.2.3.4"))).getAsJsonObject();
        assertTrue(json.get("_generated").getAsString().startsWith("Generated by"));
        assertEquals(List.of("2.0.0", "2.1.0-beta"), ScriptModules.versions(data, "1.2.3.4"));
        assertThrows(IOException.class, () -> ScriptModules.versions(data, "9.9.9.9"), "a build without the file fails");
    }

    @Test
    void everyBuildHasItsFileOrIsPending() throws IOException {
        Path data = Path.of("..", "data", "bds").toAbsolutePath().normalize();
        Set<String> without = new TreeSet<>();
        try (var builds = Files.list(data)) {
            builds.filter(Files::isDirectory).filter(b -> !Files.exists(b.resolve(ScriptModules.FILE))).forEach(b -> without.add(b.getFileName().toString()));
        }
        assertEquals(PENDING, without, "the builds without script-modules.json must be PENDING exactly");
    }
}
