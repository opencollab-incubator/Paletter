package dev.opencollab.paletter.tools.model.infer;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** {@link MappingEvidence}: the evidence keys leave mappings.json for their own file, window by window. */
class MappingEvidenceTest {
    private static JsonObject json(String text) {
        return JsonParser.parseString(text).getAsJsonObject();
    }

    @Test
    void theEvidenceKeysMoveAndTheRulesStay() {
        JsonObject mappings = json("""
            {"components": {"item:x": {"windows": [
              {"protocols": [1], "status": "sent", "fields": {
                "a": {"accepted": 3, "rejected": 1, "bdsErrors": ["bad"], "rejectedValues": ["-1"], "status": "inferred",
                      "rules": [{"kind": "identity"}], "whenAbsent": {"x.a": "1 (int)"}},
                "b": {"status": "dropped"}},
               "forms": {"boolean": {"accepted": 2, "rejected": 0, "status": "inferred", "unexplained": [{"wire": "x.c"}]}}},
              {"protocols": [2, 3], "status": "rejected", "fields": {}}]}}}""");
        JsonObject evidence = MappingEvidence.split(mappings);
        JsonObject a = mappings.getAsJsonObject("components").getAsJsonObject("item:x").getAsJsonArray("windows").get(0).getAsJsonObject()
            .getAsJsonObject("fields").getAsJsonObject("a");
        assertEquals(json("{\"status\": \"inferred\", \"rules\": [{\"kind\": \"identity\"}], \"whenAbsent\": {\"x.a\": \"1 (int)\"}}"), a);
        JsonObject first = evidence.getAsJsonObject("components").getAsJsonObject("item:x").getAsJsonArray("windows").get(0).getAsJsonObject();
        assertEquals(json("{\"accepted\": 3, \"rejected\": 1, \"rejectedValues\": [\"-1\"], \"bdsErrors\": [\"bad\"]}"),
            first.getAsJsonObject("fields").getAsJsonObject("a"));
        assertFalse(first.getAsJsonObject("fields").has("b"), "no evidence, no entry");
        assertEquals(json("{\"accepted\": 2, \"rejected\": 0, \"unexplained\": [{\"wire\": \"x.c\"}]}"), first.getAsJsonObject("forms").getAsJsonObject("boolean"));
        // the windows of mappings.json, by their protocols
        assertEquals(json("{\"protocols\": [2, 3]}"),
            evidence.getAsJsonObject("components").getAsJsonObject("item:x").getAsJsonArray("windows").get(1).getAsJsonObject());
        assertTrue(evidence.get("_generated").getAsString().startsWith("Generated by "));
    }

    /** The committed mappings.json holds no evidence key: no generator input carries what only Coverage reads. */
    @Test
    void theCommittedMappingsHoldNoEvidence() throws IOException {
        Path root = Path.of(System.getProperty("paletter.root", ".."));
        JsonObject mappings = json(Files.readString(root.resolve("data/model/mappings.json"), StandardCharsets.UTF_8));
        mappings.getAsJsonObject("components").entrySet().forEach(c -> c.getValue().getAsJsonObject().getAsJsonArray("windows").forEach(w -> {
            for (String group : new String[] {"fields", "forms"}) {
                JsonObject fields = w.getAsJsonObject().has(group) ? w.getAsJsonObject().getAsJsonObject(group) : new JsonObject();
                fields.entrySet().forEach(f -> MappingEvidence.KEYS.forEach(key ->
                    assertFalse(f.getValue().getAsJsonObject().has(key), c.getKey() + " " + f.getKey() + " " + key)));
            }
        }));
    }
}
