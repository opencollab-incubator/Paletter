/** The give capture with synthetic packets and files; the committed files are checked in BlockItemsCaptureTest. */
class GiveCaptureTest {
    private static final Map<String, String> DATA = Map.of(
        "minecraft:unpowered_repeater", "minecraft:repeater",
        "minecraft:stone", "minecraft:stone",
        "minecraft:wall_sign", "minecraft:oak_sign",
        "minecraft:lit_furnace", "minecraft:furnace");

    private static InventorySlotPacket slot(String item, int runtimeId, int slot) {
        ItemDefinition definition = new SimpleItemDefinition(item, runtimeId, ItemVersion.DATA_DRIVEN, false, null);
        InventorySlotPacket packet = new InventorySlotPacket();
        packet.setContainerId(ContainerId.INVENTORY);
        packet.setSlot(slot);
        packet.setItem(ItemData.builder().definition(definition).count(1).build());
        return packet;
    }

    private static CommandOutputPacket output(int successCount) {
        CommandOutputPacket packet = new CommandOutputPacket();
        packet.setSuccessCount(successCount);
        return packet;
    }

    @Test
    void onlyBlocksWithAnotherItemAreGivenAndTheirItems() {
        assertEquals(List.of("minecraft:lit_furnace", "minecraft:unpowered_repeater", "minecraft:wall_sign"), GiveCapture.blocks(DATA));
        assertEquals(List.of("minecraft:lit_furnace", "minecraft:unpowered_repeater", "minecraft:wall_sign", "minecraft:furnace", "minecraft:repeater",
            "minecraft:oak_sign"), GiveCapture.identifiers(DATA));
    }

    @Test
    void theFileIsMarkedGeneratedAndReadBackWithNoAnswerUnverifiedAndAnErrorRejected(@TempDir Path directory) throws IOException {
        String text = GiveCapture.render("1.2.3.4", DATA, Map.of(
            "minecraft:unpowered_repeater", GiveCapture.Given.REJECTED,
            "minecraft:repeater", new GiveCapture.Given("minecraft:repeater", 4),
            "minecraft:wall_sign", new GiveCapture.Given("minecraft:spruce_sign", 5),
            "minecraft:oak_sign", new GiveCapture.Given("minecraft:oak_sign", 6)), true);
        JsonObject json = JsonParser.parseString(text).getAsJsonObject();
        assertTrue(json.get("_generated").getAsString().startsWith("Generated by"));
        Path file = Files.writeString(directory.resolve(GiveCapture.FILE), text);
        List<GiveCapture.Entry> entries = GiveCapture.read(file);
        assertEquals(3, entries.size());
        assertEquals(new GiveCapture.Entry("minecraft:lit_furnace", "minecraft:furnace", null, null), entries.get(0));
        assertEquals(new GiveCapture.Entry("minecraft:unpowered_repeater", "minecraft:repeater", GiveCapture.Given.REJECTED,
            new GiveCapture.Given("minecraft:repeater", 4)), entries.get(1));

        GiveCapture.Check check = GiveCapture.check(entries, DATA::get);
        assertEquals(2, check.matched());
        assertEquals(List.of("minecraft:lit_furnace (block of minecraft:lit_furnace)", "minecraft:furnace (item of minecraft:lit_furnace)"), check.unverified());
        assertEquals(List.of("minecraft:unpowered_repeater (block of minecraft:unpowered_repeater)"), check.rejected());
        assertEquals(1, check.mismatches().size());
        assertTrue(check.mismatches().getFirst().contains("minecraft:spruce_sign (slot 5)"), check.mismatches().toString());
    }

    /** BDS 1.26.36.1 to 1.26.70.24: the wheat block's identifier is also an item's, and /give takes the item. */
    @Test
    void aBlockIdentifierThatIsAnItemOfItsOwnIsNoMismatch() {
        List<GiveCapture.Entry> entries = List.of(new GiveCapture.Entry("minecraft:wheat", "minecraft:wheat_seeds",
            new GiveCapture.Given("minecraft:wheat", 0), new GiveCapture.Given("minecraft:wheat_seeds", 0)));
        GiveCapture.Check check = GiveCapture.check(entries, Map.of("minecraft:wheat", "minecraft:wheat_seeds")::get);
        assertEquals(1, check.matched());
        assertEquals(List.of("minecraft:wheat (block of minecraft:wheat)"), check.ownItems());
        assertTrue(check.mismatches().isEmpty(), check.mismatches().toString());
    }

    @Test
    void theClientGivesOneIdentifierAtATimeAndRecordsTheSlotOrTheError() {
        CaptureClient client = new CaptureClient(null, null).give(List.of("minecraft:unpowered_repeater", "minecraft:repeater", "minecraft:wall_sign"), DATA);
        List<BedrockPacket> sent = new ArrayList<>();
        client.startGives(7, sent::add);
        assertEquals(7, ((SetLocalPlayerAsInitializedPacket) sent.get(0)).getRuntimeEntityId());
        assertEquals("/give @s minecraft:unpowered_repeater 1", ((CommandRequestPacket) sent.get(1)).getCommand());
        assertEquals(2, sent.size(), "the next one waits for the answer");

        // A command error answers the block: rejected
        client.commandOutput(output(0));
        assertEquals("/give @s minecraft:repeater 1", ((CommandRequestPacket) sent.get(2)).getCommand());
        // An empty slot is no answer, and a successful output is not one either
        client.inventorySlot(slot("minecraft:air", 0, 0));
        client.commandOutput(output(1));
        assertEquals(3, sent.size());
        client.inventorySlot(slot("minecraft:repeater", 5, 3));
        // The item is cleared again (the inventory is full after 36 gives); the output of the clear is no answer
        assertEquals("/clear @s", ((CommandRequestPacket) sent.get(3)).getCommand());
        client.commandOutput(output(0));
        assertEquals("/give @s minecraft:wall_sign 1", ((CommandRequestPacket) sent.get(4)).getCommand());
        // No answer in time: it stays unanswered, and a clear follows before anything else
        client.giveTimeouts(Long.MAX_VALUE);
        assertEquals(6, sent.size());
        assertEquals("/clear @s", ((CommandRequestPacket) sent.get(5)).getCommand());

        Map<String, GiveCapture.Given> gives = client.result().gives;
        assertTrue(gives.get("minecraft:unpowered_repeater").rejected());
        assertEquals(new GiveCapture.Given("minecraft:repeater", 3), gives.get("minecraft:repeater"));
        assertNull(gives.get("minecraft:wall_sign"));
    }

    /** What BDS sent for a give: a successful command output and the whole inventory in a content packet, never a slot packet. */
    private static InventoryContentPacket content(String... items) {
        InventoryContentPacket packet = new InventoryContentPacket();
        packet.setContainerId(ContainerId.INVENTORY);
        List<ItemData> contents = new ArrayList<>();
        for (int i = 0; i < items.length; i++) {
            contents.add(items[i] == null ? ItemData.AIR : ItemData.builder()
                .definition(new SimpleItemDefinition(items[i], 100 + i, ItemVersion.DATA_DRIVEN, false, null)).count(1).build());
        }
        packet.setContents(contents);
        return packet;
    }

    @Test
    void aGiveAnsweredByTheInventoryContentIsRecordedAndClearedAgain() {
        CaptureClient client = new CaptureClient(null, null).give(List.of("minecraft:unpowered_repeater", "minecraft:repeater", "minecraft:oak_sign"));
        List<BedrockPacket> sent = new ArrayList<>();
        // The join sequence sends the empty inventory
        client.inventoryContent(content(null, null));
        client.startGives(7, sent::add);
        client.commandOutput(output(0));
        assertEquals("/give @s minecraft:repeater 1", ((CommandRequestPacket) sent.get(2)).getCommand());

        client.commandOutput(output(1));
        assertEquals(3, sent.size(), "a successful output answers nothing");
        client.inventoryContent(content(null, "minecraft:repeater"));
        assertEquals("/clear @s", ((CommandRequestPacket) sent.get(3)).getCommand());
        // The clear empties the inventory again, and the next give lands in the same slot
        client.inventoryContent(content(null, null));
        client.commandOutput(output(1));
        assertEquals("/give @s minecraft:oak_sign 1", ((CommandRequestPacket) sent.get(4)).getCommand());
        client.inventoryContent(content(null, "minecraft:oak_sign"));

        Map<String, GiveCapture.Given> gives = client.result().gives;
        assertTrue(gives.get("minecraft:unpowered_repeater").rejected());
        assertEquals(new GiveCapture.Given("minecraft:repeater", 1), gives.get("minecraft:repeater"));
        assertEquals(new GiveCapture.Given("minecraft:oak_sign", 1), gives.get("minecraft:oak_sign"));
    }

    @Test
    void anInventoryContentThatChangesNothingIsNoAnswerAndUnansweredGivesEndTheGives() {
        List<String> identifiers = List.of("a", "b", "c", "d", "e", "f", "g");
        CaptureClient client = new CaptureClient(null, null).give(identifiers);
        List<BedrockPacket> sent = new ArrayList<>();
        client.inventoryContent(content("minecraft:stone"));
        client.startGives(7, sent::add);
        client.inventoryContent(content("minecraft:stone"));
        assertEquals(2, sent.size());
        for (int i = 0; i < 10; i++) {
            client.giveTimeouts(Long.MAX_VALUE);
        }
        // Five gives in a row without an answer: the server does not answer in a way this client knows, the rest is not sent
        assertEquals(5, sent.stream().filter(p -> p instanceof CommandRequestPacket c && c.getCommand().startsWith("/give")).count());
        assertTrue(client.result().gives.isEmpty());
        assertTrue(client.result().givesAborted, "the answers are partial");
    }

    /** A late answer of a give that timed out must not be recorded against the next identifier. */
    @Test
    void aLateAnswerAfterATimeoutIsNotRecordedAgainstTheNextGive() {
        CaptureClient client = new CaptureClient(null, null).give(List.of("minecraft:wall_sign", "minecraft:stone"), DATA);
        List<BedrockPacket> sent = new ArrayList<>();
        client.startGives(7, sent::add);
        client.giveTimeouts(Long.MAX_VALUE);
        assertEquals("/clear @s", ((CommandRequestPacket) sent.get(2)).getCommand());
        // The late answer comes while the clear is pending: no give is current
        client.inventorySlot(slot("minecraft:oak_sign", 5, 3));
        assertEquals(3, sent.size(), "the next give waits for the clear's output");
        client.commandOutput(output(1));
        assertEquals("/give @s minecraft:stone 1", ((CommandRequestPacket) sent.get(3)).getCommand());
        // Another late item, which is neither the identifier nor the data's item for it, is no answer either
        client.inventorySlot(slot("minecraft:oak_sign", 5, 4));
        assertTrue(client.result().gives.isEmpty());
        client.inventorySlot(slot("minecraft:stone", 6, 5));
        assertEquals(new GiveCapture.Given("minecraft:stone", 5), client.result().gives.get("minecraft:stone"));
        assertNull(client.result().gives.get("minecraft:wall_sign"));
    }

    @Test
    void aCutShortRunIsNotStagedAndADropOfAnswersIsReported(@TempDir Path directory) throws IOException {
        Map<String, GiveCapture.Given> two = Map.of("minecraft:lit_furnace", new GiveCapture.Given("minecraft:furnace", 0),
            "minecraft:furnace", new GiveCapture.Given("minecraft:furnace", 1));
        Path committed = Files.writeString(directory.resolve("committed.json"), GiveCapture.render("1", DATA, two, true));
        Path cut = Files.writeString(directory.resolve("cut.json"), GiveCapture.render("2", DATA, Map.of(), false));
        Path fewer = Files.writeString(directory.resolve("fewer.json"), GiveCapture.render("2", DATA, Map.of(), true));
        Path more = Files.writeString(directory.resolve("more.json"), GiveCapture.render("2", DATA, two, true));
        assertEquals(new GiveCapture.Staging(false, null), GiveCapture.staging(cut, committed));
        assertTrue(GiveCapture.staging(fewer, committed).stage());
        assertTrue(GiveCapture.staging(fewer, committed).drop().contains("2 (committed) to 0"));
        assertEquals(new GiveCapture.Staging(true, null), GiveCapture.staging(more, committed));
        assertEquals(new GiveCapture.Staging(true, null), GiveCapture.staging(more, directory.resolve("none.json")));
    }
}
