package dev.opencollab.paletter.tools.codegen;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** What every generator relies on: writing, checking, line endings, stale files and the command line. */
class GeneratedSourcesTest {
    private static final String HEADER = "// Generated by test";
    private static final Map<String, String> FILES = Map.of("pkg/A.java", HEADER + "\nclass A {}\n", "pkg/B.java", HEADER + "\nclass B {}\n");

    private static List<String> sync(Path root, Map<String, String> files, boolean check) throws IOException {
        return GeneratedSources.sync(root, files, List.of("pkg"), HEADER, check);
    }

    @Test
    void generateWritesWhatIsMissingOrDiffersAndCheckOnlyReportsIt(@TempDir Path root) throws IOException {
        assertEquals(List.of("pkg/A.java: missing", "pkg/B.java: missing"), sync(root, FILES, true));
        assertFalse(Files.exists(root.resolve("pkg/A.java")), "check writes nothing");
        assertEquals(2, sync(root, FILES, false).size());
        assertEquals(List.of(), sync(root, FILES, true));

        Files.writeString(root.resolve("pkg/A.java"), "changed", StandardCharsets.UTF_8);
        assertEquals(List.of("pkg/A.java: outdated"), sync(root, FILES, true));
        assertEquals("changed", Files.readString(root.resolve("pkg/A.java")));
        assertEquals(List.of("pkg/A.java: outdated"), sync(root, FILES, false));
        assertEquals(List.of(), sync(root, FILES, true));
    }

    @Test
    void lineEndingsDoNotCount(@TempDir Path root) throws IOException {
        sync(root, FILES, false);
        Files.writeString(root.resolve("pkg/A.java"), FILES.get("pkg/A.java").replace("\n", "\r\n"), StandardCharsets.UTF_8);
        assertEquals(List.of(), sync(root, FILES, true));
        assertEquals(List.of(), sync(root, FILES, false));
    }

    @Test
    void aFileWithTheHeaderThatIsNoLongerGeneratedIsDeletedAndAHandWrittenOneIsNot(@TempDir Path root) throws IOException {
        sync(root, FILES, false);
        Files.writeString(root.resolve("pkg/Dead.java"), HEADER + "\nclass Dead {}\n", StandardCharsets.UTF_8);
        Files.writeString(root.resolve("pkg/Hand.java"), "class Hand {}\n", StandardCharsets.UTF_8);
        assertEquals(List.of("pkg/Dead.java: no longer generated"), sync(root, FILES, true));
        assertTrue(Files.exists(root.resolve("pkg/Dead.java")));
        assertEquals(List.of("pkg/Dead.java: no longer generated"), sync(root, FILES, false));
        assertFalse(Files.exists(root.resolve("pkg/Dead.java")));
        assertTrue(Files.exists(root.resolve("pkg/Hand.java")));
    }

    @Test
    void theCommandLineFailsOnWhatItDoesNotKnow() {
        GeneratedSources.Arguments check = GeneratedSources.Arguments.parse(new String[] {"check", "--root", "r"}, false);
        assertTrue(check.check());
        assertEquals(Path.of("r"), check.root());
        GeneratedSources.Arguments generate = GeneratedSources.Arguments.parse(new String[] {"generate", "--sources", "s"}, true);
        assertFalse(generate.check());
        assertEquals(Path.of("s"), generate.sources());
        assertThrows(IllegalArgumentException.class, () -> GeneratedSources.Arguments.parse(new String[] {"generate", "--sorces", "s"}, true));
        assertThrows(IllegalArgumentException.class, () -> GeneratedSources.Arguments.parse(new String[] {"generate", "--sources", "s"}, false));
        assertThrows(IllegalArgumentException.class, () -> GeneratedSources.Arguments.parse(new String[] {"build"}, false));
        assertThrows(IllegalArgumentException.class, () -> GeneratedSources.Arguments.parse(new String[] {"generate", "--root"}, false));
    }
}
