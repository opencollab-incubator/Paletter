package dev.opencollab.paletter.tools.codegen.component;

import com.google.gson.JsonParser;
import dev.opencollab.paletter.tools.codegen.GeneratedSources;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * {@code generate --root DIR} writes the component API from {@code data/model}, and the behaviour keys from
 * {@link BehaviourKeys}, {@code mappings.json} and the newest behaviour probe capture ({@link BehaviourSource}), checked against
 * the newest BDS captures ({@link BehaviourEvidence});
 * {@code check --root DIR} fails if the committed sources differ (and lists the files).
 */
public final class Main {
    /** Directories whose generated files this generator owns (a file with the generator header that it no longer writes is deleted). */
    static final List<String> OWNED = List.of("dev/opencollab/paletter/item/component", "dev/opencollab/paletter/block/component",
        "dev/opencollab/paletter/internal/component", "dev/opencollab/paletter/behaviour", "dev/opencollab/paletter/internal/behaviour");

    /** How the header of every generated file starts (after {@code //}): also how stale files of this generator are recognized. */
    static final String GENERATOR = "Generated by :tools:generateComponentApi";

    /** The committed generated sources, relative to the root. */
    public static final String SOURCES ="paletter/src/generated/java";

    private Main() {
    }

    public static void main(String[] args) throws Exception {
        GeneratedSources.Arguments arguments = GeneratedSources.Arguments.parse(args, true);
        Path root = arguments.root();
        System.exit(report(root, arguments.sources() == null ? root.resolve(SOURCES) : arguments.sources(), arguments.check()));
    }

    /** @return the process exit code: 1 if {@code check} found a file out of date */
    public static int report(Path root, Path sources, boolean check) throws IOException {
        return GeneratedSources.report(changes(root, sources, check), check, ":tools:generateComponentApi");
    }

    /** @return what differs, one entry per file ({@link GeneratedSources#sync}); written unless {@code check} */
    static List<String> changes(Path root, Path sources, boolean check) throws IOException {
        Path model = root.resolve("data/model");
        ComponentGenerator.Inputs inputs = ComponentGenerator.read(model, version(root), context(root));
        ComponentGenerator.Output output = ComponentGenerator.generateAll(inputs);
        Map<String, String> files = new java.util.TreeMap<>(output.sources());
        // Reported, not removed: BDS rejects these with the experiments on, in every build with a gating capture
        Gating.rejectedEverywhere(inputs.context().gating()).forEach(id -> System.out.println("rejected by BDS even with experiments on: " + id));
        Path probe = newestProbe(root);
        files.putAll(BehaviourSource.generate(BehaviourKeys.KEYS, inputs.mappings(), probe == null ? null
            : JsonParser.parseString(Files.readString(probe, StandardCharsets.UTF_8)).getAsJsonObject(),
            probe == null ? "" : "data/bds/" + probe.getParent().getParent().getFileName() + "/behaviour-probe/capture.json",
            BehaviourEvidence.read(root)));
        // The names to keep (ApiHistory): beside the model for the committed sources, else in the sources directory given
        boolean committed = sources.toAbsolutePath().normalize().equals(root.resolve(SOURCES).toAbsolutePath().normalize());
        List<String> changes = new ArrayList<>(GeneratedSources.sync(committed ? model : sources, Map.of(ApiHistory.FILE, output.history()), List.of(),
            "// " + GENERATOR, check));
        changes.addAll(GeneratedSources.sync(sources, files, OWNED, "// " + GENERATOR, check));
        return changes;
    }

    /** A public top level type declaration (nothing indented in front: nested types are not meant). */
    private static final Pattern PUBLIC_TYPE = Pattern.compile("^public\\s+(?:[\\w-]+\\s+)*?(?:class|interface|enum|record|@interface)\\s+(\\w+)", Pattern.MULTILINE);

    /**
     * The names the generated API must keep unique and the experiment toggles of the captured servers.
     * <p>
     * Order of the generators: {@code :tools:generateConstants} before {@code :tools:generateComponentApi}. The reserved
     * names include the types the constants generator writes (a new constant class must exist before a component may not
     * take its name), and the toggles come from the same captures as {@code BedrockExperiments}.
     *
     * @return the public top level types next to the generated ones (every source file outside {@code internal} that this
     *         generator does not write itself: hand-written ones and the constants), and the toggle ids by the experiment
     *         name the creator docs use
     */
    static ComponentGenerator.Context context(Path root) throws IOException {
        Set<String> reserved = new TreeSet<>();
        for (String dir : List.of("paletter/src/main/java", "paletter/src/generated/java")) {
            Path base = root.resolve(dir);
            if (!Files.isDirectory(base)) {
                continue;
            }
            try (Stream<Path> files = Files.walk(base)) {
                for (Path file : files.filter(f -> f.toString().endsWith(".java")).toList()) {
                    String rel = base.relativize(file).toString().replace('\\', '/');
                    String source = Files.readString(file, StandardCharsets.UTF_8);
                    if (rel.startsWith("dev/opencollab/paletter/internal/") || source.startsWith("// " + GENERATOR)) {
                        continue;
                    }
                    Matcher type = PUBLIC_TYPE.matcher(source);
                    while (type.find()) {
                        reserved.add(type.group(1));
                    }
                }
            }
        }
        List<ExperimentToggles.Toggle> toggles = ExperimentToggles.read(root.resolve("paletter/src/main/resources/paletter"), root.resolve("data/bds"));
        return new ComponentGenerator.Context(reserved, ExperimentToggles.names(toggles), Gating.read(root.resolve("data/bds")));
    }

    /** @return the {@code behaviour-probe/capture.json} of the newest BDS build under {@code data/bds}, or null if none has one */
    static Path newestProbe(Path root) throws IOException {
        Path bds = root.resolve("data/bds");
        if (!Files.isDirectory(bds)) {
            return null;
        }
        try (Stream<Path> builds = Files.list(bds)) {
            return builds.map(build -> build.resolve("behaviour-probe/capture.json")).filter(Files::isRegularFile)
                .max(Comparator.comparing(capture -> capture.getParent().getParent().getFileName().toString(), Main::compareVersions))
                .orElse(null);
        }
    }

    /** Compares dotted versions number by number ({@code 1.26.63.1} after {@code 1.26.9.0}). */
    static int compareVersions(String a, String b) {
        String[] x = a.split("\\.");
        String[] y = b.split("\\.");
        for (int i = 0; i < Math.max(x.length, y.length); i++) {
            int c = Integer.compare(i < x.length ? Integer.parseInt(x[i]) : 0, i < y.length ? Integer.parseInt(y[i]) : 0);
            if (c != 0) {
                return c;
            }
        }
        return 0;
    }

    static String version(Path root) throws IOException {
        Matcher m = Pattern.compile("^version=(.+)$", Pattern.MULTILINE).matcher(Files.readString(root.resolve("gradle.properties")));
        if (!m.find()) {
            throw new IllegalStateException("no version in gradle.properties");
        }
        return m.group(1).replace("-SNAPSHOT", "");
    }
}
