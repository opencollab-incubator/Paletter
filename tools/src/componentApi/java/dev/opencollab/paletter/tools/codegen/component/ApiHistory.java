package dev.opencollab.paletter.tools.codegen.component;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.opencollab.paletter.tools.codegen.component.ApiModel.Comp;
import dev.opencollab.paletter.tools.codegen.component.ApiModel.Field;
import dev.opencollab.paletter.tools.codegen.component.ApiModel.ObjType;
import dev.opencollab.paletter.tools.codegen.component.ComponentGenerator.GenerationException;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * {@code data/model/api-history.json}: every Java name the component API has emitted, by a stable identity, the counterpart
 * of {@code constants-history.json} for the components. A recorded name is reused, never recomputed, so neither a docs
 * restructure nor a new component renames existing API (docs/api.md, "Evolution"):
 * <ul>
 *     <li>{@code classes}: component id -> class name. A new collision gives the {@code Block}/{@code Item} prefix to the
 *     newcomer ({@link NameCollisions#prefix}). A component that left the model is {@code {name, removed}} and keeps a
 *     stand-in class ({@link StandIns});</li>
 *     <li>{@code types}: {@code <component id>:<JSON path>} -> nested class name;</li>
 *     <li>{@code enums}: {@code <component id>:<JSON path>} -> open value class name;</li>
 *     <li>{@code constants}: {@code <component id>:<JSON path>=<value>} -> constant name;</li>
 *     <li>{@code fields}: {@code <component id>:<JSON path>} -> {@code {name, wire, type, nullable, default}}: the accessor
 *     and builder setter, the wire leaves the newest capture writes from it, and what a stand-in needs. When a path leaves
 *     the model and exactly one new field of the same object writes the same leaves, the JSON key was renamed: the old
 *     accessor and setter stay as {@code @Deprecated} delegates, and the entry names its successor ({@code renamedTo}),
 *     which later runs resolve directly. Without such a field the entry is marked {@code removed} and keeps a stand-in
 *     ({@link StandIns}); two such fields fail. When no field matches by wire leaves (none recorded, or Bedrock renamed
 *     the NBT key too) while the object gained fields, the maintainer decides: api.json {@code renamedFields}
 *     (old identity -> new identity) or {@code removedFields}; generation fails until then. The recorded {@code type} and {@code nullable} of a live field are its
 *     locked Java shape ({@link #checkShapes}).</li>
 * </ul>
 * Entries are never dropped, so the file only grows, and nothing generated from it disappears: a stand-in goes only when
 * its entry is deleted deliberately, in a major release (docs/api.md, "Lifecycle of versioned content"). A hand name in
 * {@code api.json} must agree with the recorded one: a deliberate rename changes both. Generated by
 * {@code :tools:generateComponentApi}.
 */
final class ApiHistory {
    static final String FILE = "api-history.json";
    static final List<String> SECTIONS = List.of("classes", "types", "enums", "constants", "fields");

    /** What the committed file records, by section. */
    private final Map<String, JsonObject> recorded = new TreeMap<>();
    /** The names of this run, by section and identity (fields: the name only; the wire is added by {@link #write}). */
    private final Map<String, Map<String, String>> current = new TreeMap<>();

    ApiHistory(JsonObject json) {
        for (String section : SECTIONS) {
            recorded.put(section, json.has(section) ? json.getAsJsonObject(section) : new JsonObject());
            current.put(section, new TreeMap<>());
        }
    }

    /**
     * The name of an identity: the recorded one, else the hand one, else the computed one.
     *
     * @param hand the name {@code api.json} gives it, or null
     * @throws GenerationException if {@code api.json} names it other than the history does
     */
    String name(String section, String key, String computed, String hand) {
        String recordedName = recordedName(section, key);
        if (recordedName != null && hand != null && !hand.equals(recordedName)) {
            throw new GenerationException(key + ": api.json names it " + hand + ", data/model/" + FILE + " " + recordedName
                + "; a deliberate rename changes both");
        }
        String name = recordedName != null ? recordedName : hand != null ? hand : computed;
        current.get(section).put(key, name);
        return name;
    }

    /** @return the recorded name of an identity, or null */
    String recordedName(String section, String key) {
        JsonElement e = recorded.get(section).get(key);
        if (e == null) {
            return null;
        }
        return e.isJsonObject() ? e.getAsJsonObject().get("name").getAsString() : e.getAsString();
    }

    /** Records the final class name of a component (after {@link NameCollisions#prefix}). */
    void className(Comp c) {
        current.get("classes").put(c.id, c.className);
    }

    /**
     * A field whose JSON key Bedrock renamed: the old accessor and setter delegate to {@code now}.
     *
     * @param owner the object both are fields of
     */
    record Renamed(Comp c, ObjType owner, String oldName, String oldKey, Field now) {
    }

    /**
     * A field that left the model without a successor: it keeps a {@code @Deprecated(forRemoval = true)} stand-in
     * ({@link StandIns}).
     *
     * @param owner the object it was a field of
     * @param entry its {@code fields} entry
     */
    record RemovedField(Comp c, ObjType owner, String key, JsonObject entry) {
    }

    /** The fields of live components that left the model ({@link #renames} finds them). */
    final List<RemovedField> removedFields = new ArrayList<>();
    /** The successor of every renamed field, also one that kept its Java name: old identity -> new identity. */
    private final Map<String, String> renamedTo = new TreeMap<>();

    /**
     * Finds the renamed fields of the model (see the class Javadoc) and collects the removed ones ({@link #removedFields}).
     * An entry that names its successor ({@code renamedTo}) resolves to it directly, through a chain of renames; only an
     * entry without one is matched by its wire leaves.
     *
     * @return the renamed fields, for {@link ApiSource}
     */
    List<Renamed> renames(ApiModel model, JsonObject api) {
        JsonObject renamedFields = api.has("renamedFields") ? api.getAsJsonObject("renamedFields") : new JsonObject();
        Set<String> declaredRemoved = api.has("removedFields") ? strings(api.getAsJsonArray("removedFields")) : Set.of();
        List<Renamed> out = new ArrayList<>();
        removedFields.clear();
        renamedTo.clear();
        JsonObject fields = recorded.get("fields");
        // In the order of the written file, whatever the order of the file read
        for (String key : new TreeSet<>(fields.keySet())) {
            if (current.get("fields").containsKey(key)) {
                continue;
            }
            JsonObject entry = fields.getAsJsonObject(key);
            Comp c = model.components.stream().filter(x -> key.startsWith(x.id + ":")).findFirst().orElse(null);
            if (c == null) {
                continue; // the component left the model: its stand-in has the field (StandIns)
            }
            String path = key.substring(c.id.length() + 1);
            String parent = ModelFields.parent(path);
            ObjType owner = objects(c).filter(o -> o.path.equals(parent)).findFirst().orElse(null);
            String oldName = entry.get("name").getAsString();
            Field successor;
            if (entry.has("renamedTo")) {
                successor = successor(c, key);
            } else if (renamedFields.has(key)) {
                String target = renamedFields.get(key).getAsString();
                successor = objects(c).flatMap(o -> o.fields.stream()).filter(f -> f.path != null && target.equals(c.id + ":" + f.path))
                    .findFirst().orElseThrow(() -> new GenerationException("api.json renamedFields: " + key + " -> " + target + ", which is no field"));
            } else {
                successor = wireSuccessor(c, owner, key, entry);
                if (successor == null && owner != null && !declaredRemoved.contains(key) && !entry.has("removed")) {
                    // Without equal wire leaves (an object or list field, a server only one, or Bedrock renamed the NBT key
                    // too) a new field of the same object may be the renamed one: the maintainer decides
                    List<String> newcomers = owner.fields.stream().filter(f -> f.path != null && !fields.has(c.id + ":" + f.path))
                        .map(f -> c.id + ":" + f.path).toList();
                    if (!newcomers.isEmpty()) {
                        throw new GenerationException(key + " (" + oldName + ") left the model while " + newcomers + " joined it: renamed or"
                            + " removed? Name the successor in api.json renamedFields {\"" + key + "\": \"<identity>\"}, or list it in"
                            + " removedFields to keep it as a stand-in");
                    }
                }
            }
            if (successor == null) {
                if (owner != null) {
                    removedFields.add(new RemovedField(c, owner, key, entry));
                }
                // else the object it was in left the model too: the stand-in of that object has it
                continue;
            }
            renamedTo.put(key, c.id + ":" + successor.path);
            ObjType successorOwner = objects(c).filter(o -> o.fields.contains(successor)).findFirst().orElseThrow();
            if (!oldName.equals(successor.java)) {
                out.add(new Renamed(c, successorOwner, oldName, key, successor));
            }
        }
        return out;
    }

    /** @return the live field a {@code renamedTo} chain from {@code key} ends at, or null if the chain ends outside the model */
    private Field successor(Comp c, String key) {
        JsonObject fields = recorded.get("fields");
        Set<String> seen = new TreeSet<>();
        String at = key;
        while (fields.has(at) && fields.getAsJsonObject(at).has("renamedTo")) {
            if (!seen.add(at)) {
                throw new GenerationException(key + ": the renamedTo entries of data/model/" + FILE + " form a cycle " + seen);
            }
            at = fields.getAsJsonObject(at).get("renamedTo").getAsString();
            String target = at;
            Field live = objects(c).flatMap(o -> o.fields.stream()).filter(f -> f.path != null && target.equals(c.id + ":" + f.path))
                .findFirst().orElse(null);
            if (live != null) {
                return live;
            }
        }
        return null;
    }

    /** @return the one new field of the same object that writes the wire leaves of a field that left the model, or null */
    private Field wireSuccessor(Comp c, ObjType owner, String key, JsonObject entry) {
        JsonObject fields = recorded.get("fields");
        Set<String> wire = strings(entry.getAsJsonArray("wire"));
        List<Field> candidates = new ArrayList<>();
        if (owner != null && !wire.isEmpty()) {
            for (Field f : owner.fields) {
                if (f.path != null && !fields.has(c.id + ":" + f.path) && wire.equals(wire(c, f))) {
                    candidates.add(f);
                }
            }
        }
        if (candidates.size() > 1) {
            throw new GenerationException(key + " left the model and " + candidates.stream().map(f -> f.path).toList()
                + " all write its wire leaves " + wire + ": which one it was renamed to is ambiguous; name it in api.json fields");
        }
        return candidates.isEmpty() ? null : candidates.getFirst();
    }

    /**
     * Locks the shape of every live field the history records: its model type ({@link StandIns#describe}, which names the
     * nested class it uses) and whether it is nullable (a boxed or a primitive accessor, a setter that takes null, a
     * required builder value) must be the recorded ones. A change of either breaks callers without a generation failure
     * otherwise: a docs default turns {@code Integer foo()} into {@code int foo()}, a split of merged types re-points a
     * field to another class, documented values turn a {@code String} into a value class.
     *
     * @throws GenerationException naming each changed field, both shapes and the entry to edit if the break is intended
     */
    void checkShapes(ApiModel model) {
        JsonObject fields = recorded.get("fields");
        List<String> changed = new ArrayList<>();
        liveFields(model).forEach((key, f) -> {
            JsonObject entry = fields.has(key) ? fields.getAsJsonObject(key) : null;
            if (entry == null || !entry.has("type")) {
                return;
            }
            String was = shape(entry.get("type").getAsString(), entry.has("nullable") && entry.get("nullable").getAsBoolean());
            String now = shape(StandIns.describe(f.type), f.nullable());
            if (!was.equals(now)) {
                changed.add(key + " was " + was + ", is now " + now);
            }
        });
        if (!changed.isEmpty()) {
            throw new GenerationException("the Java shape of recorded fields changed, which breaks callers: " + String.join("; ", changed)
                + ". Keep the old shape (api.json typeNames, optional, types), or, for an intended break (a major release), set the"
                + " entry's type and nullable in data/model/" + FILE + " fields to the new shape");
        }
    }

    private static String shape(String type, boolean nullable) {
        return type + (nullable ? " (nullable)" : "");
    }

    /** The live fields of the model by identity, the first object that has a path winning (as {@link #write} records them). */
    private static Map<String, Field> liveFields(ApiModel model) {
        Map<String, Field> out = new TreeMap<>();
        for (Comp c : model.components) {
            objects(c).forEach(o -> o.fields.stream().filter(f -> f.path != null).forEach(f -> out.putIfAbsent(c.id + ":" + f.path, f)));
        }
        return out;
    }

    /** @return the {@code fields} entries the committed file records, by identity */
    JsonObject recordedFields() {
        return recorded.get("fields");
    }

    /** @return the recorded entries of a section, by identity (a string, or an object with {@code name}) */
    JsonObject recordedSection(String section) {
        return recorded.get(section);
    }

    /**
     * @return the components the committed file records that have no class in this run, by id: they left the model
     *         ({@link StandIns})
     */
    List<String> removedComponents() {
        List<String> out = new ArrayList<>();
        for (String id : new TreeSet<>(recorded.get("classes").keySet())) {
            if (!current.get("classes").containsKey(id)) {
                out.add(id);
            }
        }
        return out;
    }

    /**
     * @return the new file: everything recorded, and this run's names. A field entry has the field's model type
     *         ({@link StandIns#describe}), {@code nullable} and {@code default}, which its stand-in needs once it leaves the
     *         model; an entry whose component or field left the model is marked {@code removed}.
     */
    String write(ApiModel model) {
        JsonObject out = new JsonObject();
        out.addProperty("_generated", "Generated by `./gradlew :tools:generateComponentApi`: every Java name the component API has"
            + " emitted, by stable identity. Names here are reused, never recomputed, and entries are never dropped. Do not edit, except to"
            + " rename deliberately (with api.json); see docs/data-pipeline.md.");
        Map<String, Field> fieldsByKey = new TreeMap<>();
        Map<String, Comp> owners = new TreeMap<>();
        for (Comp c : model.components) {
            objects(c).forEach(o -> o.fields.stream().filter(f -> f.path != null).forEach(f -> {
                fieldsByKey.putIfAbsent(c.id + ":" + f.path, f);
                owners.putIfAbsent(c.id + ":" + f.path, c);
            }));
        }
        for (String section : SECTIONS) {
            JsonObject merged = new JsonObject();
            Map<String, JsonElement> sorted = new TreeMap<>(recorded.get(section).asMap());
            current.get(section).forEach((key, name) -> {
                // Names of a component the docs leave too open to generate were never emitted
                if (!recorded.get(section).has(key) && model.components.stream().noneMatch(c -> key.equals(c.id) || key.startsWith(c.id + ":"))) {
                    return;
                }
                if (section.equals("fields")) {
                    JsonObject field = new JsonObject();
                    field.addProperty("name", name);
                    JsonArray wire = new JsonArray();
                    Field f = fieldsByKey.get(key);
                    if (f != null) {
                        wire(owners.get(key), f).forEach(wire::add);
                    } else if (recorded.get(section).has(key)) {
                        wire = recorded.get(section).getAsJsonObject(key).getAsJsonArray("wire");
                    }
                    field.add("wire", wire);
                    if (f != null) {
                        field.addProperty("type", StandIns.describe(f.type));
                        if (f.nullable()) {
                            field.addProperty("nullable", true);
                        }
                        if (f.defaultValue != null) {
                            field.add("default", f.defaultValue);
                        }
                    }
                    sorted.put(key, field);
                } else {
                    sorted.put(key, new com.google.gson.JsonPrimitive(name));
                }
            });
            if (section.equals("fields")) {
                for (String key : recorded.get(section).keySet()) {
                    if (current.get(section).containsKey(key)) {
                        continue;
                    }
                    JsonObject old = sorted.get(key).getAsJsonObject().deepCopy();
                    old.remove("renamedTo");
                    old.remove("removed");
                    if (renamedTo.containsKey(key)) {
                        old.addProperty("renamedTo", renamedTo.get(key));
                    } else {
                        old.addProperty("removed", true);
                    }
                    sorted.put(key, old);
                }
            }
            if (section.equals("classes")) {
                for (Comp c : model.removedComponents) {
                    JsonObject removed = new JsonObject();
                    removed.addProperty("name", c.className);
                    removed.addProperty("removed", true);
                    sorted.put(c.id, removed);
                }
            }
            sorted.forEach(merged::add);
            out.add(section, merged);
        }
        return new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(out) + "\n";
    }

    private static Stream<ObjType> objects(Comp c) {
        return Stream.concat(Stream.of(c.root), c.allTypes.stream());
    }

    /** The wire leaves the newest window with a result for a field ({@link Comp#evidence}) writes from it (the rules' {@code wire}). */
    static Set<String> wire(Comp c, Field f) {
        Set<String> out = new TreeSet<>();
        ApiModel.Window evidence = c.evidence(f.mappingKey);
        JsonObject mapping = evidence == null || f.mappingKey == null ? null : evidence.field(f.mappingKey);
        if (mapping != null) {
            collectWire(mapping, out);
        }
        return out;
    }

    /** A field mapping or rule: its {@code wire}, and those of its {@code rules} and of the rules of a union's forms ({@code by}). */
    private static void collectWire(JsonObject o, Set<String> out) {
        if (o.has("wire") && o.get("wire").isJsonPrimitive()) {
            out.add(o.get("wire").getAsString());
        }
        if (o.has("rules")) {
            o.getAsJsonArray("rules").forEach(rule -> collectWire(rule.getAsJsonObject(), out));
        }
        if (o.has("by")) {
            o.getAsJsonObject("by").entrySet().forEach(form -> collectWire(form.getValue().getAsJsonObject(), out));
        }
    }

    private static Set<String> strings(JsonArray array) {
        Set<String> out = new TreeSet<>();
        if (array != null) {
            array.forEach(e -> out.add(e.getAsString()));
        }
        return out;
    }
}
