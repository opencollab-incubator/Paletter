package dev.opencollab.paletter.tools.model;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.net.URLDecoder;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Reads the JSON schemas BDS writes with its documentation generator ({@code docs/json_schemas/server}) and flattens the item
 * and block component schemas into the facts the component model needs: per component and format version, per field path
 * (the notation of {@code components.json}: {@code a.b}, {@code a[]}, {@code a{}}) the JSON types, enum values, default,
 * limits, pattern, required, deprecated, underlying C++ type and the runtime constraint text. Written by
 * {@link #write} as {@code data/bds/<build>/schema.json}, read by {@link Schema}.
 *
 * <p>File names are not stable between builds, so this starts from the entry points ({@code Item Components.json},
 * {@code Block Components.json}, {@code Traits.json}), named after the format version directory they are in, and follows
 * the {@code $ref}s. Components that have the same definition in several formats are written once, with their formats.
 *
 * <p>Alternatives ({@code oneOf}, {@code anyOf}) are read one by one and then combined per path: types and enum values are
 * the union (an enum says which types it came from, {@code enumTypes}), a member is {@code required} when every alternative
 * that has it requires it ({@code requiredInSome} when only some do), and {@code minimum}, {@code maximum} and
 * {@code default} come from one alternative together, never mixed from two.
 *
 * <p>What the extract could not read is in the file too: a component that failed is in {@code skipped} (and missing from its
 * format), a schema keyword it does not know in {@code unhandledKeywords}.
 */
public final class SchemaExtract {
    /** The marker the file carries, as every generated JSON. */
    private static final String GENERATED = "Generated by `bds-schema` (tools, SchemaExtract) from the json_schemas BDS %s writes with its documentation "
        + "generator (test_config.json). Facts only (keys, types, enums, limits); the raw tree stays in the cache. Do not edit: run the command again.";

    private static final Pattern ENTRY = Pattern.compile("^(Item Components|Block Components)( \\(Beta\\))?\\.json$|^Traits\\.json$");
    private static final Pattern FORBIDDEN = Pattern.compile("^\\^\\(\\?!\\((.*)\\)\\$\\)$");
    private static final int MAX_DEPTH = 16;

    /** Facets that stay together when an alternative provides them: a default is only valid within its own limits. */
    private static final List<String> GROUP = List.of("minimum", "maximum", "default");
    /** The other scalar facets, kept as they are (the first alternative that has one counts). */
    private static final List<String> SCALARS = List.of("minLength", "maxLength", "minItems", "maxItems", "maxProperties", "pattern", "multipleOf");

    /** Keywords the extract reads, and the ones it knows it does not need (nothing else may appear in a component schema). */
    private static final Set<String> KNOWN = Set.of("type", "enum", "default", "minimum", "maximum", "minLength", "maxLength", "minItems",
        "maxItems", "maxProperties", "pattern", "deprecated", "$ref", "oneOf", "anyOf", "properties", "required", "items",
        "additionalProperties", "propertyNames", "multipleOf", "title", "$schema", "$id", "description", "minProperties", "x-underlying-type",
        "x-runtime-constraint-description");

    private final Map<Path, JsonObject> files = new HashMap<>();
    private final Set<String> unhandled = new TreeSet<>();
    private final List<String> skipped = new ArrayList<>();
    private Path server;

    private SchemaExtract() {
    }

    /** @param docs the {@code docs} directory BDS wrote (it has {@code json_schemas/server}) */
    public static JsonObject extract(Path docs, String build) throws IOException {
        return new SchemaExtract().read(docs.resolve("json_schemas/server"), build);
    }

    /** Writes the extract of {@code docs} as the {@code schema.json} {@code file}. */
    public static void write(Path docs, String build, Path file) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, render(extract(docs, build)), StandardCharsets.UTF_8);
    }

    public static String render(JsonObject schema) {
        return Model.GSON.toJson(schema) + "\n";
    }

    /**
     * The block component entry point of the builds that name it {@code block/<format>/Components.json} (title "Components"):
     * 1.26.45.1 and 1.26.52.3 have only that one (format 1.26.20), 1.26.63.1 on also {@code block_components/1.26.60/Block
     * Components.json}. Where both name one format, the {@code Block Components} file is read last and counts.
     */
    private static boolean blockComponents(Path file) {
        Path format = file.getParent();
        return file.getFileName().toString().equals("Components.json") && format != null && format.getParent() != null
            && format.getParent().getFileName().toString().equals("block");
    }

    private JsonObject read(Path server, String build) throws IOException {
        this.server = server;
        // kind -> format -> entry point
        Map<String, Map<String, Path>> entries = new LinkedHashMap<>();
        try (Stream<Path> tree = Files.walk(server)) {
            for (Path file : tree.filter(f -> ENTRY.matcher(f.getFileName().toString()).matches() || blockComponents(f)).sorted().toList()) {
                String name = file.getFileName().toString();
                String kind = name.startsWith("Item") ? "item" : name.startsWith("Block") || blockComponents(file) ? "block" : "trait";
                entries.computeIfAbsent(kind, k -> new TreeMap<>(Schema::compareVersions)).put(file.getParent().getFileName().toString(), file);
            }
        }
        if (entries.isEmpty()) {
            throw new IOException("No component schemas under " + server + " (no Item Components, Block Components or Traits file)");
        }
        JsonObject result = new JsonObject();
        result.addProperty(Model.GENERATED_KEY, GENERATED.formatted(build));
        result.addProperty("bdsVersion", build);
        JsonObject formats = new JsonObject();
        JsonObject kinds = new JsonObject();
        for (var kind : entries.entrySet()) {
            JsonArray names = new JsonArray();
            kind.getValue().keySet().forEach(names::add);
            formats.add(kind.getKey(), names);
            kinds.add(kind.getKey(), components(kind.getKey(), kind.getValue()));
        }
        result.add("formats", formats);
        kinds.entrySet().forEach(e -> result.add(e.getKey(), e.getValue()));
        if (!skipped.isEmpty()) {
            JsonArray list = new JsonArray();
            skipped.forEach(list::add);
            result.add("skipped", list);
        }
        if (!unhandled.isEmpty()) {
            JsonArray list = new JsonArray();
            unhandled.forEach(list::add);
            result.add("unhandledKeywords", list);
        }
        return result;
    }

    /** component -> its definitions, each with the formats that have exactly it. */
    private JsonObject components(String kind, Map<String, Path> formats) throws IOException {
        Map<String, JsonArray> byComponent = new TreeMap<>();
        for (var format : formats.entrySet()) {
            JsonObject entry = load(format.getValue());
            Set<String> forbidden = forbidden(kind, format.getValue());
            JsonObject properties = entry.has("properties") ? entry.getAsJsonObject("properties") : new JsonObject();
            for (var component : properties.entrySet()) {
                Map<String, JsonObject> fields = new LinkedHashMap<>();
                try {
                    visit(component.getValue().getAsJsonObject(), format.getValue(), "", 0, fields, Set.of(format.getValue() + "#"));
                } catch (IOException | RuntimeException e) {
                    // One component the extract cannot read is not the end of the others; it is missing from this format
                    skipped.add(kind + " " + format.getKey() + " " + component.getKey() + ": " + e.getMessage());
                    continue;
                }
                JsonObject definition = new JsonObject();
                JsonObject root = fields.remove("");
                if (forbidden.contains(component.getKey())) {
                    root.addProperty("deprecated", true);
                }
                definition.add("root", root);
                JsonObject paths = new JsonObject();
                fields.forEach(paths::add);
                definition.add("fields", paths);
                JsonArray definitions = byComponent.computeIfAbsent(component.getKey(), k -> new JsonArray());
                JsonObject same = null;
                for (JsonElement other : definitions) {
                    if (other.getAsJsonObject().get("root").equals(definition.get("root"))
                        && other.getAsJsonObject().get("fields").equals(definition.get("fields"))) {
                        same = other.getAsJsonObject();
                    }
                }
                if (same == null) {
                    same = new JsonObject();
                    same.add("formats", new JsonArray());
                    same.add("root", definition.get("root"));
                    same.add("fields", definition.get("fields"));
                    definitions.add(same);
                }
                same.getAsJsonArray("formats").add(format.getKey());
            }
        }
        JsonObject result = new JsonObject();
        byComponent.forEach(result::add);
        return result;
    }

    /**
     * The components the document around the entry point forbids ({@code Blocks.json} of the same format:
     * {@code propertyNames} {@code ^(?!(minecraft:a|minecraft:b)$)}): BDS rejects them, which the extract records as deprecated.
     */
    private Set<String> forbidden(String kind, Path entry) throws IOException {
        Path format = entry.getParent();
        Path document = kind.equals("block") ? format.getParent().getParent().resolve("block").resolve(format.getFileName()).resolve("Blocks.json")
            : kind.equals("item") ? format.resolve("ItemDocument.json") : null;
        Set<String> names = new LinkedHashSet<>();
        if (document != null && Files.isRegularFile(document)) {
            JsonObject components = load(document).has("properties") && load(document).getAsJsonObject("properties").has("components")
                ? load(document).getAsJsonObject("properties").getAsJsonObject("components") : new JsonObject();
            if (components.has("propertyNames") && components.getAsJsonObject("propertyNames").has("pattern")) {
                Matcher m = FORBIDDEN.matcher(components.getAsJsonObject("propertyNames").get("pattern").getAsString());
                if (m.matches() && !m.group(1).isEmpty()) {
                    names.addAll(List.of(m.group(1).split("\\|")));
                }
            }
        }
        return names;
    }

    /** Adds what the schema {@code node} says at {@code path}, then goes into its references, alternatives and members. */
    private void visit(JsonObject node, Path base, String path, int depth, Map<String, JsonObject> fields, Set<String> stack) throws IOException {
        if (depth > MAX_DEPTH) {
            throw new IOException("schema nesting deeper than " + MAX_DEPTH + " at '" + path + "' in " + rel(base));
        }
        node.keySet().stream().filter(k -> !KNOWN.contains(k) && !k.startsWith("x-") && !k.startsWith("$")).forEach(unhandled::add);
        JsonObject facets = fields.computeIfAbsent(path, p -> new JsonObject());
        if (node.has("type")) {
            for (JsonElement type : node.get("type").isJsonArray() ? node.getAsJsonArray("type").asList() : List.of(node.get("type"))) {
                if (!type.getAsString().equals("null")) {
                    union(facets, "types", type);
                }
            }
        }
        if (node.has("enum")) {
            node.getAsJsonArray("enum").forEach(value -> union(facets, "enum", value));
        }
        for (String key : GROUP) {
            if (node.has(key) && !node.get(key).isJsonNull() && !facets.has(key)) {
                facets.add(key, node.get(key));
            }
        }
        for (String key : SCALARS) {
            if (node.has(key) && !node.get(key).isJsonNull() && !facets.has(key)) {
                facets.add(key, node.get(key));
            }
        }
        if (node.has("x-underlying-type") && !facets.has("underlyingType")) {
            facets.add("underlyingType", node.get("x-underlying-type"));
        }
        if (node.has("x-runtime-constraint-description") && !facets.has("runtimeConstraint")) {
            facets.add("runtimeConstraint", node.get("x-runtime-constraint-description"));
        }
        if (node.has("deprecated") && node.get("deprecated").getAsBoolean()) {
            facets.addProperty("deprecated", true);
        }
        if (node.has("$ref")) {
            Reference target = resolve(base, node.get("$ref").getAsString());
            // A reference back into a schema being read is a recursive type: its members were already added
            if (!stack.contains(target.key())) {
                Set<String> inner = new HashSet<>(stack);
                inner.add(target.key());
                visit(target.node(), target.file(), path, depth + 1, fields, inner);
            }
        }
        List<Map<String, JsonObject>> alternatives = new ArrayList<>();
        for (String keyword : List.of("oneOf", "anyOf")) {
            if (node.has(keyword)) {
                for (JsonElement alternative : node.getAsJsonArray(keyword)) {
                    Map<String, JsonObject> own = new LinkedHashMap<>();
                    visit(alternative.getAsJsonObject(), base, path, depth + 1, own, stack);
                    alternatives.add(own);
                }
            }
        }
        if (!alternatives.isEmpty()) {
            combine(fields, alternatives, path);
        }
        if (node.has("properties")) {
            for (var member : node.getAsJsonObject("properties").entrySet()) {
                visit(member.getValue().getAsJsonObject(), base, join(path, member.getKey()), depth + 1, fields, stack);
            }
        }
        if (node.has("required")) {
            node.getAsJsonArray("required").forEach(name ->
                fields.computeIfAbsent(join(path, name.getAsString()), p -> new JsonObject()).addProperty("required", true));
        }
        if (node.has("items")) {
            for (JsonElement item : node.get("items").isJsonArray() ? node.getAsJsonArray("items").asList() : List.of(node.get("items"))) {
                visit(item.getAsJsonObject(), base, path + "[]", depth + 1, fields, stack);
            }
        }
        if (node.has("additionalProperties") && node.get("additionalProperties").isJsonObject()) {
            visit(node.getAsJsonObject("additionalProperties"), base, path + "{}", depth + 1, fields, stack);
        }
    }

    /** Puts what alternatives said into {@code fields}, as the class comment describes. */
    private static void combine(Map<String, JsonObject> fields, List<Map<String, JsonObject>> alternatives, String path) {
        // The alternatives that are objects: a member they do not all require is optional in some
        List<Map<String, JsonObject>> objects = alternatives.stream()
            .filter(a -> a.containsKey(path) && a.get(path).has("types") && a.get(path).getAsJsonArray("types").contains(new com.google.gson.JsonPrimitive("object")))
            .toList();
        String prefix = path.isEmpty() ? "" : path + ".";
        Set<String> paths = new LinkedHashSet<>();
        alternatives.forEach(alternative -> paths.addAll(alternative.keySet()));
        for (String member : paths) {
            List<JsonObject> having = alternatives.stream().map(a -> a.get(member)).filter(f -> f != null).toList();
            JsonObject target = fields.computeIfAbsent(member, p -> new JsonObject());
            boolean grouped = GROUP.stream().anyMatch(target::has);
            for (JsonObject facets : having) {
                if (facets.has("types")) {
                    facets.getAsJsonArray("types").forEach(type -> union(target, "types", type));
                }
                if (facets.has("enum")) {
                    facets.getAsJsonArray("enum").forEach(value -> union(target, "enum", value));
                    if (facets.has("types")) {
                        facets.getAsJsonArray("types").forEach(type -> union(target, "enumTypes", type));
                    }
                }
                if (!grouped && GROUP.stream().anyMatch(facets::has)) {
                    GROUP.stream().filter(facets::has).forEach(key -> target.add(key, facets.get(key)));
                    grouped = true;
                }
                for (String key : List.of("minLength", "maxLength", "minItems", "maxItems", "maxProperties", "pattern", "multipleOf", "underlyingType", "runtimeConstraint")) {
                    if (facets.has(key) && !target.has(key)) {
                        target.add(key, facets.get(key));
                    }
                }
                if (facets.has("deprecated")) {
                    target.addProperty("deprecated", true);
                }
            }
            // Direct members count against every object alternative; deeper ones against those that have them
            boolean direct = member.startsWith(prefix) && member.substring(prefix.length()).matches("[^.\\[{]+") && !objects.isEmpty();
            long required = (direct ? objects.stream().map(a -> a.get(member)) : having.stream()).filter(f -> f != null && f.has("required")).count();
            long of = direct ? objects.size() : having.size();
            if (required == of && required > 0) {
                target.addProperty("required", true);
            } else if (required > 0) {
                target.addProperty("requiredInSome", true);
            }
        }
    }

    private static String join(String path, String name) {
        return path.isEmpty() ? name : path + "." + name;
    }

    private static void union(JsonObject facets, String key, JsonElement value) {
        JsonArray values = facets.has(key) ? facets.getAsJsonArray(key) : new JsonArray();
        if (!values.contains(value)) {
            values.add(value);
        }
        facets.add(key, values);
    }

    private String rel(Path file) {
        return server.relativize(file).toString().replace('\\', '/');
    }

    /** What a {@code $ref} points to: the schema {@code node}, in {@code file}, named {@code key} (file and fragment). */
    private record Reference(Path file, JsonObject node, String key) {
    }

    /**
     * A {@code $ref} is a file ({@code Collision Box.json}), a fragment of the file it is in ({@code #/definitions/123};
     * BDS 1.26.36.1 writes all block components into one file this way) or a fragment of another file.
     */
    private Reference resolve(Path base, String ref) throws IOException {
        int hash = ref.indexOf('#');
        String name = hash < 0 ? ref : ref.substring(0, hash);
        String fragment = hash < 0 ? "" : ref.substring(hash + 1);
        Path file = base;
        if (!name.isEmpty()) {
            file = base.getParent().resolve(URLDecoder.decode(name.replace("+", "%2B"), StandardCharsets.UTF_8)).normalize();
            if (!Files.isRegularFile(file)) {
                throw new IOException("the $ref " + ref + " in " + rel(base) + " points to a file that is not there");
            }
        }
        JsonElement node = load(file);
        if (!fragment.isEmpty()) {
            if (!fragment.startsWith("/")) {
                throw new IOException("the $ref " + ref + " in " + rel(base) + " is not a JSON pointer");
            }
            for (String part : fragment.substring(1).split("/")) {
                String key = URLDecoder.decode(part.replace("+", "%2B"), StandardCharsets.UTF_8).replace("~1", "/").replace("~0", "~");
                node = node.isJsonObject() ? node.getAsJsonObject().get(key) : null;
                if (node == null) {
                    throw new IOException("the $ref " + ref + " in " + rel(base) + " points to a definition that is not there");
                }
            }
        }
        if (!node.isJsonObject()) {
            throw new IOException("the $ref " + ref + " in " + rel(base) + " does not point to a schema object");
        }
        return new Reference(file, node.getAsJsonObject(), file + "#" + fragment);
    }

    private JsonObject load(Path file) throws IOException {
        JsonObject cached = files.get(file);
        if (cached == null) {
            // The files are UTF-8, some with a byte order mark
            cached = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8).replace(String.valueOf((char) 0xFEFF), "")).getAsJsonObject();
            files.put(file, cached);
        }
        return cached;
    }
}
