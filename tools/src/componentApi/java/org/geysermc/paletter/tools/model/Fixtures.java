package org.geysermc.paletter.tools.model;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.geysermc.paletter.tools.codegen.component.BdsErrata;
import org.geysermc.paletter.tools.model.Model.Component;
import org.geysermc.paletter.tools.model.Model.Field;
import org.geysermc.paletter.tools.model.Model.JType;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * {@code data/model/fixtures.json}: the hand-written inputs of the add-on generator (errata, content samples,
 * companions), with the generated {@code bds-feedback.json} and {@code bds-keys.json}. See the file's comments.
 */
public final class Fixtures {
    /** The generated result of the key probe, in {@code data/model}. */
    public static final String KEYS_FILE = "bds-keys.json";

    public final JsonObject json;
    public final String formatVersion;
    public final JsonObject filler;

    /** {@code bds-feedback.json} (generated from the last capture), or empty. */
    public final JsonObject feedback;

    /** {@code bds-keys.json} (generated by the key probe of {@code spec-capture}), or empty. */
    public final JsonObject keys;

    /** What BDS's own schemas say ({@code data/bds/<build>/schema.json}); first in every merge. None unless a caller opts in. */
    private final Schema schema;

    /** {@code data/bds}, where the schema of a build is looked up. */
    private final Path bdsData;

    private final boolean schemaOn;

    private Fixtures(JsonObject json, JsonObject feedback, JsonObject keys, Schema schema, Path bdsData, boolean schemaOn) {
        this.json = json;
        this.schemaOn = schemaOn;
        this.feedback = feedback;
        this.keys = keys;
        this.schema = schema;
        this.bdsData = bdsData;
        this.formatVersion = json.get("formatVersion").getAsString();
        this.filler = json.getAsJsonObject("filler");
    }

    /**
     * Whether the model takes BDS's schema (full enums, limits, fields and components): the add-on, the spec capture, the mapping
     * inference, the coverage and the component API all follow this one switch, so there is one model. Off until every build is
     * captured again with the add-on the schema shapes; that change flips it together with the new data.
     */
    public static final boolean SCHEMA_IN_ADDON = false;

    public static Fixtures read(Path model) throws IOException {
        return read(model, SCHEMA_IN_ADDON);
    }

    /** {@link #read(Path)} with the switch given (for tests of both settings). */
    public static Fixtures read(Path model, boolean schemaInAddon) throws IOException {
        Path bdsData = model.resolveSibling("bds");
        return new Fixtures(JsonParser.parseString(Files.readString(model.resolve("fixtures.json"), StandardCharsets.UTF_8)).getAsJsonObject(),
            optional(model.resolve("bds-feedback.json")), optional(model.resolve(KEYS_FILE)),
            schemaInAddon ? Schema.newest(bdsData, null) : Schema.NONE, bdsData, schemaInAddon);
    }

    /**
     * The fixtures for an add-on run on one BDS build: the probed keys only if the probe ran on that build. A key a newer
     * build accepts can be one an older build refuses, and a refused key in a base makes BDS reject every variant.
     */
    public Fixtures forBuild(String bdsVersion) {
        boolean probedThere = keys.has("bdsVersion") && keys.get("bdsVersion").getAsString().equals(bdsVersion);
        return new Fixtures(json, feedback, probedThere ? keys : new JsonObject(), schema, bdsData, schemaOn);
    }

    /**
     * With the switch on, the fixtures with the newest committed schema that is not newer than the build (any if it is null),
     * none if there is none or it cannot be read; with it off, the same fixtures.
     */
    public Fixtures withNewestSchema(String bdsVersion) {
        return schemaOn ? new Fixtures(json, feedback, keys, Schema.newest(bdsData, bdsVersion), bdsData, true) : this;
    }

    /** The same fixtures for an add-on of this format version: the schema's newest format at or below it counts. */
    public Fixtures forFormat(String formatVersion) {
        return new Fixtures(json, feedback, keys, schema.forFormat(formatVersion), bdsData, schemaOn);
    }

    /** The build of the schema these fixtures merge, or null. */
    public String schemaBuild() {
        return schema == Schema.NONE ? null : schema.build();
    }

    /** What the content log said that the schema contradicts (see {@link Schema#disputed}); the add-on tests both. */
    public List<String> disputed(String component, String path) {
        List<String> facts = new ArrayList<>();
        if (feedback.has(component) && feedback.getAsJsonObject(component).has(path)) {
            feedback.getAsJsonObject(component).getAsJsonArray(path).forEach(f -> facts.add(f.getAsString()));
        }
        return schema.disputed(component, path, facts);
    }

    private static JsonObject optional(Path file) throws IOException {
        return Files.exists(file) ? JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject() : new JsonObject();
    }

    /**
     * What BDS said about a field: the schema's limits, values and required first, then in the last capture: unknown, required,
     * array, object, range a b, max n, min n, minItems n, ... (what the schema states itself is not repeated from the capture).
     */
    public List<String> facts(String component, String path) {
        List<String> facts = new ArrayList<>();
        if (feedback.has(component) && feedback.getAsJsonObject(component).has(path)) {
            feedback.getAsJsonObject(component).getAsJsonArray(path).forEach(f -> facts.add(f.getAsString()));
        }
        return schema.facts(component, path, facts);
    }

    public boolean fact(String component, String path, String fact) {
        return facts(component, path).stream().anyMatch(f -> f.equals(fact) || f.startsWith(fact + " "));
    }

    /** Groups of sibling fields of which an object may hold only one (block descriptors: name or tags). */
    public List<List<String>> exclusive() {
        List<List<String>> groups = new ArrayList<>();
        if (json.has("exclusive")) {
            json.getAsJsonArray("exclusive").forEach(g -> groups.add(g.getAsJsonArray().asList().stream().map(JsonElement::getAsString).toList()));
        }
        return groups;
    }

    /**
     * Sibling values a field needs when it is set ("blocks_to_corner_with" needs corner_and_cardinal_direction); by
     * {@code <component>:<path>}, then by the field's name (the same key of every face of material_instances).
     */
    public JsonObject together(String component, String path) {
        JsonObject together = json.has("together") ? json.getAsJsonObject("together") : new JsonObject();
        for (String key : List.of(component + ":" + path, component + ":" + path.substring(path.lastIndexOf('.') + 1))) {
            if (together.has(key)) {
                return together.getAsJsonObject(key);
            }
        }
        return new JsonObject();
    }

    public List<JsonObject> errata() {
        List<JsonObject> errata = new ArrayList<>();
        json.getAsJsonArray("errata").forEach(e -> errata.add(e.getAsJsonObject()));
        return errata;
    }

    /** Companion components a component needs, as {@code minecraft:x -> value}. */
    public JsonObject requires(String component) {
        JsonObject requires = json.getAsJsonObject("requires");
        return requires.has(component) ? requires.getAsJsonObject(component) : new JsonObject();
    }

    /** Extra description entries (e.g. states) for the variants of a component. */
    public JsonObject context(String component) {
        JsonObject context = json.getAsJsonObject("context");
        return context.has(component) ? context.getAsJsonObject(component) : new JsonObject();
    }

    public String skip(String component, String path) {
        JsonObject skip = json.getAsJsonObject("skip");
        String key = path == null ? component : component + ":" + path;
        return skip.has(key) ? skip.get(key).getAsString() : null;
    }

    /** Whether there is a {@code scriptComponents} table; without one the add-on has no script and no script variants. */
    public boolean hasScriptComponents() {
        return json.has("scriptComponents");
    }

    /** The script custom components of the spec add-on ({@code scriptComponents}): the module version, the components, the variants. */
    public JsonObject scriptComponents() {
        return json.getAsJsonObject("scriptComponents");
    }

    /** The variants that bind script custom components under a component (by id), in file order; empty for most. */
    public List<JsonObject> scriptVariants(String component) {
        List<JsonObject> out = new ArrayList<>();
        if (!hasScriptComponents()) {
            return out;
        }
        JsonObject variants = scriptComponents().getAsJsonObject("variants");
        if (variants.has(component)) {
            variants.getAsJsonArray(component).forEach(v -> out.add(v.getAsJsonObject()));
        }
        return out;
    }

    /** Fields only set in their own variants, never in a base (a docs name BDS does not take would reject every variant). */
    public boolean probeOnly(String component, String path) {
        return json.has("probeOnly") && json.getAsJsonArray("probeOnly").contains(new com.google.gson.JsonPrimitive(component + ":" + path));
    }

    /** A sample value: by {@code <component>:<path>}, then by field name; null if none. */
    public JsonElement sample(String component, String path, String name) {
        JsonObject samples = json.getAsJsonObject("samples");
        if (samples.has(component + ":" + path)) {
            return samples.get(component + ":" + path);
        }
        return name != null && samples.has(name) ? samples.get(name) : null;
    }

    /** A second valid value of a reference field (by '<component>:<path>', then field name), or null. */
    public JsonElement alternative(String component, String path, String name) {
        JsonObject alternatives = json.has("alternatives") ? json.getAsJsonObject("alternatives") : new JsonObject();
        if (alternatives.has(component + ":" + path)) {
            return alternatives.get(component + ":" + path);
        }
        return name != null && alternatives.has(name) ? alternatives.get(name) : null;
    }

    /** Further values of a map's elements, each tried in a map of its own (by '<component>:<path>', then field name). */
    public List<JsonElement> mapValues(String component, String path, String name) {
        JsonObject values = json.has("mapValues") ? json.getAsJsonObject("mapValues") : new JsonObject();
        JsonElement list = values.has(component + ":" + path) ? values.get(component + ":" + path)
            : name != null && values.has(name) ? values.get(name) : null;
        return list == null ? List.of() : list.getAsJsonArray().asList();
    }

    /**
     * Further strings of a field that no enum lists (by '<component>:<path>'), each tried as a value of its own: names the
     * hand tables of {@code Transforms} hold, which BDS's messages do not list. Probes, not facts: a name BDS rejects says so
     * in the content log, and only an accepted one is evidence.
     */
    public List<JsonElement> probeValues(String component, String path) {
        JsonObject values = json.has("probeValues") ? json.getAsJsonObject("probeValues") : new JsonObject();
        return values.has(component + ":" + path) ? values.getAsJsonArray(component + ":" + path).asList() : List.of();
    }

    /**
     * Block descriptors ({@code name}, {@code states}) to try in every field that is one: real vanilla blocks with state
     * values of each JSON type, so BDS's registry says which it takes and how it sends them.
     */
    public List<JsonObject> descriptorValues() {
        List<JsonObject> values = new ArrayList<>();
        if (json.has("descriptorValues")) {
            json.getAsJsonObject("descriptorValues").getAsJsonArray("values").forEach(d -> values.add(d.getAsJsonObject()));
        }
        return values;
    }

    public String mapKey(String component, String path, String name) {
        JsonObject keys = json.getAsJsonObject("mapKeys");
        if (keys.has(component + ":" + path)) {
            return keys.get(component + ":" + path).getAsString();
        }
        if (name != null && keys.has(name)) {
            return keys.get(name).getAsString();
        }
        return keys.get("default").getAsString();
    }

    /**
     * The model every tool works from (the add-on generator, the mapping inference and the component API generator): the docs
     * with the errata applied. Types, forms and fields are only ever added. First the hand written errata: an erratum's
     * types come first (they are what BDS takes), the documented ones stay after them (each capture asks BDS again), a field
     * an erratum makes a string gets the values its docs text lists ({@link DocValues}; the docs parser skips them where the
     * docs call the field a boolean), and a field only an erratum names gets its reason as docs text
     * ({@code (erratum) ...}). Then what BDS said ({@link BdsErrata}: the types its content log demands, the keys the probe
     * found it accepts). Last and first in precedence, BDS's own schema ({@link Schema#apply}): the enum values, limits and
     * required of every field it has, and the fields and components the docs lack. So the order of precedence is schema,
     * feedback, errata, docs.
     */
    public Model apply(Model model) {
        Map<String, Component> components = new LinkedHashMap<>();
        model.components().forEach(c -> components.put(c.id(), c));
        for (JsonObject erratum : errata()) {
            String id = erratum.get("component").getAsString();
            Component c = components.get(id);
            if (c == null) {
                throw new IllegalStateException("Erratum for unknown component " + id);
            }
            List<JType> forms = new ArrayList<>(c.forms());
            List<Field> fields = new ArrayList<>(c.fields());
            if (erratum.has("forms")) {
                int before = forms.size();
                erratum.getAsJsonArray("forms").forEach(f -> {
                    JType type = parseType(f.getAsString());
                    if (forms.stream().noneMatch(form -> form.toString().equals(type.toString()))) {
                        forms.add(type);
                    }
                });
                if (forms.size() == before) {
                    throw new IllegalStateException("Erratum of " + id + " adds no form the docs lack: it is stale, remove it");
                }
            }
            if (erratum.has("path")) {
                String path = erratum.get("path").getAsString();
                List<JType> types = new ArrayList<>();
                erratum.getAsJsonArray("types").forEach(t -> types.add(parseType(t.getAsString())));
                Field existing = c.field(path);
                if (existing == null) {
                    if (!parentExists(path, fields)) {
                        throw new IllegalStateException("Erratum of " + id + " names " + path + ", whose parent is no field of the component: "
                            + "a mistyped path would add a new field instead of correcting one");
                    }
                    fields.add(new Field(path, types, null, false, List.of(), null, null, List.of(), "(erratum) " + erratum.get("why").getAsString()));
                } else {
                    List<JType> merged = new ArrayList<>(types);
                    existing.types().stream().filter(t -> merged.stream().noneMatch(m -> m.toString().equals(t.toString()))).forEach(merged::add);
                    // the merge keeps every documented type, so it is longer only if the erratum names one the docs lack: the same
                    // types in another order are no change
                    if (merged.size() == existing.types().size()) {
                        throw new IllegalStateException("Erratum of " + id + " for " + path + " adds no type the docs lack: it is stale, remove it");
                    }
                    List<JsonElement> values = existing.enumValues();
                    if (values.isEmpty() && types.stream().anyMatch(t -> t.type().equals("string"))) {
                        values = DocValues.valuesIn(existing.doc());
                    }
                    fields.set(fields.indexOf(existing), new Field(path, merged, existing.defaultValue(), existing.required(), values,
                        existing.range(), existing.minFormatVersion(), existing.examples(), existing.doc()));
                }
            }
            components.put(id, new Component(c.id(), c.kind(), c.category(), c.name(), c.status(), c.doc(), c.page(), c.minFormatVersion(),
                c.experiments(), forms, fields, c.notes()));
        }
        Model errata = new Model(model.source(), model.commit(), model.license(), model.lists(), new ArrayList<>(components.values()), model.formatNotes());
        JsonObject json = Model.GSON.toJsonTree(errata).getAsJsonObject();
        BdsErrata.apply(json, feedback, keys);
        return schema.apply(Model.GSON.fromJson(json, Model.class));
    }

    /** The sections of fixtures.json and api.json whose keys start with a component id ({@code item:minecraft:food:path}). */
    private static final List<String> FIXTURE_SECTIONS = List.of("requires", "context", "skip", "together", "samples", "alternatives",
        "mapValues", "mapKeys", "probeOnly", "probeValues");
    private static final List<String> API_SECTIONS = List.of("rootLists", "forms", "types", "unions", "keyedExtras", "descriptors",
        "blockDescriptors", "fields", "typeNames", "standalone", "standalonePaths", "openEnums", "exclude", "handWritten", "classes",
        "optional", "noDefaults", "enums");

    /**
     * The hand input entries that name no component of the model, as {@code <file> <section>: <key>}. A renamed or removed
     * docs page would otherwise leave its entries in fixtures.json and api.json unread, with the generated output changing
     * silently. Keys that do not start with a component id ({@code block}, a bare field name, {@code default}) are skipped.
     */
    public static List<String> orphans(JsonObject fixtures, JsonObject api, java.util.Set<String> componentIds) {
        List<String> orphans = new ArrayList<>();
        collectOrphans("fixtures.json", FIXTURE_SECTIONS, fixtures, componentIds, orphans);
        collectOrphans("api.json", API_SECTIONS, api, componentIds, orphans);
        return orphans;
    }

    private static void collectOrphans(String file, List<String> sections, JsonObject json, java.util.Set<String> ids, List<String> out) {
        for (String section : sections) {
            if (!json.has(section)) {
                continue;
            }
            List<String> keys = json.get(section).isJsonArray()
                ? json.getAsJsonArray(section).asList().stream().map(JsonElement::getAsString).toList()
                : List.copyOf(json.getAsJsonObject(section).keySet());
            for (String key : keys) {
                boolean component = key.startsWith("item:") || key.startsWith("block:");
                if (component && ids.stream().noneMatch(id -> key.equals(id) || key.startsWith(id + ":"))) {
                    out.add(file + " " + section + ": " + key);
                }
            }
        }
    }

    /** Whether the parent of a path is a field, or the path is top level or an element of a list ({@code [].origin}). */
    private static boolean parentExists(String path, List<Field> fields) {
        int cut = path.lastIndexOf('.');
        String parent = cut < 0 ? "" : path.substring(0, cut);
        if (parent.isEmpty() || parent.equals("[]")) {
            return true;
        }
        String field = parent.endsWith("[]") ? parent.substring(0, parent.length() - 2) : parent;
        return fields.stream().anyMatch(f -> f.path().equals(field));
    }

    /** {@code integer}, {@code array<object>}, {@code map<string>}, ... */
    public static JType parseType(String text) {
        int open = text.indexOf('<');
        if (open < 0) {
            return JType.of(text);
        }
        return new JType(text.substring(0, open), parseType(text.substring(open + 1, text.length() - 1)), null, null);
    }
}
