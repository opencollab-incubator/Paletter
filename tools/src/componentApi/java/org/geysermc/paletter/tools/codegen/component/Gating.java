package org.geysermc.paletter.tools.codegen.component;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;

/**
 * What a BDS build does with the components the creator docs mark as experiment-gated, in a world without experiments
 * ({@code data/bds/<build>/spec-gating/gating.json}, written by {@code spec-capture --gating}). The component generator turns it
 * into the BDS-verified part of the {@code @BedrockExperiment} Javadoc. The capture is not essential: a build without the file
 * leaves the gating of its components unverified, never a failure.
 */
public final class Gating {
    private Gating() {
    }

    /** Where the file is, relative to a build directory. */
    public static final String FILE = "spec-gating/gating.json";
    public static final String ACCEPTED = "accepted";
    public static final String REJECTED = "rejected";
    /** BDS took the component's file, and sent the same as without the component. */
    public static final String IGNORED = "ignored";

    /**
     * @param build   the BDS build
     * @param without what BDS did with the component in a world without experiments: accepted, rejected or ignored
     * @param with    the same in the spec capture, whose world has the experiments on (accepted or rejected), or null if that capture has none
     */
    public record Result(String build, String without, String with) {
        /** Whether the build shows the gating: BDS does not take the component without experiments, but does not reject it with them. */
        public boolean gated() {
            return !without.equals(ACCEPTED) && !rejectedAnyway();
        }

        /** Whether BDS rejects the component with the experiments on, so the capture says nothing of its gating. */
        public boolean rejectedAnyway() {
            return REJECTED.equals(with);
        }
    }

    /** One component of a build's file, see {@link Result}. */
    public record Entry(String component, String without, String with) {
    }

    /**
     * The marked file of one build.
     *
     * @param experiments what start game of the world reported as on: for a world without experiments only what BDS always has on
     */
    public static JsonObject render(String build, int protocol, List<String> experiments, List<Entry> entries) {
        JsonObject json = new JsonObject();
        json.addProperty("_generated", "Generated by `./gradlew :tools:run --args=\"spec-capture --gating\"`: what BDS " + build
            + " does with the components the creator docs mark as experiment-gated, in a world without experiments (`without`: accepted, "
            + "rejected or ignored) and in the spec capture, whose world has them on (`with`). Do not edit.");
        json.addProperty("bdsVersion", build);
        json.addProperty("protocol", protocol);
        JsonArray echoed = new JsonArray();
        experiments.forEach(echoed::add);
        json.add("experiments", echoed);
        JsonObject components = new JsonObject();
        for (Entry entry : entries.stream().sorted(Comparator.comparing(Entry::component)).toList()) {
            JsonObject value = new JsonObject();
            value.addProperty("without", entry.without());
            if (entry.with() != null) {
                value.addProperty("with", entry.with());
            }
            components.add(entry.component(), value);
        }
        json.add("components", components);
        return json;
    }

    /** @return the results per component id, the oldest build first; empty without captures */
    public static Map<String, List<Result>> read(Path bds) throws IOException {
        Map<String, List<Result>> results = new TreeMap<>();
        if (bds == null || !Files.isDirectory(bds)) {
            return results;
        }
        List<Path> files;
        try (Stream<Path> builds = Files.list(bds)) {
            files = builds.map(b -> b.resolve(FILE)).filter(Files::isRegularFile)
                .sorted((a, b) -> Main.compareVersions(build(a), build(b))).toList();
        }
        for (Path file : files) {
            JsonObject json = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject();
            json.getAsJsonObject("components").entrySet().forEach(e -> {
                JsonObject value = e.getValue().getAsJsonObject();
                results.computeIfAbsent(e.getKey(), k -> new ArrayList<>())
                    .add(new Result(build(file), value.get("without").getAsString(), value.has("with") ? value.get("with").getAsString() : null));
            });
        }
        return results;
    }

    private static String build(Path file) {
        return file.getParent().getParent().getFileName().toString();
    }

    /** @return the components BDS rejects even with experiments on in every captured build, which no gating says anything of */
    public static List<String> rejectedEverywhere(Map<String, List<Result>> results) {
        return results.entrySet().stream().filter(e -> e.getValue().stream().allMatch(Result::rejectedAnyway)).map(Map.Entry::getKey).toList();
    }
}
