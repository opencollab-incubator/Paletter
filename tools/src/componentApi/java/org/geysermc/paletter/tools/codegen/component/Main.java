package org.geysermc.paletter.tools.codegen.component;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * {@code generate --root DIR} writes the component API from {@code data/model}, and the behaviour keys from
 * {@link BehaviourKeys}, {@code mappings.json} and the newest behaviour probe capture ({@link BehaviourSource}), checked against
 * the newest BDS captures ({@link BehaviourEvidence});
 * {@code check --root DIR} fails if the committed sources differ (and lists the files).
 */
public final class Main {
    /** Directories whose generated files this generator owns (a file with the generator header that it no longer writes is deleted). */
    static final List<String> OWNED = List.of("org/geysermc/paletter/item/component", "org/geysermc/paletter/block/component",
        "org/geysermc/paletter/internal/component", "org/geysermc/paletter/behaviour", "org/geysermc/paletter/internal/behaviour");

    /** How the header of every generated file starts (after {@code //}): also how stale files of this generator are recognized. */
    static final String GENERATOR = "Generated by :tools:generateComponentApi";

    private Main() {
    }

    public static void main(String[] args) throws Exception {
        Path root = Path.of(".");
        Path sources = null;
        for (int i = 1; i < args.length; i++) {
            if (args[i].equals("--root")) {
                root = Path.of(args[++i]);
            } else if (args[i].equals("--sources")) {
                sources = Path.of(args[++i]);
            }
        }
        boolean check = args.length > 0 && args[0].equals("check");
        int changed = run(root, sources == null ? root.resolve("paletter/src/generated/java") : sources, check);
        if (check && changed > 0) {
            System.err.println(changed + " generated component API files are stale: run ./gradlew :tools:generateComponentApi");
            System.exit(1);
        }
    }

    /** @return the number of files that differ (written unless {@code check}) */
    static int run(Path root, Path sources, boolean check) throws IOException {
        Path model = root.resolve("data/model");
        ComponentGenerator.Inputs inputs = ComponentGenerator.read(model, version(root), context(root));
        Map<String, String> files = ComponentGenerator.generate(inputs);
        Path probe = newestProbe(root);
        files.putAll(BehaviourSource.generate(BehaviourKeys.KEYS, inputs.mappings(), probe == null ? null
            : JsonParser.parseString(Files.readString(probe, StandardCharsets.UTF_8)).getAsJsonObject(),
            probe == null ? "" : "data/bds/" + probe.getParent().getParent().getFileName() + "/behaviour-probe/capture.json",
            BehaviourEvidence.read(root)));
        int changed = 0;
        for (Map.Entry<String, String> file : files.entrySet()) {
            Path path = sources.resolve(file.getKey());
            String existing = Files.exists(path) ? Files.readString(path, StandardCharsets.UTF_8).replace("\r\n", "\n") : null;
            if (!file.getValue().equals(existing)) {
                changed++;
                System.out.println((check ? "stale: " : "wrote: ") + file.getKey());
                if (!check) {
                    Files.createDirectories(path.getParent());
                    Files.writeString(path, file.getValue(), StandardCharsets.UTF_8);
                }
            }
        }
        for (String dir : OWNED) {
            Path d = sources.resolve(dir);
            if (!Files.isDirectory(d)) {
                continue;
            }
            try (Stream<Path> list = Files.list(d)) {
                for (Path p : list.filter(Files::isRegularFile).toList()) {
                    String rel = sources.relativize(p).toString().replace('\\', '/');
                    if (!files.containsKey(rel) && Files.readString(p, StandardCharsets.UTF_8).startsWith("// " + GENERATOR)) {
                        changed++;
                        System.out.println((check ? "stale (no longer generated): " : "deleted: ") + rel);
                        if (!check) {
                            Files.delete(p);
                        }
                    }
                }
            }
        }
        return changed;
    }

    /**
     * The names the generated API must keep unique and the experiment toggles of the captured servers.
     *
     * @return the public types next to the generated ones (every source file outside {@code internal} that this generator
     *         does not write itself: hand-written ones and the constants), and the toggle ids by the experiment name the
     *         creator docs use
     */
    static ComponentGenerator.Context context(Path root) throws IOException {
        Set<String> reserved = new TreeSet<>();
        for (String dir : List.of("paletter/src/main/java", "paletter/src/generated/java")) {
            Path base = root.resolve(dir);
            if (!Files.isDirectory(base)) {
                continue;
            }
            try (Stream<Path> files = Files.walk(base)) {
                for (Path file : files.filter(f -> f.toString().endsWith(".java")).toList()) {
                    String rel = base.relativize(file).toString().replace('\\', '/');
                    String name = file.getFileName().toString();
                    if (!rel.startsWith("org/geysermc/paletter/internal/") && !name.equals("package-info.java") && !name.equals("module-info.java")
                        && !Files.readString(file, StandardCharsets.UTF_8).startsWith("// " + GENERATOR)) {
                        reserved.add(name.substring(0, name.length() - ".java".length()));
                    }
                }
            }
        }
        return new ComponentGenerator.Context(reserved, toggleNames(root.resolve("data/bds")));
    }

    /**
     * @return toggle id by name, from every {@code data/bds/<build>/experiments.json}: the names of the current toggles are
     *         what the creator docs call them. A name of two ids is an error: nothing could decide between them.
     */
    static Map<String, String> toggleNames(Path bds) throws IOException {
        Map<String, String> names = new TreeMap<>();
        if (!Files.isDirectory(bds)) {
            return names;
        }
        try (Stream<Path> builds = Files.list(bds)) {
            for (Path file : builds.map(b -> b.resolve("experiments.json")).filter(Files::isRegularFile).sorted().toList()) {
                JsonObject toggles = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject().getAsJsonObject("toggles");
                for (Map.Entry<String, JsonElement> toggle : toggles.entrySet()) {
                    JsonObject value = toggle.getValue().getAsJsonObject();
                    if (value.has("name")) {
                        String other = names.put(value.get("name").getAsString(), toggle.getKey());
                        if (other != null && !other.equals(toggle.getKey())) {
                            throw new IllegalStateException("The experiment name \"" + value.get("name").getAsString() + "\" is " + other + " and "
                                + toggle.getKey() + " in the captures");
                        }
                    }
                }
            }
        }
        return names;
    }

    /** @return the {@code behaviour-probe/capture.json} of the newest BDS build under {@code data/bds}, or null if none has one */
    static Path newestProbe(Path root) throws IOException {
        Path bds = root.resolve("data/bds");
        if (!Files.isDirectory(bds)) {
            return null;
        }
        try (Stream<Path> builds = Files.list(bds)) {
            return builds.map(build -> build.resolve("behaviour-probe/capture.json")).filter(Files::isRegularFile)
                .max(Comparator.comparing(capture -> capture.getParent().getParent().getFileName().toString(), Main::compareVersions))
                .orElse(null);
        }
    }

    /** Compares dotted versions number by number ({@code 1.26.63.1} after {@code 1.26.9.0}). */
    static int compareVersions(String a, String b) {
        String[] x = a.split("\\.");
        String[] y = b.split("\\.");
        for (int i = 0; i < Math.max(x.length, y.length); i++) {
            int c = Integer.compare(i < x.length ? Integer.parseInt(x[i]) : 0, i < y.length ? Integer.parseInt(y[i]) : 0);
            if (c != 0) {
                return c;
            }
        }
        return 0;
    }

    static String version(Path root) throws IOException {
        Matcher m = Pattern.compile("version = \"([^\"]+)\"").matcher(Files.readString(root.resolve("build.gradle.kts")));
        if (!m.find()) {
            throw new IllegalStateException("no version in build.gradle.kts");
        }
        return m.group(1).replace("-SNAPSHOT", "");
    }
}
